    <div class="llm-question"><strong>开场问题：</strong>神经网络的输出为什么叫「概率」？——从频率到交叉熵损失。</div>

    <h2>提出问题</h2>
    <p>天气预报说「明天降雨概率 70%」，可第二天要么下雨、要么没下，哪来的 70%？这个数字其实描述的是<strong>长期频率</strong>：在所有相似天气的日子里，大约七成最后下了雨。概率不是对单独某一天的承诺，而是「重复很多次，某个结果占多大比例」。掷骰子掷 1000 次，数字 3 出现 168 次，就说「3 的概率约 0.168」。</p>

    <h2>最小方案：概率分布</h2>
    <p>AI 里常关心的是「所有可能结果各占多少」。比如语言模型输入「今天天气很」，它不会只蹦一个答案，而是给词表里<strong>每一个候选词都打分</strong>：好 34%、冷 21%、热 18%……这一整组数有两条铁律：<strong>每个都 ≥ 0，全部加起来正好 = 1</strong>。满足这两条的一组数就叫一个<strong>概率分布</strong>。这也顺带回答了本课标题：<strong>神经网络的输出之所以叫「概率」，是因为它吐出来的就是这样一组非负、加和为 1 的数</strong>。</p>

    <h2>发现不足：光有概率还不够</h2>
    <ul>
      <li>有了「谁各占多少」，还得问：一条消息到底带来多少「信息」？</li>
      <li>进一步，模型自己画出的概率分布 q 未必等于真实情况 p——拿这张可能画错的地图去面对真实世界，平均会多意外？</li>
    </ul>

    <h2>迭代</h2>
    <h3>信息量：越意外的消息越「值钱」</h3>
    <p>「太阳明天从东边升起」等于没说（概率≈1）；「楼下小卖部老板昨晚中了五百万」信息量爆炸（概率极小）。<strong>一件事越「出乎意料」，一旦成真带来的信息就越多。</strong>写成公式，事件 x 的信息量为 <code>I(x) = −log p(x)</code>。为什么偏偏是 <code>−log</code>？除了「概率越小、数值越大」，它还满足一条关键性质——<strong>两条互不相干消息的信息量应该能直接相加，而 log 恰好把「概率相乘」变成「信息相加」</strong>。检验三个极端：p=1（必然）→I=0；p=0.5（抛硬币）→I=1 比特；p=0.001（中奖）→I≈10 比特。底数取 2 单位是比特，深度学习常用自然对数、单位叫奈特。</p>
    <h3>熵：整个分布平均有多难猜</h3>
    <p>熵衡量「整件事整体上有多难预测」——把所有可能结果的意外程度按各自概率<strong>加权平均</strong>：<code>H(p) = −Σ p(x)log p(x)</code>。直觉看两枚硬币：公平硬币正反各半 H=1（最难猜）；灌铅硬币九成正面 H≈0.47（好猜）。<strong>均匀分布熵最大，确定性分布熵为 0</strong>。这解释了为什么 AI 猜词是有意义的事：如果每个字等概率出现，语言就是纯噪声、没法预测；真实语言熵不高不低——有规律可循（可预测），又留有选择（不无聊），「预测下一个词」才既非送分题也非无解题。</p>
    <h3>交叉熵：拿可能画错的地图去赌真实世界</h3>
    <p>熵衡量真实世界本身有多难猜，但 AI 里我们手上只有模型画的「地图」q。用模型 q 给出的「意外程度 −log q」按真实分布 p 加权平均，就叫<strong>交叉熵</strong>：<code>H(p,q) = −Σ p(x)log q(x)</code>。在猜词任务里真实答案是确定的（独热分布：p(猫)=1，其它全 0），求和里只有「猫」那一项活着，于是交叉熵塌缩成一句话：<code>−log(模型给正确答案的概率)</code>。模型越自信地答对，交叉熵越接近 0；把正确答案概率压低，交叉熵就冲高——正是理想的「错得多离谱」打分器。</p>

    <h2>总结</h2>
    <p>概率分布是对「所有可能结果各占多少」的完整描述（非负、加和为 1），这就是模型输出叫「概率」的原因。信息量和熵层层递进，最后得到交叉熵——当真实答案确定（独热）时塌缩成 <code>−log q(正确)</code>，天生就是完美的损失打分器，正是后面分类任务损失函数的来历。</p>
