    <div class="llm-question"><strong>开场问题：</strong>神经网络的每一层都在做「把一组数字变成另一组数字」的变换——这个操作用什么数学对象来表示？</div>

    <h2>提出问题</h2>
    <p>先把数学放一边。你盘下一家奶茶店，菜单上有 3 款招牌饮品，每款按自己的配方用到 4 种原料——茶叶、牛奶、糖、珍珠。比如珍珠奶茶＝2 茶＋1 奶＋0 糖＋3 珍珠。今天 4 种原料价格是 x₁、x₂、x₃、x₄，你想立刻算出每款饮品的成本是多少？答案很简单：把配方当权重，做加权求和。三款饮品就是三条加权求和——而现实中可能是几百款产品、上百种原料，神经网络里更是几百万个权重。把每条公式分开写太啰嗦了。</p>

    <h2>最小方案 · 一张配方表</h2>
    <p>把所有配方里的份数<strong>排成一张矩形表格</strong>，叫做<strong>矩阵</strong>。这张表是 3×4：3 行＝3 款饮品的配方，4 列＝4 种原料。矩阵用 <code>m × n</code> 描述大小：<strong>m 行、n 列</strong>。记住这个画面：<em>一行一份配方，一列一种原料</em>——后面所有矩阵运算都能退回这张表来理解。</p>

    <h2>矩阵乘向量：一行一次点积</h2>
    <p>假设今日原料价是「茶 1 元、奶 2 元、糖 1 元、珍珠 0 元」，写成列向量 <code>x = [1,2,1,0]</code>。矩阵乘法 <code>Wx</code> 的意思是：<strong>用 W 的每一行（配方）和 x（价格）做点积</strong>，结果拼成成本向量。一行 ①：2×1＋1×2＋0×1＋3×0＝4；行 ②、③ 同理，得到 <code>y = [4, 9, 4]</code>——珍珠奶茶 4 元、奶霸布丁 9 元、古早甜茶 4 元，一次矩阵乘法整张菜单一起算完。这正是矩阵的用处：<strong>把「同时做很多组加权求和」压成一个动作</strong>。神经网络每一层做的就是这一个动作，只是配方表大得多。</p>

    <h2>发现不足：维度必须匹配</h2>
    <ul>
      <li>W 有 n 列，x 就必须是 n 维，否则点积无从对齐——维度不符就完全无法计算。</li>
      <li>输出维度由 W 的行数 m 决定，即「从几维变到几维」由此确定。</li>
    </ul>

    <h2>迭代 · 维度规则</h2>
    <p>矩阵乘法的核心规则只有一条，记住形状就够了：<code>W(m×n) × x(n维) = y(m维)</code>。<strong>内层维度必须相等，外层维度决定结果</strong>。这个「从几维变到几维」的性质，是下一课《线性变换》的核心：矩阵不只是计算工具，它在几何上代表一次空间变换——旋转、缩放、压缩或拉伸。</p>

    <h2>总结</h2>
    <p>矩阵把多组权重整齐排列：每行是一组系数，每列对应一个输入。矩阵乘向量就是每行与 x 做点积，m 行产生 m 个结果。</p>
