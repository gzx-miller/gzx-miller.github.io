    <h2>函数作为一等值</h2>
    <p>
      高阶函数、柯里化、组合、防抖节流，说的其实是同一件事：<strong>把函数当作可以传递、可以拼装的值</strong>。柯里化让配置与计算分离，流线组合让步骤可以自由增删，防抖节流让执行时机可以被控制——它们都不改变数据本身，只重新组织函数的调度方式。
    </p>
