    <h2>定价规则的拆解</h2>
    <p>
      你在写一个课程价格计算器。定价规则不是一句话能说清的：先按会员等级打折，再按地区加税，最后统一格式化成「¥199.00」。更麻烦的是，规则本身还会变——运营要调折扣、要临时加满减、要按活动叠加优惠。你真正想要的能力不是「算一次价格」，而是<strong>把折扣、加税、格式化这些步骤像积木一样拼起来</strong>，改了哪块只换哪块。
    </p>
    <p>
      如果只会写「一个函数干完全部活」的代码，代价是明显的：每加一条规则就要回头改主函数，主函数的参数列表越拉越长，某一步想单独测试或者复用到别处，都做不到。规则和数据缠在一起，你就没法单独验证「打八折」到底对不对。
    </p>

    <h2>步骤拆分为小函数</h2>
    <p>
      最自然的做法是先把每一步拆成独立的普通函数：<code>applyDiscount(price, rate)</code> 负责打折，<code>addTax(price, rate)</code> 负责加税，<code>formatPrice(price)</code> 负责格式化，再在计算函数里按顺序依次调用。
    </p>
    <p>
      这个方案做对了一件很重要的事：<strong>它把「一个步骤」变成了一个可命名、可单独测试的独立单位</strong>。每个函数只关心自己的换算，输入一个数、输出一个数，逻辑干净。这一步的拆分必须保留，问题只在于接下来怎么把这些单位组装起来。
    </p>

    <h2>固定参数的重复传递</h2>
    <ul>
      <li>每调用一次 <code>applyDiscount</code> 都要重复传一遍 <code>rate</code>。「打八折」这条已经确定下来的规则，却每次都得重新交代一次参数。</li>
      <li>三步的顺序被硬编码在计算函数的三行调用里。想插一条「满减」，又得回去改主函数。</li>
      <li>想复用「打八折」这个动作，只能复制那段带参数的调用，规则一变，散落各处的 0.2 全得改。</li>
      <li>到了搜索框这种高频场景，问题更明显：用户每敲一个字就发一次请求，300 毫秒里敲八个字就是八次网络请求，服务器和列表都在抖。</li>
    </ul>

    <h2>柯里化与函数组合</h2>
    <p>
      先解决「规则要重复交代参数」这一点。如果把函数写成<strong>一次只接收一个参数</strong>、每接收一个就返回一个新函数，那么「打折」就可以分两步完成：先喂给它折扣率，得到一个「已经记住八折的函数」，再把这个函数喂给任意价格。
    </p>
    <p>
      <code>const applyDiscount = (rate) =&gt; (price) =&gt; price * (1 - rate)</code>，于是 <code>const discount20 = applyDiscount(0.2)</code> 就是一个只等价格的函数，<code>discount20(200)</code> 得到 160。这种把多参数函数拆成一串单参数函数的技术叫<strong>柯里化</strong>，它最大的价值是<strong>让配置和计算分开</strong>：折扣率在配置阶段就固定下来，之后反复调用不必再传。
    </p>
    <p>
      回头看，随手在函数里返回一个函数、或者接收一个函数当参数，这件事本身有个名字：<strong>高阶函数</strong>。其实你早就在用它了——<code>map</code> 接收一个转换函数、<code>filter</code> 接收一个筛选函数、<code>reduce</code> 接收一个收敛函数，它们都是高阶函数，只是我们用得太顺手而没留意。
    </p>
    <p>
      接着解决「顺序被硬编码」。既然每一步都是「一个数进、一个数出」的函数，就可以写一个<strong>组合器</strong>把若干单步函数串成一条流水线：<code>pipe</code> 从左到右依次执行，<code>compose</code> 从右到左依次执行。价格计算于是变成一句声明：
    </p>
    <p>
      <code>pipe(applyDiscount(0.2), addTax(0.06), formatPrice)(200)</code>
    </p>
    <p>
      要加满减，就在中间插一个函数；要换折扣，只改 <code>applyDiscount</code> 的参数。这里有一条必须记牢的规则：<strong><code>pipe</code> 与 <code>compose</code> 的方向恰好相反</strong>，同一个项目里混用两种风格时，先确认你写的是哪一种，否则会得到「先加税再打折」这种看似对、实则错的结果。
    </p>
    <p>
      最后解决高频调用。搜索联想、窗口滚动、按钮连点这类事件，触发频率远高于我们真正需要的处理频率，于是有了两个控制执行节奏的包装函数：
    </p>
    <ul>
      <li><strong>防抖</strong>：事件停手一段时间后才执行一次。适合搜索联想——用户还在打字就不发请求，停下来的那一刻才发。</li>
      <li><strong>节流</strong>：在固定时间间隔内至多执行一次。适合滚动、拖拽——不管触发多密，保证一段时间内只处理一次。</li>
    </ul>
    <p>
      它们和柯里化一样，都是「包一层、返回一个新函数」，调用方拿到的是增强后的函数。这里有个使用上的细节：既然返回的是新函数，<strong>需要取消时就得先把返回值存下来，再调用它的 <code>cancel</code></strong>；如果当场用完就丢，组件卸载时那个还在计时的防抖任务就没有办法清理了。
    </p>

