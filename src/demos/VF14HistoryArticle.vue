      <strong>开场问题：</strong>课程大纲刚排好，手一抖把「跟练示例」拖到了画布角落，又顺手删错了一个节点。此时画布上的数据已经是改坏后的版本，刷新页面也救不回来——一个可编辑的画布，怎样才能让用户安心地「改错了就退回去」？
    </div>

    <h2>只能前进的编辑器</h2>
    <p>
      最朴素的画布只维护「当前状态」：节点数组、连线数组，用户每拖一下、每删一个节点，就直接覆盖这份数据。它简单、直接，也足够应付演示，但有一个致命缺口——<strong>没有过去</strong>。
    </p>
    <p>
      删除是不可逆的：节点对象从数组里消失，与它相连的边也一起被清理；拖拽是不可逆的：旧坐标被新坐标覆盖，松手之后没有任何地方还留着原来的位置。用户能做的只有小心翼翼地操作，或者从头再来一遍。
    </p>
    <p>
      要补上这个缺口，编辑器必须额外保存「历史」。而历史的第一种实现思路，不是记录每一个动作，而是记录<strong>每一个状态</strong>。
    </p>

    <h2>快照式历史的原理</h2>
    <p>
      快照式历史的核心只有三步。第一步，在任何会改变图的操作发生<strong>之前</strong>，把当前整张图导出成一份快照，压入 undo 栈；第二步，撤销时从 undo 栈弹出最近一份快照，把当前状态压入 redo 栈，再用快照恢复画布；第三步，重做时反过来，从 redo 栈弹出快照，把当前状态压回 undo 栈，再恢复。
    </p>
    <p>
      这里存的是「变更前」而不是「变更后」。因为撤销的本质是回到操作发生前的样子，变更前快照正好就是那个样子；而变更后的状态并不需要提前保存，等到真正撤销时现场再取一次即可。
    </p>
    <ul>
      <li>新操作发生时，把变更前快照压入 undo 栈，并<strong>清空 redo 栈</strong>。</li>
      <li>撤销时，undo 栈弹出、当前状态进入 redo 栈、快照写回画布。</li>
      <li>重做时，redo 栈弹出、当前状态进入 undo 栈、快照写回画布。</li>
      <li>清空 redo 的理由很直观：一旦从历史中间分叉，原来那条「未来」就不再属于当前时间线。</li>
    </ul>
    <p>
      导出与恢复分别由 <code>toObject()</code> 和 <code>fromObject()</code> 完成。前者把节点、连线与视口打包成可序列化对象，后者把对象重新装载回画布。业务代码不需要逐字段搬运，整图替换一次完成。
    </p>

    <h2>拖拽合并成一条</h2>
    <p>
      快照式历史最容易踩的坑，是记录得太勤。节点拖拽过程中会持续触发 drag 事件，鼠标每移动一像素都可能产生一次位置变化。如果每次变化都导出一份快照，拖一次节点就能塞进几十上百条记录，undo 栈瞬间被无意义的中间态填满。
    </p>
    <p>
      正确的粒度是「一次用户操作 = 一条历史」。在 <code>dragstart</code> 时把变更前快照暂存在一个临时变量里，拖拽过程中只更新画面、不碰历史；到 <code>dragstop</code> 时再判断位置是否真的发生变化，有变化才把那份暂存快照压入 undo 栈。这样无论中间移动了多少次，最终只留下一条可撤销的记录。
    </p>
    <p>
      同样的思路适用于其他高频输入：连续输入的文字、滑块拖动、尺寸调整，都应该在「开始」时记快照、在「结束」时提交一条记录，而不是把每个中间值都当成独立历史。
    </p>

    <h2>栈深与深拷贝</h2>
    <p>
      快照保存的是整张图，成本随节点数量线性增长。节点上百、历史几十步时，内存占用会变得可观。因此 undo 栈必须限制深度，例如只保留最近 20 到 50 条，超出后丢弃最旧的一条；用户能回退的步数有限，但换来的是稳定的内存曲线。
    </p>
    <p>
      另一个必须处理的问题是<strong>深拷贝</strong>。画布里的节点对象是响应式的，如果直接把引用放进栈，后续拖拽修改节点位置时，栈里那份「历史」也会跟着变，撤销时拿到的其实是当前状态。入栈前要用 <code>JSON.parse(JSON.stringify(...))</code> 或结构化克隆做一次彻底复制，让快照与运行态彻底脱钩。
    </p>
    <ul>
      <li>只保存可序列化的业务数据，函数、DOM 引用、第三方实例不要混进快照。</li>
      <li>选中态、拖拽中标记属于瞬时界面状态，可在导出前剔除，减少无意义差异。</li>
      <li>视口是否纳入历史要明确：恢复视口能让用户回到当时的视野，也可能让画面突然跳动。</li>
      <li>图之外如果还有业务状态（例如标题、筛选条件），要一并纳入快照，否则撤销后会出现图文不一致。</li>
    </ul>

    <h2>命令模式与快照模式</h2>
    <p>
      历史还有另一条路线：命令模式。每个操作封装成一个带 <code>do</code> 与 <code>undo</code> 的命令对象，执行时做变更，撤销时执行反向操作——新增节点对应删除节点，移动节点对应写回旧坐标。它记录的是「动作」，不是「整张图」。
    </p>
