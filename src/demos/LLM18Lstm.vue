    <div class="llm-question"><strong>开场问题：</strong>RNN 的记忆为什么传不远？——给记忆装上「阀门」</div>

    <h2>提出问题</h2>
    <p>上一课手算出了 RNN 的病：每读一个词，旧记忆就被「×0.6 再混入新词」稀释一次，读了 20 个词，20 步前的信息 <code>0.6²⁰ ≈ 0.00004</code>，几乎归零。</p>
    <p>想象读一本小说：第 1 章写「主角害怕黑暗」，第 30 章主角走进地下室——这时关键要想起第 1 章那句话。人不会把中间 30 章的每个细节都死记，但会<strong>主动记住对后面重要的事</strong>，因为早已判断出「主角害怕黑暗」值得留。RNN 坏就坏在不会「主动」：每步机械地混合所有内容，重要的和无关的一起被稀释。</p>
    <div class="llm-box warn">
      <strong>解药</strong>：给记忆装上阀门——几个开关，分别管「忘掉多少旧的」「写入多少新的」「读出多少给当前用」。
    </div>

    <h2>最小方案</h2>
    <p>LSTM（长短期记忆网络，1997 年提出）的第一招，是<strong>把记忆拆成两条线</strong>：</p>
    <ul>
      <li><strong>长期记忆 <code>C</code></strong>（Cell State）：一条「高速公路」，信息能几乎不受干扰地从句首开到句尾。新内容想挤进来必须先过阀门，不放行则原有信息<strong>原样保留</strong>——这正是对治 RNN「每步稀释」的关键。</li>
      <li><strong>短期记忆 <code>h</code></strong>（Hidden State）：当前这一步的「工作台」，每步根据长期记忆和当前词重新算一份，用来预测下一个词。</li>
    </ul>
    <p>两条线之间有三个阀门，各管一件事：</p>
    <ol class="llm-steps">
      <li><strong>忘记阀</strong>：长期记忆里旧内容保留多少。</li>
      <li><strong>写入阀</strong>：当前词的新信息写进长期记忆多少。</li>
      <li><strong>读出阀</strong>：从长期记忆读出多少，当作这一步的短期记忆 <code>h</code>。</li>
    </ol>

    <h2>阀门怎么工作</h2>
    <p>每个阀门说穿了就是一个 <strong>0 到 1 之间的数</strong>：1 完全打开、0 完全关死、0.6 放 60% 过去。这个数不是手拧的，而是网络根据「当前词」和「当前短期记忆」，用老朋友 <strong>Sigmoid</strong>（把任意值压到 0~1）算出来的，并靠训练数据不断优化，直到学会该开时开、该关时关。</p>
    <div class="llm-box hint">
      核心就盯中间那行：<code>C新 = f·C旧 + i·g</code>，翻成人话是——<strong>新的长期记忆 = 忘记阀 × 旧记忆 + 写入阀 × 新内容</strong>。<code>⊙</code>（逐元素相乘）负责用阀门「掐住流量」。
    </div>
    <p>这里有个值得回味的反转：第 8 课里 Sigmoid 把值压到 0~1 是<strong>缺点</strong>（两端压平、梯度消失）；可搬到这，「0 到 1」恰恰是<strong>优点</strong>——它天生就是个阀门开度，0 关死、1 全开。同一个函数换了个位置，缺点摇身变成优点。</p>

    <h2>手算一遍</h2>
    <p>仍让长期记忆 <code>C</code> 就是一个数，记「主角怕不怕黑」，只用核心行 <code>C ← f·C + i·g</code>。网络已学会：读到重要词 <code>f=0.9, i=0.9</code>，读到无关词 <code>f=0.99, i=0.04</code>。从 <code>C0=0</code> 开始：</p>
    <ol class="llm-steps">
      <li>① 害怕黑暗（重要）：<code>C = 0.9×0 + 0.9×0.95 = 0.855</code> ——写入阀大开，记忆点亮</li>
      <li>② 主角（无关）　：<code>C = 0.99×0.855 + 0.04×0.2 ≈ 0.854</code></li>
      <li>③ 吃了（无关）　：<code>C ≈ 0.854</code> ——每步忘记阀≈0.99，几乎一动不动</li>
      <li>…一连串无关词，<code>C</code> 基本不动…</li>
      <li>⑨ 地下室　　：<code>C ≈ 0.851</code> ——9 个词后「害怕」还稳稳记着</li>
    </ol>
    <p>关键在②步往后：忘记阀≈0.99，旧记忆几乎原样带过去；写入阀≈0.04，无关词几乎挤不进来。于是 9 个词读下来记忆只从 0.855 掉到 0.851，还剩 <strong>99%</strong>。对照同一句话喂给 RNN：读到「地下室」时 RNN 记忆只剩不到 <strong>2%</strong>，「害怕」早被冲没了。同一句话，一个记得住、一个记不住，差别全在那几个阀门。</p>

    <h2>发现不足</h2>
    <p>有了高速路和阀门，LSTM 能处理的远距离依赖远超 RNN。原理就藏在那行公式里：长期记忆走「<code>f·C旧</code>」这条道，忘记阀 <code>f</code> 接近 1 时记忆几乎无损前传，连带梯度也能几乎无损传回很远——<strong>梯度消失被大大缓解</strong>。算给你看：隔 30 个词，RNN 是 <code>0.6³⁰ ≈ 0</code>（彻底没了），LSTM 按忘记阀 0.99 算是 <code>0.99³⁰ ≈ 0.74</code>，还留着 74%。实验中 LSTM 能可靠记住 50~100 步前的信息，2010~2017 年间语音识别、机器翻译、文本生成的主力都是它。</p>
    <div class="llm-box warn">
      <strong>新的硬伤：必须按顺序读词，无法并行。</strong>读完第 <code>k</code> 个词才能算第 <code>k+1</code> 个，因为 <code>h_t</code> 依赖 <code>h_(t-1)</code>。100 个词的句子要做 100 步串行计算，没法摊开让 GPU 上万核心同时算。2017 年 Google 提出 Transformer，不按顺序读词，让每个词同时看到句子里所有词、天生可并行，把大模型的训练时间从几个月压到几天。
    </div>

    <h2>总结</h2>
    <p>LSTM 用两种记忆（长期 <code>C</code> + 短期 <code>h</code>）和三个阀门（忘记 / 写入 / 读出）解决了 RNN 的记忆淡出。核心就一行：<code>C ← 忘记阀×旧记忆 + 写入阀×新内容</code>。忘记阀≈1，重要信息就能几乎无损地传几十上百步。遗留问题是顺序计算、无法并行——这正催生了 Transformer。</p>
