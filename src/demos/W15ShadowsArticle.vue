      <strong>开场问题：</strong>你把球和方块摆在一个地面上，光照、高光都到位了，可它们像贴在背景上的贴纸：方块悬在半空，地面上没有任何影子，球和方块之间也互不遮挡。你把光源角度压低，满心期待拉出一道长长的投影，结果还是什么都没有。光照明明已经算了「谁朝着光」，为什么算不出「谁挡住了光」？
    </div>

    <h2>光照遮挡的缺失</h2>
    <p>
      光照模型的 <code>N·L</code> 只回答了一个问题：这个表面朝不朝着光源。它默认光<strong>畅通无阻</strong>地照到每个表面。可真实场景里，总有东西挡在光路上——这正是画面「悬浮感」的来源。
    </p>
    <p>
      想判断「某个点是否被挡住」，就得知道：从光源看过去，这个点前面有没有别的东西、离光源最近的那层表面在哪。在着色器里自己硬凑，账很难付：用 CPU 逐像素做射线求交，几万个像素乘以场景三角形成本直接爆炸，跑不到实时；让每个物体自己判断挡了谁，就要两两比较，无法统一处理；而单个物体的着色器里根本没有「整个场景」的全局信息。于是问题落到：<strong>怎么高效地知道，场景里每个受光点，是不是被更靠近光源的东西挡住了？</strong>
    </p>

    <h2>光源视角深度图</h2>
    <p>
      把「从光源看场景」这件事，交给 GPU 再渲染一遍。第一遍，把相机搬到光源的位置、朝向场景，照常渲染一遍，但<strong>不记录颜色，只记录深度</strong>——也就是「从光源看，每个方向离它最近的表面有多深」。这张图就是 <strong>shadow map（阴影贴图）</strong>。
    </p>
    <p>
      这个方案做对了一件事：<strong>它用一次渲染，把「谁挡在前面」压缩成了一张可查询的深度表</strong>。原本无从下手的全局遮挡关系，变成了一次深度比较。
    </p>

    <h2>自遮挡与粉刺</h2>
    <ul>
      <li><strong>有表还得会「查」。</strong>第二遍渲染时，得知道屏幕上的某个像素，对应到光源视野里深度图的哪个位置；这个映射关系还没建立。</li>
      <li><strong>自遮挡会让表面长满黑点。</strong>深度值有量化误差，同一个平面明明没被挡，比较时却可能被误判为「更远」，于是整片表面冒出条纹状的黑色噪点，也就是阴影粉刺（shadow acne）。</li>
      <li><strong>边界硬得发假。</strong>直接做一次比较只能得到「是/否」两个结果，阴影边缘是锯齿状的硬边，缺少真实阴影的柔和过渡。</li>
      <li><strong>强度不可调。</strong>要么全黑要么全亮，没法让阴影「淡淡的」，也谈不上和光照自然衔接。</li>
    </ul>

    <h2>光空间坐标映射</h2>
    <p>
      先补「怎么查」。第一遍从光源视角渲染时，顶点着色器用 <code>uLightMVP</code> 把网格变换到光空间，片段直接写 <code>gl_FragCoord.z</code>——记下的是这个点在该视角下的屏幕深度。第二遍换成相机视角渲染时，顶点着色器<strong>顺手把每个顶点的光空间坐标 <code>vLightSpacePos</code> 也算出来</strong>，这样片段阶段就能拿它去查表。
    </p>
    <p>
      到了片段着色器，把光空间坐标做<strong>透视除法并映射到 <code>[0, 1]</code></strong>，得到在阴影贴图上的采样坐标：<span class="lesson-kv">projCoords = lightSpacePos.xyz / w * 0.5 + 0.5</span>。用它采样 shadow map，就取到了「光源在这个方向看到的最浅深度」。整个流程是：
    </p>
    <ol class="lesson-steps">
      <li>Pass 1：用 <code>uLightMVP</code> 把网格变换到光空间，把 <code>gl_FragCoord.z</code> 写入深度纹理。</li>
      <li>Pass 2：正常渲染场景，顶点着色器同时计算顶点的光空间坐标 <code>vLightSpacePos</code>。</li>
      <li>片段中把光空间坐标做透视除法并映射到 <code>[0, 1]</code>，用它采样 shadow map。</li>
      <li>比较当前深度与采样深度判断遮挡，对周围 3×3 共 9 个纹素做 PCF 平均得到软阴影，乘强度后作用于漫反射与高光。</li>
    </ol>
    <p>
      判断规则很直白：如果<strong>当前点的深度比阴影贴图里存的最近深度更深</strong>，说明沿这个方向有更靠近光源的东西，当前点在它后面，落进阴影。写成表达式就是 <code>currentDepth - bias &gt; pcfDepth</code>。为什么要减一个 <code>bias</code>？因为深度值有量化误差，同一个平面在比较时可能刚好「差那么一点点」，被误判成被遮挡，于是长出粉刺。给当前深度减去一个很小的偏移量，就能把它压过去。
    </p>
    <p>
      再补「柔化」。单点比较得到的是一刀切的硬边。把当前像素周围 3×3 共 9 个纹素<strong>各做一次比较，再把结果平均</strong>（<code>shadow / 9.0</code>），阴影边缘就有了渐变——这就是 <strong>PCF（Percentage Closer Filtering）</strong> 的简化版。最后把阴影乘上一个强度系数，作用在漫反射与高光上，就得到既不生硬又可控的软阴影。
    </p>
    <div class="lesson-box warn">
      <strong>三个必须权衡的点：</strong><code>bias</code> 太小会留下阴影粉刺，太大则会让阴影和物体「脱开」、飘起来（peter-panning），要在两者之间取舍；shadow map 的分辨率决定阴影边缘精度，越高越清晰，但显存、带宽和采样成本同步上涨；本课的平行光用一个正交投影构成 <code>uLightMVP</code>，而点光源（要六面）或聚光灯需要更复杂的方法，属于进阶内容。
    </div>

