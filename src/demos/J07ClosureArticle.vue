    <h2>闭包的两面</h2>
    <p>
      作用域链决定了函数能看见谁，闭包则让这份「能看见」跨越了外层函数的生命周期。它既能当作私有状态的保险箱，也可能变成内存的锁链——用对了是封装，用过头就是泄漏。
    </p>
    <div class="lesson-term">
      <span class="term-name">「闭包」</span>指一个内部函数加上它引用的词法环境。函数在定义时就按嵌套结构定好了能访问哪些变量（词法作用域），这条从内往外的查找路径叫作用域链；即使外层函数已经返回，内部函数仍能读写那些变量，因此闭包既适合封装私有状态，也要记得及时解除引用以免长期占用内存。
