      <strong>开场问题：</strong>购物车徽标要显示已加入商品的总数，于是写了 <code>function addItem() { let count = 0; count++; return count }</code>，可每点一次按钮，徽标都只显示 1。函数明明在累加，为什么数字始终停在原地？
    </div>

    <h2>作用域链怎么查</h2>
    <p>
      你最直接的念头大概是：既然函数记不住数量，那就把 <code>count</code> 挪到函数外面，变成全局变量。这个方向其实没错——<strong>一个函数能看见哪些变量，本来就由它写在哪里决定</strong>。JavaScript 用的是<strong>词法作用域</strong>：能访问哪些变量，在定义那一刻就按代码的嵌套结构定好了，规则是从内往外一层层找，这条查找路径就叫<strong>作用域链</strong>。
    </p>
    <p>
      关键在「从内往外」：先在当前函数自己的作用域里找，找不到就去定义它的外层作用域找，再找不到继续往外，直到最外层。而且<strong>只看「写在哪」，不看「谁调用」</strong>——同一个函数无论从哪里被调起来，它沿用的始终是定义时那条链。
    </p>

    <h2>闭包是怎么形成的</h2>
    <p>
      把 <code>count</code> 挪到全局，确实让函数看得见了，可它同时带来两个新麻烦：全局变量谁都能改，而且第二个计数器会和第一个共享同一个 <code>count</code>。你真正想要的，是让变量<strong>只被这一个函数看得见</strong>，又能在多次调用之间一直活着。
    </p>
    <p>
      办法是把变量藏进一个外层函数：外层写 <code>let count = 0</code>，再返回一个内部函数去读写它。<strong>即使外层函数执行完并返回了，内部函数依旧握着它出生时的那套词法环境</strong>——这个「内部函数 + 它引用的词法环境」的组合，就是<strong>闭包</strong>。
    </p>
    <p>
      它一次满足了你前面两个诉求：数据私有（外部拿不到 <code>count</code>），状态持久（多次调用之间 <code>count</code> 不会被重置）。开头的 bug 正是缺了这层包裹——每调一次 <code>addItem</code>，函数体里的 <code>let count = 0</code> 都重新执行一遍，自然永远从 0 开始。
    </p>

    <h2>用闭包藏住数据</h2>
    <p>
      既然闭包能让变量活下来，顺水推舟，就把它当成私有状态的容器：返回一个对象，只暴露 <code>add</code>、<code>count</code> 这样的方法，数据本身留在闭包里。
    </p>
    <p>
      这样一来，外部拿不到数据，只能走你给出的接口，「谁能改、怎么改」都被收口了。这正是<strong>模块模式</strong>最早的雏形——用闭包把实现细节和公开接口分开，让状态变成只可操作、不可窥探的东西。
    </p>

    <h2>循环里的变量捕获</h2>
    <p>
      闭包有一天会给你来个反直觉的跟头。给几门课绑定点击回调：<code>for (var i = 0; i &lt; 3; i++) { btn[i].onclick = () =&gt; alert(i) }</code>，无论点哪一门，弹出来的都是 3。
    </p>
    <p>
      原因还是作用域链：<code>var</code> 定义的 <code>i</code> 只有唯一一个绑定，三个回调引用的是同一个它，等回调真正执行时，循环早已跑完，<code>i</code> 停在 3。解法是把 <code>var</code> 换成 <code>let</code>：<code>let</code> 在每次迭代都会生成一个<strong>新的绑定</strong>，每个回调各自闭包住自己那一个，于是依次弹出 0、1、2。旧代码里没有 <code>let</code>，则要靠立刻执行的函数表达式（IIFE）手动为每一轮造一个作用域。
    </p>

    <h2>闭包也会留住内存</h2>
    <p>
      闭包让变量活着，代价是它<strong>也拦住了垃圾回收</strong>。只要还有闭包引用着某个大对象，这个对象就不会被回收，哪怕别的代码早就不需要它了。
    </p>
    <p>
      所以养成两条习惯：一是不再需要某个闭包时，把保存它的变量置为 <code>null</code>，解除引用；二是让闭包<strong>只捕获真正需要的字段</strong>，而不是整个大对象——比如只留住 <code>user.id</code>，而不是把整个 <code>user</code> 拖住。现代引擎还会主动优化掉闭包里其实没被用到的变量，但「少捕获、及时解除」始终是最稳的做法。
    </p>

