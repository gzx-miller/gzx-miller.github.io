    <h2>总结</h2>
    <p>
      选择器回答的是两个问题：<strong>一条规则圈住了哪些元素，以及它和别的规则谁说话更算数</strong>。把身份、状态、局部、结构四类匹配补齐，再用特异性判断胜负，开场的「染色溢出」与「不生效」就都能提前避开。
    </p>
    <div class="lesson-term">
      <span class="term-name">「选择器」</span>决定匹配对象：通配匹配全部，类型匹配标签名，类/ID 匹配 class 与 id，属性匹配特性，伪类匹配状态，伪元素匹配元素上的虚拟部分，组合器（后代、<code>&gt;</code>、<code>+</code>、<code>~</code>）表达元素间的结构关系。它们各具<strong>特异性</strong>，命中同一元素时以特异性大小决定胜负，同级时后声明者胜。
    </div>
