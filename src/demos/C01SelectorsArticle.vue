  <LessonArticle>
    <div class="lesson-question">
      <strong>开场问题：</strong>我想只给课程目录的「一级条目」加个橙色左边框，顺手写了 <code>.menu li</code>，结果嵌在里面的子目录条目也一起变了色——一条选择器到底圈住了哪些元素？
    </div>

    <h2>提出问题</h2>
    <p>
      场景很小：课程网站的侧边栏有一份目录，一级条目下面还可能嵌套子目录。需求是「一级条目加下边距和橙色左边框」。你随手写下 <code>.menu li { ... }</code>，上线后子目录条目也带上了边框，视觉上乱成一团。更麻烦的是，<code>.menu</code> 后来在购物车页也被复用了，同一份样式把购物车的商品列表也改了一遍。
    </p>
    <p>
      这类问题有两个方向，方向相反却都表现为「样式莫名其妙」：<strong>选多了，污染到不该管的元素；选少了，样式干脆不生效</strong>。它们都没有报错、没有提示，能依靠的只有你对匹配规则的理解。而一旦多条规则同时命中一个元素，还要看谁「更硬」——这就是选择器必须一次讲清的原因。
    </p>

    <h2>最小方案</h2>
    <p>
      最朴素的写法：直接用标签名或类名去选。<code>p { line-height: 1.6 }</code> 统一段落行高，<code>.btn { padding: 8px 16px }</code> 统一按钮内边距。
    </p>
    <p>
      这个方案做对了一件大事：<strong>绝大多数「整站统一」的排版，一条类型或类选择器就能一次写完</strong>，简单、可读、没有歧义。当页面上只有一种按钮、一种段落时，它完全够用。
    </p>

    <h2>发现不足</h2>
    <ul>
      <li>管不了状态：按钮悬停、输入框聚焦、奇数行——这些「元素正处于某一种情况」没有标签名可写。</li>
      <li>管不了局部：段落首字母放大、在元素前后插入一个图标，这是元素的「某个部分」，不是元素本身。</li>
      <li>管不了结构：只想要「直接子元素」或「紧跟其后的兄弟」，标签名无从表达这层关系。</li>
      <li>选得中但打不赢：多条规则命中同一个元素时，谁生效不看出场顺序，只看权重。</li>
      <li>直写标签名会全局生效，一处改动会牵动别的页面，像开场那样把购物车也改掉。</li>
    </ul>

    <h2>迭代</h2>
    <p>
      先把「按身份选」补成一整套：通配 <code>*</code> 匹配所有元素（常用来做全局重置）；类型 <code>p</code>、<code>div</code> 匹配标签名；类 <code>.card</code> 匹配 class 包含该值的元素；ID <code>#header</code> 匹配 id 等于该值的元素；属性 <code>input[type="text"]</code> 匹配带有某特性的元素。
    </p>
    <p>
      再把「状态」和「局部」也算进来。<strong>伪类</strong>表达状态：<code>a:hover</code> 悬停、<code>input:focus</code> 聚焦、<code>li:nth-child(odd)</code> 奇数项。<strong>伪元素</strong>表达元素上那块「虚拟的部分」：<code>p::first-letter</code> 命中首字母，<code>.tip::before</code> 在元素前插入内容。为什么伪元素能凭空造出一个东西？因为它命中的是盒子上的一个虚拟位置，而不是 DOM 里的真实节点。
    </p>
    <p>
      这里有个帮你分清两者的记号约定：<strong>伪类写一个冒号，伪元素写两个冒号</strong>。老写法允许伪元素也用一个冒号，但按双冒号来写，一眼就能分辨「这是在描述状态，还是在描述元素身上的某个部分」。属性选择器也比想象中灵活，除了精确匹配 <code>[type="text"]</code>，还能按前缀、后缀、包含来匹配，比如一次性选中页面上所有的外部链接。
    </p>
    <p>
      最后补上「结构关系」，也就是组合器：空格是后代选择器，选中所有层级；<code>&gt;</code> 是子元素选择器，只选直接子级；<code>+</code> 只选紧挨着的那一个后置兄弟；<code>~</code> 选中后面所有同级兄弟。开场那个「子目录被染色」的问题，把 <code>.menu li</code> 换成 <code>.menu &gt; li</code> 就精确了。
    </p>
    <p>
      组合器还有一个容易被忽视的特点：它表达的是<strong>结构关系，而不是元素身份</strong>。也就是说 <code>.menu &gt; li</code> 里的 <code>&gt;</code> 描述的是「谁是谁的直接子级」，一旦你在中间插了一层 <code>div</code> 做包裹，原有的直接子级关系就被破坏了，样式会突然失效——这也是重构结构时最常踩的坑之一。
    </p>
    <p>
      但选得准还不够，还得能赢。两条规则同时命中一个元素时，比较的是<strong>特异性</strong>：大致是 ID &gt; 类/属性/伪类 &gt; 类型/伪元素，处在同一级时后声明的胜出（C_06 会把这张权重表彻底讲透）。所以日常一般用类名而不是 ID——不是 ID 不好用，而是它权重太高，日后想覆盖会很难受。
    </p>
    <div class="lesson-box warn">
      <strong>两个工程习惯：</strong>选择器不要嵌套过深，<code>.page .content .list .item .link</code> 这种既难维护、匹配也慢，能用一个语义类名解决就别堆四层；样式不生效时，先打开开发者工具看哪条规则最终胜出、它来自哪个文件，再决定是改选择器还是调顺序，别靠猜。
    </div>

