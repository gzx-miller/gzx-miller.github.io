    <h2>全站字体替换</h2>
    <p>
      你在做课程站，想要中英混排的正文看起来更规整，于是给全站换了一套字体。做法很常见：在页面模板顶部加一行指向字体 CDN 的 <code>&lt;link&gt;</code>，再在 CSS 里写上字体族名。本地看着挺好，问题全在上线后才冒出来。
    </p>
    <p>
      这里面藏着一串连锁反应：字体文件不在你自己手里，用户浏览器要先去第三方服务器取；文件没到之前，浏览器要么先不显示文字等着，要么先用系统兜底字体顶上、字体到了再换回来。而<strong>换字体的那一刻，字宽和行高都会变</strong>，整块文字跟着重新排版，于是页面抖了一下。这就解释了为什么「只是换个字体」会同时影响速度、稳定性和隐私。
    </p>

    <h2>外链字体引入</h2>
    <p>
      最省事的做法就是那行外部链接：把字体服务商的地址贴进页面，剩下交给浏览器。它确实解决了最表面的诉求——<strong>页面文字用上了想要的字体</strong>，而且不用你维护任何字体文件。
    </p>
    <p>
      这一点没有错：字体是设计的一部分，该用就得用。问题在于，把字体来源、加载时机、加载失败的表现全部外包出去，等于把三个不可控因素一起引进了页面。
    </p>

    <h2>第三方字体风险</h2>
    <ul>
      <li>用户的浏览器直接连第三方字体服务器，IP 与访问行为会外泄，隐私合规上容易被质疑。</li>
      <li>境外 CDN 在本地网络下可能很慢甚至超时，字体迟迟不到，文字就一直「隐身」。</li>
      <li>字体未就绪时先隐藏文字会造成短暂空白（FOIT），先用兜底字体再切换（FOUT）则会让排版抖一下。</li>
      <li>字体文件体积不小，尤其中文字体动辄几 MB；全量加载会明显拖慢首屏。</li>
      <li>从第三方动态提供的字体，加载完还可能引发版本与缓存的不确定，问题难复现。</li>
    </ul>

    <h2>字体自托管方案</h2>
    <p>
      思路不是「不用字体」，而是<strong>把字体搬回自己家里、把加载过程管起来</strong>。这就是 <code>next/font</code> 要解决的事：它在构建时下载字体文件并随应用一起自托管，用户浏览器只会向你的站点请求字体，不再有第三方请求。
    </p>
    <p>
      它提供两个入口：<code>next/font/google</code> 用于加载字体服务商上的字体，<code>next/font/local</code> 用于加载你自己项目里的字体文件。两者用法一致，都返回一个对象，你把它挂到根布局上，整棵组件树都能用。
    </p>
    <p>
      挂载方式推荐用 <code>variable</code>：它会生成一个 CSS 变量（例如 <code>--font-inter</code>），你在根布局的 <code>html</code> 上引用，再在全局样式里用 <code>var(...)</code> 组合成字体族。这样做的好处是<strong>字体与类名解耦</strong>：以后想整体换字体，只改变量的值，不用逐页改动。
    </p>
    <p>
      接着处理那一下抖动。两点最关键：
    </p>
    <ol class="lesson-steps">
      <li>用 <code>display: 'swap'</code>。它让文字先用兜底字体立即显示，等真字体到位再平滑切换，避免出现「一片空白」的 FOIT。其余取值里 <code>'block'</code> 会短暂隐藏文本，<code>'optional'</code> 则更偏向放弃晚到的字体。</li>
      <li>靠自托管的尺寸校正消除偏移。因为兜底字体与目标字体的字符宽高并不一致，直接换会抖动；自托管方案会为字体附上校正信息，让两者在版式上尽量对齐，切换时几乎看不出跳动。</li>
    </ol>
    <p>
      最后是瘦身。中文字体很大，别指望全量加载。用 <code>subsets</code> 只加载需要的字符子集，用 <code>weight</code> 只声明真正用到的字重。常见折中是「拉丁子集 + 系统中文字体兜底」，把最重的部分交给系统已有的字体。如果公司有自研字体或第三方授权字体，用 <code>next/font/local</code> 配合对应的字体文件即可。
    </p>
    <div class="lesson-box hint">
      <strong>一个容易忽略的好处：</strong>字体在构建时就被下载下来并自托管，运行时不向字体服务商发起任何请求，隐私更友好；同时构建产物里已包含字体文件，部署上线后不会再受第三方可用性影响。
    </div>

