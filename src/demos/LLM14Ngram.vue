    <div class="llm-question"><strong>开场问题：</strong>不懂语法、不懂语义，光靠「数数」能不能接出下一个词？</div>

    <h2>提出问题</h2>
    <p>用手机打字输入「今天天气」，键盘弹出「真好」「不错」「怎么样」几个候选。手机怎么猜的？它没有读懂「天气」、没联网查天气预报，做的事极其简单：<strong>翻历史记录、数数</strong>。它读过几千万条消息，数过每次「今天天气」后面跟着什么——真好 4120 次、不错 3890 次、怎么样 2540 次……按频率排序，就能给出候选。这是手机输入法的基本原理，纯粹的数数、和「理解语言」毫无关系。</p>

    <h2>最小方案</h2>
    <p>em>prompt the method more通用：不管前面说了多少，<strong>只看最近的 N 个词</strong>来预测下一个。看 1 个词叫一元模型、2 个叫二元模型、看 N 个词就叫 <strong>N-gram</strong>。训练很简单：爬下大量文本，把每段连续的 N 个词都数一遍、统计频率、存成一张巨大的表格即可——<strong>不需要理解语言、不需要语法规则，只需要数数</strong>。</p>
    <h3>它查的其实是一张频率表</h3>
    <p>这张表怎么查？以二元模型（N=2）为例，想预测「天气」后面接什么，就翻到「前文 = 天气」那一块，数它后面各词出现次数，再除以「天气」的总出现次数（如 10000），就得到每个候选的概率：真好 23.0%、不错 21.0%、预报 18.0%……而「香蕉」只共现 3 次、概率几乎为零——<strong>语料里没数到的组合，N-gram 只能给接近 0 的概率</strong>。换个角度看，这就是<strong>条件概率</strong>：给定前面 N 个词、下一个词出现的可能性。语言模型的本质就是给「下一个词」分配一张概率分布表，N-gram 是这个想法最朴素的实现：能数则数、数不到就抓瞎。</p>

    <h2>发现不足</h2>
    <ul>
      <li><strong>记性只有 N 个词</strong>：用 N=2 补「那只从小在胡同里长大、非常怕生人的小猫，今天第一次 ___」，模型只看最后两个词「第一次 ___」，完全不知道前面在讲一只猫。</li>
      <li><strong>加大 N 也救不了</strong>：把 N 调到 5 看「怕生人的小猫，今天第一次」，可训练数据里见过这个完整组合的概率几乎为零。N 越大，每个具体组合出现次数越少、没见过的组合越多——练成了一个两难困境。</li>
      <li><strong>把词当符号</strong>：即便见过「猫 → 出门」，也没法推断「小猫 → 出门」——「猫」和「小猫」是两个毫不相关的字符串，统计帮不了彼此。</li>
    </ul>

    <h2>迭代 / 收束</h2>
    <p>尽管有这些局限，N-gram 几十年间一直是语言技术的支柱：手机输入法候选词、早期语音识别（用它过滤「听起来像但文法奇怪」的结果）、垃圾邮件过滤、机器翻译的初级版。它有用，是因为<strong>语言里大量短距离搭配非常固定</strong>——「天气」后面接「预报」的概率远高于接「香蕉」，这些规律数数就能捕捉到。但它也做不到长句子、跨句理解、词义灵活性——这些需要一个能「理解词义」而不是「认识词的形状」的工具，这正是下一课要解决的「词」本身的问题。</p>

    <h2>总结</h2>
    <p>N-gram 是语言预测的「数数法」：看最近 N 个词 → 查历史统计频率表 → 预测下一个词。不需要理解语言，只需要一张巨大的频率表；但它的记性只有 N 个词，超出这个范围的上下文完全看不到，也无法处理相似词之间的借力。</p>
