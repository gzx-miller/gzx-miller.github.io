    <h2>总结</h2>
    <p>
      RAG 流水线的价值在于把加载、切分、向量化、存储、检索、重排、生成七个环节收成一条可复用的链路。其中「重排」负责把最相关的排到最前、「来源标注」负责让答案可查，而整条链的质量必须分环节测量——只盯最终回答，是找不到问题出在哪一环的。
    </p>
    <div class="lesson-term">
      <span class="term-name">「重排（Rerank）」</span>是在向量召回之后、生成之前插入的一道精排工序：用更强的相关性模型（交叉编码器，或 Cohere Rerank 一类服务）对候选文档逐条打分，再取最相关的少数几条送进提示词。它与召回的分工是——<strong>召回负责「不漏」，重排负责「排准」</strong>。边界：重排更慢更贵，所以只对少量候选执行；它换不掉召回，候选集里根本没有的答案，重排也变不出来。
