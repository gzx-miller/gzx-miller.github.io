      <strong>开场问题：</strong>加载、切分、向量化、检索、生成——单独拎出来每一步你都会写，可它们散在几个脚本片段里：换一份文档要改三处参数，想临时加一步「重排」发现函数签名对不上；等用户追问「这条答案你是从哪看到的」，你支支吾吾答不上来，后台也翻不出依据。
    </div>

    <h2>提出问题</h2>
    <p>
      前面的课里，文档切分、向量检索你都已经单独跑通过。但真正要交付的，不是几个能跑的片段，而是一条能反复跑的<strong>流水线</strong>：加载 → 切分 → 向量化 → 存储 → 检索 → 重排 → 生成，七个环节首尾相接。
    </p>
    <p>
      旧办法是把每一步写成临时脚本，用的时候手工拼。它把三笔成本留给了你：
    </p>
    <ol class="lesson-steps">
      <li><strong>参数到处散</strong>：切分大小、嵌入模型、生成温度散落在不同文件，换个文档或换套模型要满仓库找。</li>
      <li><strong>中间结果不留痕</strong>：某一环出了问题，你没有留存下来的中间产物可以定位，只能靠猜。</li>
      <li><strong>回答没有出处</strong>：生成的是纯文本，用户无法核对，你也无法回溯到具体是哪份文档支撑了这句话。</li>
    </ol>
    <p>
      要回答的是：<strong>怎样把七个环节收成一条可复用的流水线，并在其中补上「精排」与「溯源」，让回答既准又可查？</strong>
    </p>

    <h2>最小方案</h2>
    <p>
      最朴素的做法：写一个类 <code>RAGPipeline</code>，把七个环节收成七个方法；再给两个组合方法——<code>buildIndex</code> 串起「加载、切分、向量化、存储」前四步，<code>query</code> 串起「检索、重排、生成」后三步。所有可调参数（<code>chunkSize</code>、<code>chunkOverlap</code>、嵌入模型、温度）在构造函数里定死。
    </p>
    <p>
      这个方案做对了一件事：<strong>它把「一次性的脚本」变成了「可复用的对象」</strong>。参数收敛到一处，换文档只改输入、换模型只改构造，流水线的形状不再跟着实现细节乱动。
    </p>

    <h2>发现不足</h2>
    <ul>
      <li>检索回来的 Top-K 是按向量相似度排的，可「最像」不等于「最相关」：字面高度相似、其实没用的噪声块会混进上下文。</li>
      <li>检索结果不是越多越好：往提示词里塞太多块会稀释上下文、还白烧 token，真正的关键句被淹没。</li>
      <li>回答没有标注来源：用户无法核对依据，出了问题也追不回是哪份文档支撑的。</li>
      <li>文档更新后没有统一的「重建口径」，新旧内容混在同一个索引里，答案时效说不清。</li>
      <li>中间结果不留痕：某次答错了，你判断不了到底是切分切碎了，还是检索压根没召回。</li>
    </ul>

    <h2>迭代</h2>
    <p>
      不推翻这条七步流水线，而是在它上面补三层。
    </p>
    <p>
      第一步，把节点收进类里之后，<strong>在「检索」与「生成」之间插入一步「重排」</strong>。检索阶段负责「不漏」，先宽召回一批候选（比如 <code>k=10</code>）；重排阶段再对这批候选逐条精算相关性，把最相关的少数几条排到最前。真实项目里这一步用交叉编码器或 Cohere Rerank 之类的<strong>重排模型</strong>，它能显著提升送进提示词那几条的质量。本课演示里的「重排」是占位实现（保持原顺序返回），正是留给你接真实重排模型的位置。
    </p>
    <p>
      第二步，<strong>控制进提示词的块数</strong>。重排之后只保留最相关的少数几条，别把召回的全部塞进去——上下文被稀释，模型反而抓不住重点，还徒增成本。
    </p>
    <p>
      第三步，<strong>把来源带出来</strong>。每个文档块都保留它的 <code>metadata</code>（来源、主题、更新时间），生成答案时连同命中的来源一起返回，做到「答得出来、也查得到」。离线建索引时就记好来源与更新时间，在线回答时才好标注依据、判断时效——本课演示的「检索到的文档」面板，就是把这一步的中间结果摊开给你看。
    </p>
    <div class="lesson-box warn">
      <strong>端到端才叫流水线：</strong>七个环节是逐级传递的，任何一环质量不足都会让最终回答失真——切分太碎，检索召回的就没有完整语义；召回太少，重排也变不出没有的答案。所以要<strong>分环节测量</strong>（召回好不好、重排有没有把相关的排上来、答案对不对），而不是只盯着最后那句回答。
    </div>

