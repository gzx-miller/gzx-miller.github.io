      <strong>开场问题：</strong>课程列表里做一个「搜索 + 按评分排序」，结果排完序之后原始课程数组的顺序也被改掉了，清空搜索框再也回不到最初的样子——只是排个序，动原数组干什么？
    </div>

    <h2>筛选与排序需求</h2>
    <p>
      你在做一个课程列表：上面一个输入框，输入关键词就只留下标题匹配的课程，同时按评分从高到低排列。看起来只是两步处理，但列表数据往往不止一处用——顶部可能还要显示「共 N 门课程」，另一个面板要拿它算平均分。
    </p>
    <p>
      如果处理过程会就地改动这份数组，代价会一路传下去：清空关键词时你拿不回原始顺序，必须先想办法把顺序「还原」；别人读到的是被你改过的状态，于是出现「谁先读谁对」这类无法复现的 bug；多个组件共享同一份引用时，一次筛选可能悄悄改变了另一个组件的渲染结果。所以这里真正需要的不是「会写循环」，而是<strong>把处理表达成一串只读的步骤：每一步都产出新数组，原始数据始终不动</strong>。
    </p>

    <h2>新建数组循环</h2>
    <p>
      最直接的做法：声明一个新的空数组，然后写一个 <code>for</code> 循环遍历源数组，标题命中关键词就把这一项 <code>push</code> 进去；循环结束后再对结果排序。
    </p>
    <p>
      这个方案做对了一件重要的事：<strong>它明确地构造了一份新数据</strong>，至少筛选这一步没有改动源数组，说明「处理产生新数组」这个方向是对的。问题在于，代码写出来的是「怎么一步步做」，而不是「我要什么」。
    </p>

    <h2>手写循环缺陷</h2>
    <ul>
      <li>筛选、排序、取前几条一旦都要做，就会全部揉进同一个循环体，每加一步都要回头改这段循环，越改越难读。</li>
      <li>手动循环里容易漏写分支：条件判断少了一个 <code>continue</code>，同一个元素就可能被重复添加；索引算错还会读到不存在的元素。</li>
      <li>只要中间有人用 <code>sort</code> 排序，就地排序会连原数组的顺序一起改掉，前面为「不改原数据」做的努力全部白费。</li>
      <li>循环体里顺手给每个元素加个前缀之类的副作用会混在遍历里，读代码时看不出哪些是纯转换、哪些是改外部状态。</li>
      <li>排序的比较函数写错（比如返回布尔值而不是数字）不会报错，只会得到一个无法预测的顺序，且难以察觉。</li>
    </ul>

    <h2>链式方法拆解</h2>
    <p>
      不推翻「产出新数组」，而是把「一个循环做很多事」拆成一颗颗只做一件事的方法：<code>filter</code> 负责决定保留谁，<code>map</code> 负责把元素换成新形态，<code>toSorted</code> 负责排序。三者都返回新数组，串起来就成了一条<strong>转换流水线</strong>。
    </p>
    <p>
      先说各自的分工。<code>filter</code> 接收一个判断函数，返回由「判断为真」的元素组成的新数组——它表达的是保留，不是删除。<code>map</code> 接收一个转换函数，一对一地把每个元素换成新值，结果长度与源数组相同。而 <code>forEach</code> 只用来执行副作用，它不返回新数组，所以不要把它当成 <code>map</code> 的替代品，也别用 <code>map</code> 去干副作用的活——写了 <code>map</code> 却不接返回值，是这段代码里最常见的浪费。
    </p>
    <p>
      排序这里必须分清两个方法：<code>sort</code> 就地修改原数组，并且返回的就是同一个引用；<code>toSorted</code> 返回排序后的新数组，原数组保持不变（ES2023 引入）。要保住「原数据不被改动」这条底线，流水线里就只用 <code>toSorted</code>。另外比较函数必须返回数字：负数表示第一个参数排在前面。用 <code>(a, b)</code> 接收两个元素、返回 <code>b.score - a.score</code>，得到的就是评分降序；返回布尔值则完全不符合规则。
    </p>
    <p>
      于是这条流水线从头到尾都不碰原数组，原数组的引用可以被安全地缓存与复用：清空关键词时直接从原始数据重新算一遍即可，不需要任何「还原」逻辑。这也是 React 与 Vue 里不可变更新的基础——状态用新引用替换旧引用，框架才检测得到变化、才敢跳过没有变化的部分。
    </p>
    <p>
      当然，声明式不等于免费。每串一层，数组就被完整遍历一遍，也产生一个中间数组，步骤很多时内存与耗时都会上去。如果最终只想要一个聚合结果（总分、最大值、分组统计），<code>reduce</code> 能把多条处理收敛成单个结果，但它也更容易写得难读，嵌套太深时宁可拆成几个中间变量。还有一点：<code>map</code> 总会产出与源等长的新数组，如果只是要丢掉一部分元素，直接用 <code>filter</code>，不要先 <code>map</code> 再 <code>filter</code> 绕一圈。
    </p>

