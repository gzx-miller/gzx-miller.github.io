      <strong>开场问题：</strong>一张发布流水线图改了十几轮，节点已经互相压住、连线绕成一团，每次加一个环节都要把半张图重新拖一遍——能不能让画布自己按依赖关系把节点排整齐？
    </div>

    <h2>手工摆位局限</h2>
    <p>
      流程图的价值在于「一眼看出先后」。可节点位置是人手工摆的，而图是会长大的：今天插一个「静态检查」，明天在中间加一段「灰度放量」，每次插入都要求你把后续节点整体往右挪。挪到第三轮，位置记录的不是逻辑，而是历史遗留——<strong>图的形状开始和它表达的含义脱节</strong>。
    </p>
    <p>
      更麻烦的是分工。手工摆的位置只存在于某个人的记忆里，换个人接手，改完就再也摆不回原来的样子。我们需要的是：位置由图的<strong>结构</strong>算出来，而不是由人的手感决定。只要依赖关系不变，谁点「自动布局」都该得到同一张图。
    </p>

    <h2>写死坐标方案</h2>
    <p>
      最朴素的做法是「写死坐标」：把每个节点该在的 <code>position</code> 手写进数组，让它们看起来是排好的。这招其实做对了一件事——<strong>它承认了位置可以被提前决定、可以被复现</strong>。同一份数据渲染出的图永远一样，这正是自动布局想追求的性质。
    </p>
    <p>
      顺着这个思路，稍微好一点的做法是手工拖动加「保存布局」，把当前坐标存下来。位置仍然是确定的，也仍然是一条数据。
    </p>

    <h2>新增节点连锁改动</h2>
    <ul>
      <li>节点一多就不可控，十个节点的相对位置还能脑补，三十个就纯粹在猜。</li>
      <li>每新增一个节点，它下游所有节点的坐标都得跟着调，改动量和图的大小成正比。</li>
      <li>写死的坐标记不住「为什么在这里」——依赖关系一变，位置不会自动跟着变。</li>
      <li>手工拖动的结果依赖于某次操作，换个环境、换个人就复现不出来。</li>
      <li>一旦用户把图拖乱，没有一键恢复的能力，只能指望撤销。</li>
    </ul>

    <h2>依赖关系算位置</h2>
    <p>
      不推翻「位置由数据决定」，而是把这句话再推一步：位置不是人给的，而是<strong>算法从依赖关系里算出来的</strong>。整件事拆成两半——用一个纯函数算出「id 到坐标」的映射，再拿着这个映射逐个写回节点。写回用 <code>updateNode(id, { position })</code>，最后 <code>await fitView({ padding, duration })</code> 把整张图收进视野。
    </p>
    <p>
      真正的核心在第一步，也就是分层。这里用的是 Kahn 算法的思路：<strong>按入度一层一层往下推，每个节点的层号取所有前置节点层号的最大值加一</strong>。展开成步骤是这样：
    </p>
    <ol class="lesson-steps">
      <li><strong>建图统计入度。</strong>遍历所有边，按 <code>source → target</code> 登记邻接关系，并给 <code>target</code> 的入度加一。指向不存在节点的边和自环直接跳过，它们不构成有效的先后关系。</li>
      <li><strong>找起点。</strong>入度为 0 的节点没有任何前置依赖，全部入队，层号记为 0，它们是图的第一层。</li>
      <li><strong>逐层推进。</strong>出队一个节点，遍历它的后继：把后继的层号更新为「当前层号 + 1」与「已有层号」中的较大值，同时把后继的入度减一；某个后继的入度减到 0 时，说明它的前置都已安排妥当，可以入队。</li>
      <li><strong>处理环。</strong>队列排空后仍剩余入度的节点，就是陷在环里、永远凑不齐前置的点。算法把它们统一追加到最后一层的后面，<strong>保证过程一定会终止</strong>。</li>
      <li><strong>换算坐标。</strong>层号决定主轴位置——层号乘以「节点尺寸 + 层间距」；同层内的序号决定副轴位置——序号乘以「节点尺寸 + 节点间距」。方向为从左到右时主轴落到 <code>x</code>，从上到下时主轴落到 <code>y</code>。</li>
    </ol>
    <p>
      第三步里那个「取较大值」是容易被忽略的关键。它保证一个节点永远排在<strong>它所有前置节点</strong>的右边，而不只是排在最早那个前置的右边——也就是取最长路径。若图里存在 <code>A → B → D</code> 与 <code>A → D</code> 两条路径，<code>D</code> 的层号会跟着更长的链走到 2，绝不会因为一条捷径而提前窜到 B 前面去。
    </p>
    <div class="lesson-box warn">
      <strong>两个必须记住的约束：</strong>第一，<strong>环在流程图里是常态而不是意外</strong>（比如「驳回后回到上一环节」），算法必须显式处理它，否则队列永远推不完，程序直接卡死。第二，<strong>坐标计算用到了节点尺寸</strong>，卡片一旦改大小，<code>nodeWidth</code>、<code>nodeHeight</code> 与间距参数要同步更新，不然排好的图又会重新叠在一起。
    </div>
    <p>
      还有一层工程上的好处值得交代：把整件事写成<strong>纯函数</strong>——输入节点与边，输出一个坐标映射 <code>Map</code>，过程中不碰任何响应式状态。这样它既好写单元测试（给定图结构，断言首层 <code>x</code> 最小、最长依赖链的节点层号最大），也方便日后换成 dagre、elkjs 这类更成熟的布局引擎：<strong>换算法只需换那个纯函数，写回的数据流一点不动</strong>。
    </p>
    <p>
      布局只改写 <code>position</code>，不碰 <code>data</code>，也不碰连线。所以用户可以随意拖动、随意摆放，随时点一下「自动布局」就能恢复整齐——手工的自由和自动的秩序可以共存。
    </p>

