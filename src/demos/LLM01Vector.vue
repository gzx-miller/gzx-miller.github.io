    <div class="llm-question"><strong>开场问题：</strong>计算机只认识数字，它怎么知道「猫」和「老虎」比「猫」和「金鱼」更像？</div>

    <h2>提出问题</h2>
    <p>假设你在写一个程序，希望它能回答「猫、老虎、金鱼——哪两个更像」。你脱口而出「猫和老虎」，理由是「都是猫科、长得像」。但问题来了：<strong>计算机不懂「猫科」、不懂「长得像」，它只认识数字。</strong>你没法把一只猫塞进 CPU，只能给它数字。那么，如果只允许用数字描述一只动物，你打算怎么描述？</p>

    <h2>最小方案</h2>
    <p>最省事的做法：给每种动物打一个「体型分」（0 到 1）。金鱼 <code>0.02</code>、猫 <code>0.25</code>、狗 <code>0.45</code>、鳄鱼 <code>0.50</code>、老虎 <code>0.90</code>。瞬间，「像不像」变成了可计算的东西——两个数的差越小就越像：距离(猫,老虎)＝|0.25−0.90|＝0.65，而距离(猫,金鱼)＝|0.25−0.02|＝0.23。虽然结论反了，但这个方案做对了一件大事：<strong>把「比较两个事物」变成了「比较两个数字」</strong>，这个思想要保留。</p>

    <h2>发现不足</h2>
    <ul>
      <li>在一个数字的世界里，狗和鳄鱼成了「天造地设的一对」——只因为它们差 0.05，体重差不多。</li>
      <li>把一只动物压成一个数时，丢掉了太多信息：性格、习性、危险程度全没了。</li>
    </ul>

    <h2>迭代</h2>
    <p>不推翻「用数字描述」，给每只动物两个数 <code>(体型, 凶猛)</code>，一个当横坐标、一个当纵坐标，从数轴升级到平面。狗和鳄鱼在横轴上仍贴着，但「凶猛」这一轴把它们狠狠拉开（距离从约 0.05 变成约 0.70）。</p>
    <p>关键的一步出现了：你把一只动物写成了一组<strong>有顺序的数字</strong>——<code>狗 = [0.45, 0.20]</code>。这组数字，数学上就叫<strong>向量</strong>。数字的个数叫<strong>维度</strong>，刚造的是 2 维向量。同一个向量有三副面孔，说的是同一件事：它是<strong>一列数字</strong>（计算机看到的）、平面上<strong>一个点</strong>（画出来的）、从原点指向那个点的<strong>一支箭头</strong>（最好用的视角）。</p>
    <p>再往下：体型和凶猛都接近的猫和狐狸怎么区分？再加一维「是否家养」；会飞的和会游的？再加。每发现一种区分不开，就<strong>加一个维度</strong>。3 个数是空间里的点，4 个、100 个数画不出来，但数学不在乎——距离照样算、相似照样比。GPT 一类大模型里每个词就是一个上万维的向量（GPT-3 用了 12288 维），没人指定「体型」「凶猛」，这些维度是模型自己从海量文本里学出来的，但思想和你今天发明的完全一样。</p>

    <h2>总结</h2>
    <p>向量，就是给事物拍的一张「数字照片」：用一组有顺序的数字捕捉特征，于是「像不像」这种模糊的直觉，第一次变成了可以计算的距离。</p>
