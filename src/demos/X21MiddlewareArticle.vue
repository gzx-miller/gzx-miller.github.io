    <h2>总结</h2>
    <p>
      中间件解决的是「横切逻辑往哪儿放」：鉴权、语言、分流这类对一批路径生效的规则，从几十个页面里收拢到一处，并在渲染之前完成。代价是它挂在请求主链路上，所以要限定匹配范围、保持轻量、避开不兼容的依赖。
    </p>
    <div class="lesson-term">
      <span class="term-name">「中间件（middleware）」</span>在请求到达路由渲染之前运行的统一入口，可放行、重定向或重写，并可修改请求头与响应头，适合鉴权、多语言检测、A/B 测试与灰度发布。它运行在独立运行时，不能直接用 Node 专有 API，依赖需兼容；用匹配配置限定路径以免静态资源也走一遍；新版本中该文件已更名为代理，旧名仍可用但属弃用。
    </div>
