    <div class="lesson-question">
      <strong>开场问题：</strong>后台的「没登录就跳登录页」，你在十几个页面顶上各抄了一遍，结果新加的页面忘了抄，直接被陌生人打开——有没有一个地方，能在页面开始渲染之前就统一拦下来？
    </div>

    <h2>提出问题</h2>
    <p>
      你在做一个带后台的管理系统。有两类需求：一是所有后台路径都要先校验登录状态，没登录的一律挡在门外；二是站点要能按用户的语言偏好自动跳到对应语言版本。这两件事听起来不相关，但它们有一模一样的形状——<strong>都发生在「请求到达页面之前」，都要对一批路径统一生效</strong>。
    </p>
    <p>
      如果把它们写进每个页面，就等于把一条通用规则复制粘贴到几十个地方。复制得越多，越容易漏；而且检查发生在页面已经开始渲染之后，等于先干了一半活再把人赶走，白费力气。
    </p>

    <h2>最小方案</h2>
    <p>
      最直接的做法是「哪儿需要就在哪儿检查」：在每个后台页面或布局的开头读一下登录态，没有就跳走。它的好处是直观：打开文件就能看到它对谁负责。
    </p>
    <p>
      但它把「横切关注点」当成了「页面自身的逻辑」。鉴权、语言、分流这些规则本质上属于整个站点，不属于任何单个页面；<strong>把它们分散进页面，就等于让每个页面各自实现一遍同一套规则</strong>。
    </p>

    <h2>发现不足</h2>
    <ul>
      <li>同一段检查在几十个文件里重复，新页面一旦忘记沿用就直接裸奔。</li>
      <li>检查发生在渲染阶段，页面已经开始执行才被拦下，浪费了服务端计算。</li>
      <li>想改规则（比如换登录路径）要挨个文件搜一遍，容易漏改。</li>
      <li>语言检测、灰度分流这类逻辑没有天然归属，塞进哪个页面都别扭。</li>
      <li>没法在请求进入之前就完成重定向，用户可能先看到一个中间状态。</li>
    </ul>

    <h2>迭代</h2>
    <p>
      把这类逻辑收拢到一个固定位置：放在项目根目录（或源码目录）下的中间件文件。它<strong>在每个请求、路由开始渲染之前运行</strong>，你可以在这里读写请求信息、决定放行、改道或改写，然后再把请求交给后面的渲染流程。
    </p>
    <p>
      它对外提供三种基本动作，理解了这三个就够用：
    </p>
    <ol class="lesson-steps">
      <li>放行——让它继续走正常流程，可以顺带修改请求头或响应头。</li>
      <li>重定向——把用户送到另一个地址，浏览器地址栏会随之变化，适合鉴权与语言跳转。</li>
      <li>重写——地址栏不变，但实际渲染另一个路径的内容，适合 A/B 测试与灰度发布。</li>
    </ol>
    <p>
      用在鉴权上，就是读一下会话凭据：如果访问的是受保护路径却没有凭据，直接重定向到登录页；如果已经登录却访问登录页，就反向送回后台。用在分流上，是从凭据里读一个版本标记，没有就随机分配一个并写回，再把请求重写到对应版本的页面——用户看到的地址不变，内容却按分组呈现。
    </p>
    <p>
      用在多语言上，是先判断路径里是否已经带了语言前缀：没有的话，从凭据或请求头里的语言偏好推断一个语言，再重定向到带前缀的地址。这个模式在下一篇会展开成完整的国际化方案。
    </p>
    <p>
      还有一个很实用的能力：往请求头注入自定义信息（如当前路径或用户标识），下游的服务端组件即可读到它。
    </p>
    <p>
      但它挂在请求主链路上，所以要用配置项限定匹配的路径范围，避免连静态资源、图片这类请求也走一遍逻辑，白白增加开销。
    </p>
    <div class="lesson-box warn">
      <strong>三个必须知道的限制：</strong>中间件运行在独立的运行时里，不能直接使用 Node 专有的 API，引入的依赖必须与之兼容；它默认要对匹配路径在缓存前执行，所以逻辑要尽量轻；另外新版本已经把这个文件更名为代理，旧文件名仍可用但属于弃用状态，新建项目建议用新名字。
    </div>

