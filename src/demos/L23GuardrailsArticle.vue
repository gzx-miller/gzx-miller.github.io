    <h2>校验层的嵌入</h2>
    <p>
      护栏解决的是「模型输出不可控」。做法是在调用前后插校验层：输入侧挡注入与有害内容，输出侧用 schema 校验格式、用审核规则检查合规与业务范围，不通过就重试、改写或降级，并把每一次拦截记进日志。约束一旦从提示词里搬出来，才真正可检查、可复盘。
    </p>
    <div class="lesson-term">
      <span class="term-name">「护栏（Guardrails）」</span>指在 LLM 调用前后插入的校验层：输入侧拦提示注入与有害内容，输出侧用 schema 校验格式、用审核规则检查合规与业务范围，不通过则<strong>重试、改写或降级</strong>。边界：它是模型外的确定性防线，替代不了模型自身的对齐；规则应可配置、可灰度，误伤正常提问时能快速调整阈值与话术；所有拦截都要留日志以便审计与迭代。
