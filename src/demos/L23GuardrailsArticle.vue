    </div>

    <h2>概率模型的失控</h2>
    <p>
      LLM 是一个概率模型，输出天生不可控：格式可能走样、可能一本正经地编造事实、也可能被<strong>提示注入</strong>牵着走。更麻烦的是，提示词和用户输入待在<strong>同一条上下文里，没有谁比谁更权威</strong>——你写在 system 里的规则，用户可以用一句「忽略上面」尝试覆盖。
    </p>
    <p>
      只靠「把提示词写得更严厉」来防守，会把三笔成本留给你：
    </p>
    <ul>
      <li>它只是自觉，不是保证：模型这一轮听话，下一轮未必。</li>
      <li>遇到注入就失守：规则和输入平级，用户永远有机会覆盖它。</li>
      <li>没有审计：出了问题既说不清是哪一步放过的，也没法据此收紧规则。</li>
    </ul>
    <p>
      要回答的是：<strong>怎样在模型之外，加一道不依赖模型自觉、能够被检查和复盘的确定性关卡？</strong>
    </p>

    <h2>调用前后检查</h2>
    <p>
      最直接的做法：在调用前后各插一道检查。用户输入进来先过一遍安全审核（用一段审核提示词让模型判断是否含有害内容、是否在诱导越权），模型回答出去之前再过一遍合规检查。
    </p>
    <p>
      这个方案做对了一件事：<strong>它把「约束」从模型的脑子里搬到了调用链上</strong>。检查成了一个个独立、可替换、可复盘的步骤，而不是藏在提示词里的一句期望。
    </p>

    <h2>自审机制漏洞</h2>
    <ul>
      <li>用同一个模型审自己，等于让它护着自己：一段擦边的回答很可能被判成安全，审核需要独立的提示词与判定标准。</li>
      <li>只查输入不够：幻觉、隐私泄露、跑题这些毛病都是模型<strong>生成出来</strong>的，输入侧根本看不见。</li>
      <li>只查输出又太晚：有害输入已经进了上下文，甚至已经消耗了 token，才在出口被拦下。</li>
      <li>拦下来之后怎么办没说清：直接抛一个报错，用户体验比不拦还差。</li>
    </ul>

    <h2>双侧护栏补齐</h2>
    <p>
      不推翻「插检查点」，而是把两侧、动作、格式和日志四条线补齐。
    </p>
    <ol class="lesson-steps">
      <li><strong>定义规则</strong>：把格式校验、内容安全、业务范围写成明确的判定项。</li>
      <li><strong>输入护栏</strong>：用户提问进来先检查是否合法、是否命中提示注入。</li>
      <li><strong>输出护栏</strong>：模型回答出去前校验格式与合规，不通过就重试或改写。</li>
      <li><strong>记录</strong>：所有拦截与修正都落日志，供审计和后续调整规则。</li>
    </ol>
    <p>
      第一步先补<strong>两侧都查</strong>。输入护栏管「能不能问」，输出护栏管「能不能答」——它们防的是不同的东西：前者挡住有害提问和提示注入，后者挡住模型自己跑出来的幻觉、跑题、隐私和不当建议。少任何一侧，都会漏掉一整类风险。
    </p>
    <p>
      第二步补<strong>拦下之后的动作</strong>。护栏的价值不在于「报错」，而在于「还有别的出路」：可以<strong>重试</strong>（把安全约束写进提示词后重新生成），可以<strong>改写</strong>（比如把输出里的手机号、邮箱、身份证号直接脱敏），也可以<strong>降级</strong>（超纲问题回一句礼貌的拒绝话术，而不是冷冰冰的异常）。
    </p>
    <p>
      第三步补<strong>格式护栏</strong>。这是工程里最常用、也最划算的一类：让模型按预定义 schema 输出，再用 Zod 在程序侧校验，字段缺失或类型不对就当作不合格。它同时防住了「格式不稳定」和「内容不合规」两种问题，也让后续重试有据可依。
    </p>
    <p>
      最后补<strong>日志</strong>。每一次拦截和修正都要记下来，你才能回答「上周那批正常提问为什么被误伤」「哪条规则从来没触发过」。护栏系统好不好用，靠的就是这些可复盘的数据。
    </p>
    <div class="lesson-box warn">
      <strong>护栏不是越多越好：</strong>规则叠得太厚会误伤正常提问、拖慢响应、推高成本。规则要<strong>可配置、可灰度</strong>，阈值和话术能在误伤出现时快速调整；医疗、法律这类敏感领域才需要更严格的护栏。另外，护栏是模型外的确定性防线，它替代不了模型自身的对齐。
    </div>

