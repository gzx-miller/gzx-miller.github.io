      <strong>开场问题：</strong>用户在输入框里打字，我并没有写任何赋值语句，代码里那个变量怎么就跟着变了？
    </div>

    <h2>报名表单构成</h2>
    <p>
      做一个活动报名表：姓名、邮箱两个输入框，外加一个「同意接收课程通知」的勾选框；三项都填齐之后，「提交报名」按钮才可点，否则置灰，并给出一句提示告诉用户还差什么。
    </p>
    <p>
      表单的本质是<strong>用户输入如何进入业务状态，并驱动按钮、提示这些反馈同步更新</strong>。看起来简单，但输入框有自己的行为——它保存着用户敲进去的字符，也保存着光标位置。麻烦在于，这份「界面上的事实」和「代码里的事实」默认是两份，需要有人把它们接起来。
    </p>

    <h2>手动监听赋值</h2>
    <p>
      最直接的做法：每个输入框都绑一个 <code>@input</code> 监听，回调里从事件对象上取出当前值，手动赋值给对应的变量；勾选框再单独绑一次。哪个字段要联动，就再补一段更新逻辑。
    </p>
    <p>
      这个方案做对了两件事：<strong>它承认「控件的变化是一类事件」</strong>，也<strong>承认「业务状态是唯一源头」</strong>。把值搬进变量之后，校验、提交都能基于同一份数据来做，思路是对的。
    </p>

    <h2>样板代码膨胀</h2>
    <ul>
      <li>字段一多，样板代码成倍增长，每个控件都要写一遍「取事件对象、读值、赋值」。</li>
      <li>漏绑一个监听，那个字段就永远停在初始值，界面上看着正常，提交时才发现是空的。</li>
      <li>用户输入的首尾空格会原样进入状态，导致「看起来填了、实际校验不过」这类诡异现象。</li>
      <li>输入框给出的值默认是字符串，数字字段需要额外转换，转换逻辑散落在每个回调里。</li>
      <li>校验判断散在各处，提交按钮的启用条件与提示文案容易各写一套，互相不一致。</li>
    </ul>

    <h2>双向绑定语法糖</h2>
    <p>
      把「取事件、读值、赋值」这三步收成一句声明，这就是 <code>v-model</code>。它并不是新机制，而是一个<strong>语法糖</strong>：对文本输入而言，它展开成「把状态绑到 <code>value</code> 属性」加「监听 <code>input</code> 事件」，从而把表单控件与响应式状态连接成<strong>双向关系</strong>——状态变，输入框显示跟着变；用户输入，状态跟着变。样板代码就此消失，剩下的是「这个字段对应哪个状态」这条唯一信息。
    </p>
    <p>
      接着处理「输入细节」。空格、类型、触发时机这些事每个项目都会遇到，与其在每个回调里重复，不如在同步之前统一处理，这就是<strong>修饰符</strong>：
    </p>
    <ul>
      <li><code>.trim</code> 在同步前去掉首尾空格，从源头避免「看起来填了」的假象。</li>
      <li><code>.number</code> 把输入结果按数字处理，省去手写转换。</li>
      <li><code>.lazy</code> 改变同步时机，从「每次输入」变成「失焦或回车」，减少高频更新。</li>
    </ul>
    <p>
      然后是状态的组织方式。表单字段往往属于<strong>同一个业务对象</strong>，把它们收进一个 <code>reactive</code> 对象，比散落成好几个独立变量更便于组织，提交时也能整体取用。
    </p>
    <p>
      最后是校验。直觉做法是在提交时写一串判断，但更贴合响应式的做法是<strong>用 <code>computed</code> 表达校验结论</strong>：把所有规则写进一段派生计算，得出「是否可提交」，按钮的禁用状态与提示文案都读同一个结果。这样校验逻辑只有一处，输入一变，按钮和提示自动跟进，不会出现按钮亮了却提示「请补全信息」这种自相矛盾。
    </p>
    <div class="lesson-box warn">
      <strong>两条不能省的原则：</strong>前端校验的价值在于<strong>即时反馈</strong>，真实提交仍然必须依赖服务端校验，二者缺一不可；另外<strong>不要只用「禁用按钮」表达错误</strong>——用户看到灰按钮并不知道差在哪，必要时应给出明确提示。字段较多时，可以先把校验规则集中定义，再交给 <code>computed</code> 汇总结果。
    </div>
    <ol class="lesson-steps">
      <li>用户填写姓名、邮箱并勾选同意项。</li>
      <li><code>v-model.trim</code> 把输入同步到表单状态，同时去掉首尾空格。</li>
      <li>用一个 <code>computed</code> 计算「是否可以提交」，按钮状态与提示文案都读它。</li>
      <li>提交后清空表单，验证双向绑定的状态同步复位。</li>
    </ol>

