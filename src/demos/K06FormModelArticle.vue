      <span class="term-name">「双向绑定」</span>指 <code>v-model</code>，它本质是「绑定值 + 事件监听」的语法糖：对文本输入展开为 <code>value</code> 绑定与 <code>input</code> 事件处理，把表单控件与响应式状态连成双向关系。修饰符 <code>.trim</code>、<code>.number</code>、<code>.lazy</code> 在同步前处理常见输入细节；校验用 <code>computed</code> 表达，让提交按钮状态与提示文案随输入自动更新，且服务端校验始终不可省略。
