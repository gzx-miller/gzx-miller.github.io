    <h2>输入状态通路</h2>
    <p>
      表单处理的核心是把「界面上的输入」和「代码里的状态」接成一条双向通路：<code>v-model</code> 负责连接，修饰符负责在同步前清洗输入细节，<code>reactive</code> 把同属一个业务对象的字段组织起来，<code>computed</code> 把校验收成唯一结论。前端只管即时反馈，最终的正确性仍然交给服务端把关。
    </p>
