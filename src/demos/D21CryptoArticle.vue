    <h2>用途导向的选型</h2>
    <p>
      摘要算法的用途，本质上是先分清「要不要能解回来、要不要证明真伪」：能解回来用加密，证明真伪用带密钥的 HMAC，而验证密码这个特殊场景要的既不是快也不是可逆，而是「不可逆 + 每个用户随机 + 慢到打败暴力枚举」。加盐慢哈希把这三点一次凑齐，密码存储才算真正立住。
    </p>
    <div class="lesson-term">
      <span class="term-name">「加盐慢哈希」</span>指先用每个用户独立的随机盐参与运算，再交给一个刻意拖慢的密钥派生函数（<code>scrypt</code>、<code>PBKDF2</code>、<code>bcrypt</code>、<code>argon2</code>）反复迭代，产出定长摘要的密码存储方式。边界：盐不是密钥、无需保密，但要和摘要一起存；盐只解决「相同密码产生相同摘要」，真正拉开暴力破解成本的是「慢」；<code>md5</code>/<code>sha1</code> 等快速哈希无论加不加盐都不能用于存密码；比对必须用常数时间的 <code>timingSafeEqual()</code>。
    </div>
