      <strong>开场问题：</strong>数据库被拖走了一份拷贝，你原本很镇定——密码存的是哈希，反推不出明文。可审计报告一句话把你钉住：库里三千个账号，只对应不到一百个不同的哈希值。也就是说大量用户用了同一个密码，攻击者只要撞破其中一个，剩下的人一起完蛋。
    </div>

    <h2>通用哈希的隐患</h2>
    <p>
      你最初的做法大概是这样：注册时算一遍 <code>createHash('sha256')</code> 把摘要存进库，登录时把输入的密码再算一遍，和库里的值比对。「只存摘要、不存明文」是密码存储的底线，方向没有错。
    </p>
    <p>
      问题在于，通用哈希函数有两个特性恰好成了攻击者的帮凶。它是<strong>公开且确定</strong>的——同样的输入永远得到同样的输出；它又是<strong>为快而生</strong>的——设计目标就是尽快算出结果。这两点合起来，埋下了三类只能由你来兜的隐藏成本：
    </p>
    <ul>
      <li>确定性意味着可以预计算：常见密码的哈希值是一张谁都能查的表，攻破一个就等于攻破一片。</li>
      <li>快意味着可以暴力枚举：主流 GPU 每秒能对 SHA-256 做数十亿次尝试，短弱密码几个小时就见底。</li>
      <li>没有随机意味着「相同密码 → 相同摘要」：拖库后统计频次，就能直接把「批量用同一密码」的账号圈出来。</li>
    </ul>
    <p>
      <strong>有没有一种存储方式，既保留「不可逆」，又让「撞破一个」不再等于「撞破一批」，同时让暴力枚举慢到不划算？</strong>
    </p>

    <h2>直存摘要的漏洞</h2>
    <p>
      最省事也最常见的做法：直接存 <code>sha256(password)</code>，登录时用同样的算法再算一次比对。
    </p>
    <p>
      这个方案确实做对了一件关键的事：<strong>哈希是单向的，明文永远不落库</strong>。哪怕整库泄露，攻击者拿到的也只是一串定长摘要，而不是用户的原始密码。这条底线必须保留——后面所有的补救都建立在它之上。
    </p>

    <h2>相同摘要的暴露</h2>
    <ul>
      <li>相同密码得到相同摘要：库里两个用户都用了 <code>123456</code>，两行哈希一模一样，破一个等于破一双。</li>
      <li>彩虹表可反查：<code>sha256('123456')</code> 是全网皆知的定值，攻击者不必爆破，查表即得明文。</li>
      <li>哈希太快：SHA-256 在消费级 GPU 上每秒可尝试数十亿次，八位小写字母的组合几小时就能穷举完。</li>
      <li>取巧会翻车：<code>md5</code> 与 <code>sha1</code> 已被证明存在碰撞，只适合做非安全的完整性校验，绝不能用于密码或签名。</li>
      <li>比对方式本身也可能泄密：用 <code>===</code> 逐字节比较会在第一个不同字节处提前返回，比较耗时会随匹配程度变化，留下时序攻击的缺口。</li>
    </ul>

    <h2>随机盐与慢哈希</h2>
    <p>
      先补<strong>随机盐</strong>。注册时用 <code>randomBytes(16)</code> 生成一段随机字节当盐，把它和密码一起送进哈希函数，最后把盐和摘要一并存储。之所以先补它：它是「相同密码产生相同摘要」这个最致命问题的直接解药，改动最小。盐不是秘密，不需要保密，它的作用只是让每个用户的计算结果都带上随机性——攻击者再想用一张彩虹表通吃，就得为每个盐各重算一张，成本瞬间爆炸。
    </p>
    <p>
      补完盐，还差一件事没解决：盐只防「预计算」，不防「在线暴力破解」，SHA-256 那个「快」的毛病还在。于是再补<strong>慢</strong>——改用刻意拖慢的密钥派生函数，把迭代次数（成本因子）作为参数显式调高，让单次校验耗时被人为拉到毫秒级，从而把每秒可尝试次数从数十亿压到几百：
    </p>
    <ol class="lesson-steps">
      <li>用 <code>randomBytes(16)</code> 为这个用户生成独立随机盐。</li>
      <li>用 <code>pbkdf2Sync(password, salt, 10000, 64, 'sha512')</code>，或 <code>scryptSync</code>，反复迭代得到摘要。</li>
      <li>把盐与摘要一起入库；校验时用同一个盐重算，再用 <code>timingSafeEqual()</code> 比对。</li>
    </ol>
    <p>
      生产里更省心的做法是直接上 <code>bcrypt</code> 或 <code>argon2</code>，它们把盐和成本参数一起编码进结果字符串，你不用自己维护这两样。注意 <code>timingSafeEqual()</code> 这一环：它做常数时间比较，不因内容不同而改变耗时，正是用来堵上前面那个时序缺口。
    </p>
    <p>
      顺着同一条「摘要用在哪」的线，还有几处边界要分清。<strong>完整性校验</strong>用裸哈希就够：<code>createHash('sha256')</code> 算文件校验和，用来确认下载没被改动。<strong>消息认证</strong>则必须换 <code>createHmac('sha256', secret)</code>——密钥参与运算，攻击者不知道密钥就伪造不出签名，这正是裸哈希与 HMAC 的分界：有没有密钥。而<strong>需要把数据解回来的机密性场景</strong>，用的是对称加密 <code>createCipheriv('aes-256-gcm', key, iv)</code>；GCM 自带认证标签（authTag），解密时校验它就能发现密文被改，<strong>IV 每次加密都必须重新随机生成、绝不能复用</strong>。至于密钥，一律通过环境变量或密钥管理服务提供，绝不硬编码进仓库；方案还要预留轮换路径，让旧密钥仍能解开历史数据。若需要「谁能加密、谁能解密」分离，才轮到 RSA 这类公私钥体系出场。
    </p>
    <div class="lesson-box warn">
      <strong>两个常见误区：</strong>一是以为「加了盐就安全」——盐只解决预计算，真正拉高暴力破解成本的是「慢」；二是以为可以自己在摘要上随便加个固定字符串当盐——固定值等于全局共用一个盐，起不到随机化的作用。<strong>盐必须每个用户独立、每次生成都随机。</strong>
    </div>

