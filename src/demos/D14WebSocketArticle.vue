    <h2>实时推送长连接</h2>
    <p>
      你已经用 WebSocket 做实时推送：一次握手之后连接一直开着，服务端随时可以把新消息推给客户端。这类长连接是聊天、协作、实时通知的底座，但它带来的问题和管理普通 HTTP 请求完全不同——<strong>一次请求答完就断，你根本没有「连接状态」要操心；而长连接要一直活着，就得有人负责确认它是不是真的还活着</strong>。
    </p>
    <p>
      麻烦在于，TCP 连接是「沉默」的。它不会主动告诉你对面已经掉线，链路上的路由器、NAT、负载均衡器也可能在空闲一段时间后<strong>静默地掐断</strong>这条连接，而两端的连接对象却仍然存在、状态栏上仍显示「已连接」。于是你要付的代价很具体：服务端以为自己还在跟一个活人说话，消息发出去却石沉大海；客户端以为自己还连着，界面却再没更新过。所以核心问题是：<strong>怎么及时知道一条长连接其实已经死了，并在它死掉之后可靠地接回来？</strong>
    </p>

    <h2>断线重连机制</h2>
    <p>
      最省事的做法：连上就一直用，什么也不管。客户端在 <code>onclose</code> 里直接重新 <code>new WebSocket(url)</code>，断了就立刻重连。
    </p>
    <p>
      这个方案做对了一件事：<strong>它承认了「连接会断」是常态</strong>，并给出了最小的补救——断了就再来一次。网络稳定、没有中间设备捣乱时，它确实能跑。
    </p>

    <h2>静默断开隐蔽性</h2>
    <ul>
      <li>它只认得「客户端主动感知到的断开」。被中间设备静默掐掉的连接，<code>onclose</code> 可能很久甚至永远不触发，那条「假死」连接就一直挂着。</li>
      <li>断线时立刻重连，一旦服务端正在重启，所有客户端会在同一时刻一起涌上来，形成<strong>重连惊群</strong>，把刚起来的服务再打挂一次。</li>
      <li>一直重连却没有上限，网络长时间不通时会变成停不下来的无效请求，白白耗电耗流量。</li>
      <li>服务端若只维护一张「连接表」却从不清理，死连接越积越多，广播时既浪费又容易出错。</li>
    </ul>

    <h2>心跳与退避重连</h2>
    <p>
      不推翻「断了就重连」，而是把它拆成两件独立的事：<strong>先用心跳主动探测连接是不是还活着，再用退避策略决定断了以后怎么重连</strong>。顺序不能反——不先发现「假死」，重连根本不会被触发。
    </p>
    <p>
      第一件事是<strong>应用层心跳</strong>。协议层的探活往往太慢、而且在很多网络环境里不生效，所以要在应用层自己确认：客户端和服务端按固定间隔互发一个极小的 <code>ping</code> / <code>pong</code> 消息，约定好「多久没收到对方的响应就算失效」，超时了就把这条连接<strong>主动关掉</strong>——关闭的动作会触发 <code>onclose</code>，把那条静默死亡的连接正式标记为已断开。这就补上了最小方案漏掉的第一类连接：客户端察觉不到的假死。
    </p>
    <p>
      第二件事是<strong>指数退避重连</strong>。断线后不要立刻重连，先等一小段再试；仍然失败就把等待时间翻倍（比如 1 秒、2 秒、4 秒、8 秒……），直到设一个上限。这样服务端短暂不可用时，重连压力会随时间自动减轻，而不是持续高压。但光有退避还不够：如果所有客户端都从「1 秒」起步，它们依然会在同一些时刻齐步重连。所以还要给每次等待加一点<strong>随机抖动（jitter）</strong>，把同一批客户端的重连时刻错开，从根上避免惊群。
    </p>
    <p>
      两件事补齐后，服务端这一侧的职责也清晰了：维护一张<strong>连接表</strong>，记录每个在线连接，据此向全部或指定客户端<strong>广播</strong>消息；心跳超时和连接关闭时，把失效项从表里清掉。这里有一条容易被忽视的运维要求——<strong>连接是持久资源，数量很贵</strong>。单机连接数要限制，心跳成功率、在线连接数、广播耗时都应做成可观测指标，否则连接一多，你连「哪里出问题」都看不到。当服务从一台扩到多台，某个节点上的连接表只认识自己那部分用户，跨节点广播还需要一条共享的发布订阅通道（例如 <code>Redis</code> 的 <code>Pub/Sub</code>）来把消息转发给其它实例。
    </p>
    <div class="lesson-box warn">
      <strong>两个必须记住的边界：</strong>其一，WebSocket 的鉴权要么在<strong>握手阶段</strong>完成、要么在<strong>首条消息</strong>里完成，它走的是升级后的自定义协议，<strong>不能直接复用 HTTP 那套中间件逻辑</strong>；其二，重连的等待时间一定要带<strong>随机抖动</strong>，否则退避只能缓解、不能消除惊群。
    </div>

