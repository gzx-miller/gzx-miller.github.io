    <h2>多步链信息保全</h2>
    <p>
      多步链的难点从来不在「串起来」，而在「串的时候别把信息漏掉」。默认只往下递最后一段输出，需要早期输入或需要同时用到多段中间结果时，就得显式地保留、透传、搬运——把这些决定写在链上，流程才既跑得通又看得懂。
    </p>
    <div class="lesson-term">
      <span class="term-name">「顺序链」</span>指把多个处理步骤首尾相接，前一步的输出作为后一步的输入依次执行。边界是：它默认只传递「最后一段输出」，如果你需要更早的输入，或需要某一步同时用到多段中间结果，必须显式地把它们保留或透传下去，否则会在链的后半段悄悄丢失。
