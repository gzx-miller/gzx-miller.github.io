    </div>

    <h2>逐步接力假设</h2>
    <p>
      多步链里最自然的假设是「上一步的输出，就是下一步的输入」。但真实的业务流程往往不是这样：后面某一步真正需要的，可能是<strong>一路上的好几段信息</strong>，其中还包括一段<strong>很早之前就确定、后来再没被用过</strong>的内容——比如最开始那个课程主题。
    </p>
    <p>
      一旦每步只把最后一段输出往下递，三笔成本立刻出现。
    </p>
    <ol class="lesson-steps">
      <li>想把早期输入留给后面的步骤，只能自己额外存变量、再手工接进去，接漏一处就丢一段上下文。</li>
      <li>字段一多，「谁该接给谁」全靠脑记，步骤一重排就得把接线全部重接一遍。</li>
      <li>整条链接了哪几步、中间丢了哪个字段，出问题时没有一个地方能一眼看出来。</li>
    </ol>
    <p>
      于是问题变成：<strong>当一步的输出不是下一步直接想要的输入时，中间那段「搬运」该由谁负责？</strong>
    </p>

    <h2>手动接力串联</h2>
    <p>
      最朴素的做法是按顺序接力：<code>const outline = await outlineChain.invoke({ topic })</code>，接着 <code>const detail = await detailChain.invoke({ outline })</code>，最后 <code>const summary = await summaryChain.invoke({ detail })</code>。上一步的结果直接当作下一步的入参。
    </p>
    <p>
      这个方案做对了一件事：<strong>确立了「上一步输出 = 下一步输入」这个基本流向</strong>。三步各自独立可测，顺序也一目了然。
    </p>

    <h2>早期信息丢失</h2>
    <ul>
      <li>走到第三步时，<code>topic</code> 早就不在手里了，想让摘要带上主题只能回头再算一次。</li>
      <li>第三步想同时用到 <code>outline</code> 和 <code>content</code>，可接力只递过来最后一段，前一段已经没了。</li>
      <li>「翻译 → 改写 → 配标题」这类链里，第二步其实需要的是<strong>原始中文</strong>，而不是第一步翻译出来的英文，接力却把原文冲掉了。</li>
      <li>步骤一多，每个中间结果都要单独起名，顺序一调就等于把整段代码重写。</li>
    </ul>

    <h2>传递内容对象化</h2>
    <p>
      不推翻「接力」，而是改变每一步传递的东西。第一步补<strong>把输入从「一个字符串」放宽成「一个对象」</strong>：让上一步不只交出正文，而是按名字交出一份「这次算出来的字段 + 需要继续带着的字段」。这样「要不要留下 topic」就从一件默认发生、容易丢的事，变成一次显式的决定。
    </p>
    <p>
      第二步补<strong>透传</strong>：用 <code>RunnablePassthrough</code> 把原始输入原样带过一层，例如在第一步的结构里同时给出 <code>outline</code> 和一个透传的 <code>topic</code>。先补它，是因为它精准治好了开场的病症——早期输入不再被扔在半路。
    </p>
    <p>
      第三步补<strong>形状搬运</strong>：后续某一步如果只想要对象里的某一个字段，就写一个小函数做映射，例如把整个对象转成模板要的那个变量组合，再交给 <code>invoke</code>。这个映射函数就是「数据形状的搬运工」——它写在哪里，谁往下传了什么，就摆在哪里，既可读也可查。
    </p>
    <p>
      最后补<strong>分支</strong>：当流程要根据内容选不同路径（技术问题走 A 链、投诉建议走 B 链），用 <code>RunnableBranch</code> 按条件挑一条执行。它和顺序链一样，本身也是可组合的 Runnable，因此可以和普通步骤混在一起搭。调试时同样把链拆成两截，先看上游交出的对象里到底有哪些字段，再决定下游该搬哪些。
    </p>
    <div class="lesson-box hint">
      <strong>一个判断口诀：</strong>只要某一步的输入里出现了「不是上一步刚产出的东西」，那它就必须被显式保留或透传，否则它一定会在这条链里消失。
    </div>

