    <h2>隐式期望显式化</h2>
    <p>
      提示词工程本质上是「把隐式期望显式化」：用角色定基调、用清晰指令定任务、用 Few-shot 定标准、用思维链定推理过程、用结构化输出定格式，再靠真实样例迭代与回归。模型的能力没变，变的只是你喂给它的约束有多清楚。
    </p>
    <div class="lesson-term">
      <span class="term-name">「少样本提示（Few-shot Prompting）」</span>指在提示词里给出少量「输入到期望输出」的示例，让模型照着示例对齐输出格式与判别标准；它<strong>不更新模型参数</strong>，只通过本次上下文影响行为。边界：示例要典型并覆盖边界类别，数量和顺序都可能影响结果；示例过多会挤占上下文、推高成本；它与「微调」（真正改动参数）不是一回事。
