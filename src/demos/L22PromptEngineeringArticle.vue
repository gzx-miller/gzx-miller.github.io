    <h2>自然语言的模糊性</h2>
    <p>
      LLM 的行为由输入决定，可自然语言输入天生模糊。「把这段解释一下」——解释给谁看？多长？什么格式？你心里有数，但没写下来，模型只能靠猜。猜到什么算什么，于是每次结果都飘。
    </p>
    <p>
      只写一句需求的旧做法，把三笔成本留给了你：
    </p>
    <ul>
      <li>结果不稳定，同一个问题要重跑几遍，再挑一个勉强能用的。</li>
      <li>格式不统一，想拿 JSON 却总是收到一段话，程序没法直接消费。</li>
      <li>判别标准藏在你的脑子里——什么算「正面」、什么算「简洁」，模型无从对齐。</li>
    </ul>
    <p>
      要回答的是：<strong>输入到底该怎么写，才能让模型的输出稳定、可控、能直接进下游？</strong>
    </p>

    <h2>要求逐步具体化</h2>
    <p>
      最省事的一步是把要求写具体：把「解释一下」换成「用 200 字，分三段——定义、原理、应用场景，面向初学者」。
    </p>
    <p>
      这个方案做对了一件事：<strong>它把隐式的期望变成了显式的约束</strong>。字数、结构、面向谁，从「模型猜」变成「你定」。有了这几条硬指标，输出至少不会再漫无边际。
    </p>

    <h2>判别标准的缺失</h2>
    <ul>
      <li>光有指令，判别标准还是模糊：让模型给评论打「正面 / 负面 / 中性」，它可能回你一个「比较正面」——既不在你给的标签里，格式也不齐。</li>
      <li>复杂推理直接要答案容易错：模型一步跳到结论，中间的推导被跳过，错了也无从检查。</li>
      <li>输出格式依然不稳：你要求 JSON，它可能先来一句「好的，这是结果」，或者套一层代码围栏，下游解析直接失败。</li>
      <li>同一套措辞换个领域就失灵，没有可复制的套路，只能靠灵感。</li>
    </ul>

    <h2>模糊逐层显式化</h2>
    <p>
      不推翻「把要求写具体」，而是按「谁在说、看样例、再推理、给结构」的顺序，一层层把模糊补成显式。
    </p>
    <ol class="lesson-steps">
      <li><strong>给角色</strong>：在 system 提示里框定身份，比如「你是一位资深前端架构师」。</li>
      <li><strong>说任务</strong>：把要做的事、输出长度与结构写清楚。</li>
      <li><strong>给样例</strong>：用几组「输入到期望输出」的样例把判别标准对齐。</li>
      <li><strong>引导推理</strong>：要求模型先分步思考，再给结论。</li>
    </ol>
    <p>
      第一步先补<strong>角色</strong>，因为它一次性约束了全局：语气、关注点、用词深浅。同样是给代码建议，「资深架构师」和「科普作者」给出的侧重完全不同。为什么先补它？因为它是后面所有要求的总基调。
    </p>
    <p>
      第二步补<strong>示例</strong>，也就是 Few-shot。判别标准光用文字描述总有歧义，但当你在提示里放上「正面 / 负面 / 中性」各一条样例，模型看到的是「长这样才算正面」。样例把抽象标签变成了看得见的标尺，尤其适合分类、改写这类「你说的和我理解的不一样」的任务。
    </p>
    <p>
      第三步补<strong>思维链</strong>（Chain of Thought）。对数学题、多步推理这类任务，让模型「一步步思考再给结论」，等于把一步到位的猜测拆成一段可检查的推导。中间步骤暴露出来后，你既能看出它在哪一步想歪，复杂任务的整体准确率也会提高。
    </p>
    <p>
      第四步补<strong>结构化输出</strong>。明确要求按 JSON 或指定字段返回，把「格式」也变成显式约束；需要生产级稳定时，再配合输出解析器（如 Zod schema）在程序侧强制校验——提示词负责引导，解析器负责兜底。
    </p>
    <p>
      最后一件事常被忽略：提示词是要<strong>迭代</strong>的。别指望一次写对，要拿真实样例反复跑、对比、修正；而且要像对待代码那样做版本管理与回归测试——只改了几个字，可能弄好了一个场景、弄坏了另一个。事实类任务用低温度压住随机性，创作类任务才调高温度换取多样性。
    </p>
    <div class="lesson-box warn">
      <strong>提示词改动会「牵一发动全身」：</strong>它在上下文里不是独立模块，改了 A 段的措辞，可能影响 B 场景的判断。每次改动都要拿一组固定样例回归验证，别等上线后才发现旧功能退化。
    </div>

