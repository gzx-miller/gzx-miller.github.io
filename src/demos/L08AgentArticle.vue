    <h2>固定流程边界</h2>
    <p>
      这条链的每一步，都是你在写代码时就钉死的：先检索、再生成、再解析，次序固定、次数固定。这在「输入永远长一个样」的任务里没问题。可一旦任务需要<strong>根据中间结果临时决定下一步做什么</strong>，写死的链就彻底不够用了：先算数还是先查文档，取决于题目本身；要不要再查一次，取决于上一次查到的东西够不够。
    </p>
    <p>
      坚持「人工把流程写死」，三笔成本都得你自己扛。
    </p>
    <ol class="lesson-steps">
      <li><strong>分支穷举不完</strong>：你得预判用户所有可能的问法，用条件判断一条条覆盖，问法稍微一变就漏。</li>
      <li><strong>表达不了「看结果再决定」</strong>：真正需要的是「这一步的产出决定下一步走哪条路」，而静态的链根本无法在运行中改道。</li>
      <li><strong>加一项能力就要改全流程</strong>：想让它会算数、会查天气，就得回头改整条链的结构，越改越怕动。</li>
    </ol>
    <p>
      于是问题变成：<strong>能不能别再替模型把步骤排死，而是把「下一步做什么」的决定权，交给模型自己？</strong>
    </p>

    <h2>上下文资料堆叠</h2>
    <p>
      最朴素的做法是把所有可能用到的资料、能想到的能力，一股脑塞进上下文，提前告诉模型「你有这些信息，自己看着用」。它跑得简单，也确实承认了一件重要的事：<strong>模型光靠自己脑子里的东西不够用，它需要外部信息</strong>。这个前提立住了，后面才有得谈。
    </p>

    <h2>堆叠资料成本</h2>
    <ul>
      <li>资料全塞进去，提示词又长又贵，还常常塞不下——文档一多就超了上下文。</li>
      <li>精确算式靠「塞资料」救不了：不管上下文里有多少数字，模型算 <code>128</code> 乘 <code>64</code> 仍可能报错。</li>
      <li>资料是死的：查不到实时天气、读不到你数据库里的最新库存。</li>
      <li>它只能在「已有的资料」里挑，没法自己决定「我该去取什么、去哪儿取」。</li>
    </ul>

    <h2>能力工具化封装</h2>
    <p>
      不推翻「把外部能力交给模型」，而是改成让模型自己决定「什么时候、用哪一个」。第一步补<strong>工具</strong>：把每一项外部能力做成一个可以被调用的函数，附上名字、用途和参数。有了工具，模型才第一次有了「动手」的可能——但光有工具还不够，它还得知道什么时候该动手。
    </p>
    <p>
      第二步补<strong>一个推理循环</strong>：让模型先想、再动手、再回看。这就是 <strong>ReAct</strong> 模式，一圈由三步组成。
    </p>
    <ol class="lesson-steps">
      <li><strong>Thought（思考）</strong>：模型先想——现在缺什么信息？要不要调工具？该调哪个？</li>
      <li><strong>Action（行动）</strong>：选定一个工具，给出参数，真正执行。</li>
      <li><strong>Observation（观察）</strong>：把工具返回的结果读回来，作为下一轮思考的新输入。</li>
    </ol>
    <p>
      拿到观察结果后回到第一步，再判断信息够不够：够了就给出<strong>最终答案</strong>，不够就再转一圈。核心在于「推理」和「行动」是<strong>交替</strong>发生的——模型不是在最后一刻才做决定，而是每一步都根据刚刚看到的东西重新决策。
    </p>
    <p>
      第三步补<strong>驱动器</strong>：<code>AgentExecutor</code> 负责把这个循环真正转起来——每一轮把模型的思考、工具调用、观察结果拼回给它，直到它给出最终答案。它还必须带一个<strong>最大迭代次数</strong>（<code>maxIterations</code>），因为模型的循环是不可预测的，没有上限就可能一直绕下去、把 token 烧光。
    </p>
    <p>
      最后补两条边界：<strong>工具描述写得清不清楚，直接决定模型挑不挑得对</strong>；而简单任务其实用一条普通链更可控、更便宜——不是所有任务都值得上 Agent。开着 <code>verbose</code> 把每轮的思考和工具调用记下来，出问题时才有回放可查。
    </p>
    <div class="lesson-box warn">
      <strong>Agent 不是「更聪明的链」：</strong>它的推理过程不可预测，同样的输入两次可能走不同的路，而每一轮绕圈都在消耗 token。所以它需要迭代上限和日志回放，也需要一个兜底——Agent 走不出结果时，能回退到一条确定的简单链，而不是把用户晾在那儿。
    </div>

