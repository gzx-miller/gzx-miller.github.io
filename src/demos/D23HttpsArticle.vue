    <h2>加密与身份证明</h2>
    <p>
      HTTPS 由两部分构成：TLS 负责把流量加密，证书链负责证明「对方是它自称的那台服务器」。只做前者，你得到的是一条「跟身份不明者加密对话」的通道；只有把证书一路验到受信任的根、把废弃协议关掉、再用 HSTS 逼着全站走加密，并把私钥与证书当密钥一样管理起来，HTTPS 才算真正成立。
    </p>
    <div class="lesson-term">
      <span class="term-name">「证书链」</span>是从服务器证书经由中间 CA 一路签名到受信任根 CA 的验证路径，客户端逐环校验签名与域名，最终把身份锚定在系统或浏览器内置的根证书上。边界：根证书由操作系统与浏览器预置，<strong>不随站点下发</strong>；自签名证书依然提供加密，但不在信任库里，浏览器会报「不安全」；服务器漏发中间证书会让链断掉，部分客户端直接拒绝握手；CA 签发的正式证书还需在到期前续期，否则验证链会因过期而失效。
