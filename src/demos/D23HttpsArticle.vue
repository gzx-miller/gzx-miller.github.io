      <strong>开场问题：</strong>你用 OpenSSL 生成了一对自签名证书，<code>https.createServer</code> 也跑起来了，浏览器地址栏却挂着「不安全」的红色警告；同事那边少发了一层中间证书，Chrome 干脆拒绝连接，而加 <code>-k</code> 跳过校验的 <code>curl</code> 却能通。同样是「用了 HTTPS」，为什么一个警告、一个能连、一个被拒？
