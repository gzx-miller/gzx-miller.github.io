    <h2>明文传输的风险</h2>
    <p>
      HTTP 是明文传输，链路上的任何一跳都能偷看和改写你的请求。你想「加密」，于是把服务从 <code>http</code> 换成 <code>https</code>。但「加密」其实只解决了一半问题，旧办法留下的三笔成本，必须由你自己补上：
    </p>
    <ul>
      <li>明文可被窃听、篡改：公共 WiFi 能给你注入广告，运营商能看到你请求里的全部内容。</li>
      <li>没有身份验证：你以为连的是银行，中间人却分别跟你和银行各建一条 TLS，把你的加密流量在自己这里解密、再转发，你全程毫无察觉。</li>
      <li>只加密不认证：攻击者可以在链路中间篡改请求内容与响应，你既不知道对方是谁，也判断不了拿到的数据真假。</li>
    </ul>
    <p>
      <strong>怎么让对方除了「加密」，还能证明「它确实是自称的那台服务器」？</strong>
    </p>

    <h2>私钥与证书配置</h2>
    <p>
      最直接的做法：把私钥和证书读进来，交给 <code>https.createServer({ key, cert }, handler)</code>，监听 443 端口。
    </p>
    <p>
      它做对了一件很重要的事：<strong>建立了一条加密通道</strong>。TLS 握手会协商出会话密钥，此后应用数据在网络上看都是密文，窃听者拿不到明文——这一步是 HTTPS 的基础，不可省略。
    </p>

    <h2>自签证书不被信任</h2>
    <ul>
      <li>加密不等于可信身份：自签名证书不在操作系统的受信任根证书库里，浏览器没法验证「证书上的域名是否真的归你」，于是报不安全。</li>
      <li>少发中间证书：服务器只发了自己的证书、没带中间 CA，客户端就无法把「你的证书」一路接到任何受信任根上，链是断的。</li>
      <li>协议版本过旧：SSLv3 与 TLS 1.0/1.1 存在已被公开的漏洞，继续开放等于给攻击者留后门。</li>
      <li>私钥管理松懈：权限过松或被提交进仓库，谁拿到私钥谁就能冒充你的站点。</li>
      <li>证书到期无人监控：到期那一刻，所有客户端直接拒绝连接，等于全站宕机。</li>
    </ul>

    <h2>证书链的补齐</h2>
    <p>
      先补<strong>证书链</strong>。证书不是孤立的一张纸，而是「服务器证书 → 中间 CA → 受信任根 CA」一条链，每一环都由上一环的私钥签名。客户端顺着这条链一路验到系统内置的受信任根，才能确认域名与身份。之所以先补它：没有身份验证的加密，等于「跟一个自称是银行的人加密聊天」——中间人照样能解密转发，这正是 HTTPS 要防的头号威胁。所以生产必须用 CA 签发的证书，本地开发用 <code>mkcert</code> 或 OpenSSL 自签名就够了，它提供加密，但不提供「被信任的身份」。
    </p>
    <p>
      再补<strong>协议版本与密码套件</strong>。在服务器选项里显式设置最低版本，并优先使用 TLS 1.3：
    </p>
    <ol class="lesson-steps">
      <li>准备证书：本地用自签名，生产用 CA 签发或 Let's Encrypt 自动续期。</li>
      <li><code>https.createServer</code> 传入 <code>key</code> 与 <code>cert</code>；也可以在反向代理或负载均衡层终止 TLS。</li>
      <li>显式设置 <code>minVersion: 'TLSv1.2'</code> 与强密码套件，禁用 SSLv3 与 TLS 1.0/1.1。</li>
      <li>用在线 TLS 检测报告核对协议版本与套件配置是否符合预期。</li>
    </ol>
    <p>
      接着补<strong>全站强制加密</strong>：开启 HSTS，让浏览器此后只允许用 HTTPS 访问你的域名，堵住「第一次访问还是明文、被劫持降级」的口子。
    </p>
    <p>
      最后补<strong>密钥与证书的生命周期管理</strong>。私钥要收紧文件权限、妥善备份、绝不进代码仓库；证书要设置到期监控，留出足够的续期窗口——Let's Encrypt 的证书有效期只有 90 天，靠自动续期才跑得稳，手动续期一定要提前量；方案还要预留更换私钥的路径，避免出问题时手忙脚乱。
    </p>
    <div class="lesson-box hint">
      <strong>架构上的选择：</strong>TLS 不一定非得在应用里终止，也可以交给反向代理或负载均衡层，应用只处理普通 HTTP。好处是证书集中管理、续期只改一处；代价是从网关到应用那段内网流量是否是明文，需要按你的安全边界单独评估。
    </div>

