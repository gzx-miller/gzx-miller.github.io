    <h2>把私钥与证书当密钥一样管理</h2>
    <p>
      最后是<strong>密钥与证书的生命周期</strong>。私钥要收紧文件权限、妥善备份、<strong>绝不进代码仓库</strong>；证书要设<strong>到期监控</strong>，并留出足够的<strong>续期窗口</strong>——Let's Encrypt 的证书有效期只有 90 天，靠自动续期才跑得稳，手动续期一定要打提前量。方案还要预留<strong>更换私钥的路径</strong>，需要时能平滑切换，免得真出问题时手忙脚乱。
