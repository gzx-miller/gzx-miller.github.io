    <h2>明文传输欠下的三笔账</h2>
    <p>
      HTTP 是明文传输，链路上任何一跳都能偷看和改写你的请求。你想「加密」，于是把服务从 <code>http</code> 换成 <code>https</code>。但「加密」只解决了一半问题，旧办法留下的三笔成本，还得你自己补上：
    </p>
    <ul>
      <li>明文可被窃听、篡改：公共 WiFi 能往你页面里注广告，运营商能看到你请求里的全部内容。</li>
      <li>没有身份验证：你以为连的是银行，中间人却分别跟你和银行各建一条 TLS，在你眼皮底下解密再转发。</li>
      <li>只加密不认证：攻击者能在链路中间改动请求与响应，你既不知道对方是谁，也判断不了数据的真假。</li>
    </ul>
    <p>
      最直接的做法是：把私钥和证书读进来，交给 <code>https.createServer({ key, cert }, handler)</code>，监听 443。它做对了一件很重要的事——<strong>建立了一条加密通道</strong>。TLS 握手会协商出会话密钥，此后应用数据在网上都是密文，窃听者拿不到明文，这一步是 HTTPS 的地基，不可省略。
    </p>
    <p>
      <strong>怎么让对方除了「加密」，还能证明「它确实是自称的那台服务器」？</strong>
    </p>

    <h2>自签证书到底缺了什么</h2>
    <ul>
      <li>加密不等于可信身份：自签名证书不在操作系统的受信任根证书库里，浏览器没法验证「证书上的域名是否真的归你」，于是报「不安全」。</li>
      <li>少发中间证书：服务器只发了自己的证书、没带中间 CA，客户端就无法把「你的证书」一路接到任何受信任根上，链是断的。</li>
      <li>协议版本过旧：SSLv3 与 TLS 1.0/1.1 存在已被公开的漏洞，继续开放等于给攻击者留后门。</li>
      <li>私钥管理松懈：权限过松或被提交进仓库，谁拿到私钥谁就能冒充你的站点。</li>
      <li>证书到期无人监控：到期那一刻，所有客户端直接拒绝连接，等于全站宕机。</li>
    </ul>

    <h2>补上证书链与信任锚</h2>
    <p>
      先补<strong>证书链</strong>。证书不是孤立的一张纸，而是「服务器证书 → 中间 CA → 受信任根 CA」的一条链，每一环都由上一环的私钥签名。客户端顺着这条链一路验到系统内置的受信任根，才能确认域名与身份。之所以先补它：没有身份验证的加密，等于「跟一个自称是银行的人加密聊天」，中间人照样能解密转发，而这正是 HTTPS 要防的头号威胁。
    </p>
    <p>
      所以生产必须用 CA 签发的证书——<strong>Let's Encrypt</strong> 免费、可自动续期，是最常见的选择；本地开发用 <code>mkcert</code> 或 OpenSSL 自签名就够，它提供加密，但不提供「被信任的身份」，浏览器仍会报警。
    </p>

    <h2>定住协议版本并强制全站加密</h2>
    <ol class="lesson-steps">
      <li>准备证书：本地用自签，生产用 CA 签发或 Let's Encrypt 自动续期。</li>
      <li><code>https.createServer</code> 传入 <code>key</code> 与 <code>cert</code>；也可以把 TLS 终止交给反向代理或负载均衡。</li>
      <li>显式设置 <code>minVersion: 'TLSv1.2'</code>（推荐 TLS 1.3）与强密码套件，禁用 SSLv3 与 TLS 1.0/1.1。</li>
      <li>开启 HSTS，让浏览器此后只允许用 HTTPS 访问你的域名。</li>
    </ol>
    <p>
      显式设定最低版本与密码套件，就是把已经不安全的老协议关在门外；再用在线 TLS 检测报告核对一遍，确认配置真的生效，而不是你以为生效了。接着补<strong>全站强制加密</strong>：开启 HSTS，堵住「第一次访问还是明文、被劫持降级」的口子——第一次明文访问恰恰是最容易被中间人利用的窗口。
    </p>
