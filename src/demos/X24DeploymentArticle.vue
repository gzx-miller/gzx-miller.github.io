    <p>
      最省事的做法是：本地构建出产物，把产物整个目录扔到任意静态托管上，配个域名就完事。对纯静态项目，这确实可行，而且便宜、稳定。
    </p>
    <p>
      但它默认了一个前提——<strong>所有内容都能在构建时算好，运行时不需要任何服务端逻辑</strong>。一旦项目里有需要按请求处理、或按用户身份变化的部分，这个前提就崩了。
    </p>

    <h2>纯静态托管边界</h2>
    <ul>
      <li>服务端渲染、表单操作、接口处理这些能力需要 Node 服务，纯静态托管根本接不住。</li>
      <li>想自己托管时，产物里并不直接包含运行所需的一切，静态资源要额外搬运，容易漏。</li>
      <li>环境变量、域名、HTTPS、缓存这些都得自己配，漏一项线上就出问题。</li>
      <li>「纯静态导出」听起来万能，其实会禁掉一批动态能力，构建时才会暴露。</li>
      <li>没有健康检查与回滚预案，一旦上线出问题只能手忙脚乱地改。</li>
    </ul>

