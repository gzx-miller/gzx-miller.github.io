    <div class="llm-question"><strong>开场问题：</strong>为什么「国王 − 男人 + 女人 ≈ 女王」？词的含义如何变成坐标？</div>

    <h2>提出问题</h2>
    <p>上一课 N-gram 学到「猫 → 出门」出现过 800 次，但现在有人写「小猫」，它查遍整张表只找到 3 次空白记录——它<strong>不知道「猫」和「小猫」是同一种动物</strong>。因为对 N-gram 来说，词是<strong>字符串</strong>，「猫」「小猫」「猫咪」是三个毫不相关的符号，即使意思几乎相同。病根是：符号之间没有任何距离或相似度。要让词有「意思」，得用<strong>数字</strong>表示，让「猫」「小猫」的数字很接近、「猫」和「飞机」的数字很远。</p>

    <h2>最小方案</h2>
    <p>最朴素的落地法：<strong>挑几个语义属性当「维度」，给每个词在每维上打个分（0~1）</strong>。先试两个维度——「动物性」和「体型大小」，把词摆进去：<code>猫 (0.86, 0.27)</code>、<code>小猫 (0.90, 0.13)</code>、<code>狗 (0.80, 0.32)</code> 全挤在「小动物」那一角、挨得很近；<code>飞机 (0.03, 0.95)</code> 远在另一头。用距离一量，「猫」和「小猫」就天然相似了。每个词都成了平面上的一个<strong>点（两个数）</strong>。</p>
    <h3>发现不足：两个维度分不开近义词</h3>
    <p>可「猫」和「狗」几乎落在同一个点上——这两个维度分不开它们。要区分还得再加「忠诚 vs 警觉」「会不会抓老鼠」……加到三维、五维仍搞不定「自由 vs 民主」「悲伤 vs 忧郁」。一个词的意思牵涉成百上千种真实但说不清的属性。所以真实 NLP 里维度取<strong>非常多</strong>——常见的 <strong>128、300、768、甚至上千维</strong>，每一维都是一个「说不清但确实有用的语义方向」。</p>

    <h2>迭代</h2>
    <p>把一个词表示成 <code>(v₁, v₂, …, v_d)</code> 这串数字，就是它的<strong>词向量（词嵌入）</strong>，d 是维数，常达几百上千。意思是相近的词向量挨得近。可几百维手工填不现实、也全凭感觉太主观——<strong>能不能让机器自己把这些数字学出来？</strong>线索藏在语言学家那句老话里：<em>「一个词的意思，由它经常出现的场合决定。」</em>机器读不懂词义，但能<strong>数上下文</strong>——「猫」和「小猫」出现在几乎相同的句子结构里，说明它们应该很近。这就给了机器一个不依赖人工、纯靠统计的判据：<strong>上下文越像的词，就该离得越近</strong>。</p>
    <h3>Word2Vec：遮词猜词游戏</h3>
    <p>先随机给每个词发一串数字，然后反复玩填空题：遮住句子里一个词，让网络拿上下文词的向量把它猜出来。比如「今天我带着 ___ 去公园散步，它很兴奋」，网络猜「猫 0.3、狗 0.4、孩子 0.2、朋友 0.1」，真实答案是「猫」——猜错了，就微调相关词的向量，让「猫」在这种上下文下得分更高。几十亿次填空之后，总出现在相似上下文里的词（「猫」「小猫」「猫咪」）被一点点<strong>推到相近的位置</strong>。这套 2013 年由 Google 提出的方法就叫 <strong>Word2Vec</strong>，第一次把「词的意思」彻底变成可计算的数字。</p>
    <h3>意外惊喜：向量运算有意义</h3>
    <p>训练完后研究人员发现一个让所有人兴奋的结果：<code>向量(国王) − 向量(男人) + 向量(女人) ≈ 向量(女王)</code>。这不是人为设计的，而是纯粹从文本里<strong>自然浮现</strong>的——「国王」和「男人」的关系，与「女王」和「女人」的关系在空间上是相同的方向和距离。这里的加减就是第 2 课的<strong>向量加减</strong>，逐个维度地加加减减，落点正落在「女王」附近。类似的还有「北京−中国+法国 ≈ 巴黎」等——词向量把语言的<strong>语义关系编码成了空间方向</strong>。</p>
    <div class="llm-box warn">⚠ 局限：每个词只有一个固定向量。「我去银行取钱」和「我坐在河岸边」里的「银行」意思完全不同，但词向量只记住「银行」的平均意思、无法按上下文动态调整——这要靠每次按上下文重新计算词的表示，也就是注意力机制要做的事。</div>

    <h2>总结</h2>
    <p>词向量把每个词变成一行数字，让意思相近的词数字也相近。训练方式极简单：遮一个词、让网络猜、猜错了就微调。副产品是词向量空间里冒出「国王−男人+女人 ≈ 女王」这样的语义方向；局限是每词一个固定向量、无法区分一词多义。</p>
    <div class="llm-term"><span class="term-name">「词向量（词嵌入）」</span>是指把每个词表示为一串稠密数字 <code>(v₁,…,v_d)</code>，通过「上下文相似的词意思相近」这一假设，用遮词猜词的训练让相似词在向量空间里挨得近，从而让语义关系（如「国王−男人+女人≈女王」）变成空间中的方向。</div>
