    <h2>多效果的串联管线</h2>
    <p>
      后处理把「给画面加效果」这件事从场景里彻底剥了出来：先把场景渲进一张纹理，再用全屏四边形把它当成普通图片处理。一个效果是一遍，一遍的输出能喂给下一遍——所谓后处理管线，就是把一张图接一张图地传下去。
    </p>
    <div class="lesson-term">
      <span class="term-name">「后处理（Post-processing）」</span>指在场景渲染完成之后，对最终画面整体做的图像处理，通常用「渲染到纹理 + 全屏四边形」实现。每个效果是一遍 pass：输入一张纹理、在片段着色器里做逐像素或邻域运算、输出一张纹理。边界与例外：全屏四边形的顶点在 NDC 直接输出、UV 由顶点位置换算；要串联效果必须把中间结果写回纹理（而非屏幕）；模糊、描边这类邻域效果需采样多个纹素，成本随采样次数上升，是移动端的主要瓶颈。
