      <strong>开场问题：</strong>你把场景渲进一张纹理，再用一块全屏四边形给它做高斯模糊，画面糊得很漂亮。接着你想在模糊之上再叠一层泛光——把画面里的高光提亮、晕开。于是你在同一个片段着色器里先算出模糊色，再对着模糊色提亮。结果屏幕上是一团「糊掉的光斑」，原图里那些锐利的亮点全不见了。为什么「模糊」和「泛光」这两步单独看都对，串在一起就歪了？
    </div>

    <h2>画面级处理特性</h2>
    <p>
      后处理和普通渲染有个根本区别：它的输入是「一整张已经画完的画面」，输出也是「一整张画面」。你不再关心场景里有什么物体，只关心这张图上的每个像素。这带来一个内生的约束——<strong>片段着色器在某一刻只能算出一个结果</strong>：它读进一张图、吐出一张图，中间过程不会自动留在任何地方。
    </p>
    <p>
      于是「把所有效果塞进同一个片段着色器」这个老办法，账变得很难算：
    </p>
    <ul>
      <li>中间结果<strong>留不下</strong>。你在一段代码里先算模糊、再对模糊提亮，前一步的结果只是一段局部变量，没法被当成「下一张输入图」再采样一次；</li>
      <li>效果之间<strong>互相污染</strong>。「先灰度再泛光」和「先泛光再灰度」是两种不同结果，但一个着色器里只能写死一种顺序；</li>
      <li>每加一个效果，就往那个巨大的 <code>if / else</code> 里<strong>再插一个分支</strong>，参数越缠越乱，效果无法自由组合。</li>
    </ul>
    <p>
      所以真正的问题不是「怎么写一个模糊」，而是：<strong>怎么让一个效果产出的画面，能被下一个效果当成输入，干净地接下去？</strong>
    </p>

    <h2>独立渲染通道</h2>
    <p>
      把每一个效果拆成独立的<strong>一遍（pass）</strong>：先把场景渲染到一张 FBO 纹理上，再用一块覆盖全屏的四边形，在片段着色器里对这张纹理做运算。一遍只做一件事——输入一张图，输出一张图。
    </p>
    <p>
      这个方案做对了一件根本的事：<strong>它把「特效」变成了一个只管像素、不碰场景的纯函数</strong>。灰度、模糊、泛光，本质上都只是「对一整张图做某种逐像素或邻域运算」，跟场景里是球还是方块已经没关系了。
    </p>

    <h2>中间结果断链</h2>
    <ul>
      <li><strong>输出直接上屏就断了链。</strong>如果第二遍把结果直接画到屏幕，那么第三个效果就无从取用它的输出——想串联，中间结果必须落进一张能被再次采样的纹理，而不是屏幕。</li>
      <li><strong>全屏四边形不是场景里的物体。</strong>若拿相机矩阵、投影矩阵去画它，它会被当成 3D 世界里的一块布，转开、缩远，根本盖不住整屏。</li>
      <li><strong>逐像素运算做不出模糊。</strong>灰度只读自己那一个纹素就够了，但模糊要读「周围」——单个纹素的运算里没有「邻居」这个概念，采样点得自己偏移出去。</li>
      <li><strong>效果越贵，采样越多。</strong>灰度采样一次就够，换成 <code>3×3</code> 模糊，一次片段里从 1 次涨到 9 次；把效果再叠加，成本成倍——后处理的瓶颈几乎全在这里。</li>
    </ul>

    <h2>全屏四边形绘制</h2>
    <p>
      先解决「怎么画一块盖住全屏的四边形」。它<strong>不属于场景</strong>，所以不需要任何 MVP：顶点着色器直接把顶点位置原样输出成 NDC 坐标，<code>gl_Position = vec4(a_position, 0.0, 1.0)</code>；UV 也不用额外传，由顶点位置换算 <code>v_uv = a_position * 0.5 + 0.5</code>，<code>[−1,1]</code> 的坐标正好映射成 <code>[0,1]</code> 的纹理坐标。
    </p>
    <p>
      第一个效果最简单，<strong>灰度</strong>（逐像素）。采样一次拿到当前颜色，用亮度加权 <code>dot(color.rgb, vec3(0.299, 0.587, 0.114))</code> 得到灰色，再用 <code>mix(color.rgb, gray, u_intensity)</code> 按强度在原色和灰度之间插值——<code>intensity</code> 就是那个可调的「力度」。
    </p>
    <p>
      第二个效果开始需要邻居，<strong>高斯模糊</strong>（邻域）。对当前像素周围 <code>3×3</code> 共 9 个纹素各采样一次，按高斯权重（中心权重最大、四角最小）加权求和。这就是<strong>加权邻域卷积</strong>；它的副作用恰好解释了开场——模糊之后，原图里锐利的高光已经被「摊平」了，画面只剩下一团柔和的色块。
    </p>
    <p>
      第三个效果是<strong>泛光</strong>（阈值加亮）。判断 <code>length(color.rgb) &gt; 0.8</code>：只有亮度超过阈值的像素，才按强度提亮后叠回原图，于是高光周围晕出一圈光。看清它的前提——<strong>它必须去读原图里的高光</strong>，而不是读一张已经模糊过的图。
    </p>
    <p>
      最后把三个 pass <strong>串联成管线</strong>：让每一遍的输出<strong>不直接上屏</strong>，而是写回一张纹理，作为下一遍的输入。这一步才是开场困惑的答案——「模糊」和「泛光」各自保留自己的输出，就能按任意顺序组合；想要「先模糊再泛光」，就让泛光那遍去读原图挑高光，而不是读模糊的结果。
    </p>
    <div class="lesson-box warn">
      <strong>四条要记牢的边界：</strong>全屏四边形的顶点直接在 NDC 输出、UV 由顶点位置换算，别把相机矩阵混进去；本课的 <code>3×3</code> 模糊是<strong>一步近似</strong>，工程里更省的做法是把高斯拆成横向、纵向两次线性 pass，再配合降采样；成熟的泛光会先提取高亮、多次降采样模糊后再叠加，本课用「阈值判定加亮」做简化演示；后处理的开销集中在片段的纹理采样次数上，采样越多越贵，这正是移动端的主要瓶颈。
    </div>

