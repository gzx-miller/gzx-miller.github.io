      <strong>开场问题：</strong>一条通知文案写成 <code>'欢迎 ' + name + '，你有 ' + count + ' 条消息'</code>，两个引号、两个加号、两个空格，少写一个就少个空格；更麻烦的是这条文案还要换行、还要把用户昵称拼进 HTML 提示框——有没有一种字符串，能像写文档一样直接把变量嵌在句子中间？
    </div>

    <h2>提出问题</h2>
    <p>
      你在写站内通知：文案里要插用户名和消息数，要分两行显示，点开还是一条带粗体昵称的 HTML 提示。用加号拼接的写法，问题不在「能不能拼出来」，而在<strong>拼接的边界全都靠人眼数</strong>：哪段是静态文字、哪段是变量、空格到底有没有漏，读代码的人得逐个加号对过去。
    </p>
    <p>
      更深的隐患在于转义。你打算拼一段 HTML，把用户昵称放进粗体标签里：<code>'&lt;b&gt;' + name + '&lt;/b&gt;'</code>。可昵称是用户自己填的，如果它本身就是一段带尖括号的脚本片段呢？加号拼接会把用户输入<strong>原封不动</strong>地塞进 HTML，浏览器照单执行——这就是 XSS。也就是说，拼接不仅难读，还把「哪些内容需要转义」这件事完全交给了你手动记忆。
    </p>

    <h2>最小方案</h2>
    <p>
      最直接的答案就是那个老办法：用 <code>+</code> 把字符串和变量一段段接起来。它确实能工作，而且是纯字符串运算，没有副作用，也不需要任何新语法——在只有一两个变量的短文案里，这套写法简单到不值一提。
    </p>
    <p>
      这个方案对的地方在于：<strong>它清楚地划出了一条边界——静态文本和动态值可以自由组合成一条输出</strong>。这条边界要保留，只是「怎么组合」可以更省心。
    </p>

    <h2>发现不足</h2>
    <ul>
      <li>多行文本只能用 <code>\n</code> 拼，源码里的缩进一旦带进来，缩进空格也会变成文案的一部分。</li>
      <li>变量一多，引号和加号交织在一起，到底哪里少了一个空格、哪里多了一个引号，光看代码看不出来。</li>
      <li>用 <code>+</code> 拼接的 HTML 没有任何自动转义，用户昵称里的尖括号会直接变成可执行的标签。</li>
      <li>文案要复用、要统一改成模板时，散落的加号片段没法集中管理，想抽成一个「格式化函数」也找不到合适的切入口。</li>
    </ul>

    <h2>迭代</h2>
    <p>
      第一步，换掉引号。用反引号写字符串，就得到<strong>模板字面量</strong>：换行直接回车即可，不必写 <code>\n</code>；变量用 <code>${}</code> 插进去，里面可以放任意表达式，不限于变量名。<code>`欢迎 ${name}，你有 ${count} 条消息`</code> 把句子和值放在一起读，边界一眼可见。
    </p>
    <p>
      但真正有意思的机制藏在下一步。如果<strong>不直接调用，而是把模板字面量当作参数「贴到」一个函数前面</strong>，这个函数就会变成所谓<strong>标签函数</strong>，而模板的静态部分和动态部分会被<strong>拆成两份</strong>交给它：第一个参数 <code>strings</code> 是字符串片段组成的数组，其余参数 <code>values</code> 是各个插值的值。函数拿到这两份材料之后，可以自己决定怎么拼。
    </p>
    <p>
      这个「拆开再拼」的动作，就是一切文本 DSL 的入口。函数在拼接之前<strong>可以逐个检查每个插值</strong>，于是转义、加粗、翻译、高亮都能在这里完成。一个最典型的应用是国际化：把文案里的中文标签当成插值传进去，标签函数按当前语言查到对应词再拼回来，一条模板就能同时输出中英文。这里有个必须记住的数量关系——<strong>字符串片段的数量恒等于插值数量加一</strong>，因为每个插值两侧都有静态文本把句子隔开。
    </p>
    <div class="lesson-box warn">
      标签模板<strong>不会自动转义</strong>。它只是把插值原样交给你，如果你在标签函数里直接把插值拼进 HTML，XSS 风险一点没少。正确做法是在标签函数内部对每个插值做转义，把尖括号等特殊字符处理掉再拼——重点在于「转义这件事终于有了一个统一的发生地点」。
    </div>
    <p>
      如果只想要「原样文本」而不想让 <code>\n</code> 这类转义生效，可以直接用内置标签 <code>String.raw</code>：它取到的是未经转义的原始片段，写正则、写路径时特别顺手。此外，片段数组还通过 <code>strings.raw</code> 保留了原始版本，于是工具不仅能拿到「插值了哪些值」，还能拿到「静态文本长什么样」，这正是它能解析出模板结构、进而高亮语法或校验查询的原因。styled-components 与 graphql-tag 这类库，本质就是各自写了一个标签函数。
    </p>

