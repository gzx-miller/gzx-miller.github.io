    <p>
      模板字面量解决的是「把变量嵌进文本」的可读性问题，而标签模板更进一步，把「拼装文本」这件原本散落在加号之间的事，<strong>收拢成了可以集中控制的一道工序</strong>。插值和静态片段被拆成两份材料交给你，转义、翻译、高亮于是第一次有了统一的发生地点。
