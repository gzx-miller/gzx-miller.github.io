    <h2>形变引起的法线偏移</h2>
    <p>
      光照算的是 <code>N·L</code>，其中 <code>N</code> 是法线——垂直于表面的方向。当你对模型施加变换（旋转、缩放）时，顶点跟着走，<strong>法线也必须跟着正确地变化</strong>，否则它就不再垂直于变形后的表面，算出的光照自然全错。
    </p>
    <p>
      麻烦在于「法线该怎么变」并不显然，随手糊弄都要付账：直接把法线当常量不动，物体<strong>一转身法线就错</strong>；用模型矩阵直接乘法线，旋转看着没问题，可一旦<strong>非等比缩放</strong>就出乱子；想让每个顶点都手工求一遍法线，曲面又太难，还很难保证相邻面共享顶点时法线方向一致。所以真正要问的是：<strong>存不存在一个矩阵，能把任意变换（尤其是非等比缩放）下的法线，正确地变换到世界空间？</strong>
    </p>

    <h2>旋转与等比缩放</h2>
    <p>
      先看简单情形。对<strong>纯旋转和等比缩放</strong>来说，模型矩阵左上角那个 3×3 就够了：旋转会把法线正确地旋转过去，等比缩放只是把法线按同一个比例拉长——而拉长不影响方向，最后归一化就抵消掉了。于是先写 <code>normalize(mat3(model) * aNormal)</code>。
    </p>
    <p>
      这个方案做对了一件重要的事：<strong>它让法线跟着模型「转」了</strong>。物体旋转时明暗不会漂移，方向感是对的。只要你不做非等比缩放，这么写完全够用。
    </p>

    <h2>非等比缩放的偏差</h2>
    <ul>
      <li><strong>非等比缩放就错。</strong>法线是「垂直关系」，不是「位置坐标」。把表面沿 Y 压扁后，原本垂直于它的法线应当朝「反方向」倾斜；直接用模型矩阵乘，法线会偏到错误的朝向，正如开场那样亮面变暗、暗面变亮。</li>
      <li><strong>硬边会被抹平。</strong>立方体若用「所有相邻面法线平均」当作每个顶点的法线，六个面会共享同一条光滑法线，硬边消失，方盒看着像个软胶块。</li>
      <li><strong>忘了归一化强度失真。</strong>模型缩放会让法线长度改变，<code>N·L</code> 的强度被整体放大或缩小，光照忽明忽暗。</li>
      <li><strong>拿 4×4 整套矩阵去变。</strong>法线是方向量，与平移无关；若连平移一起作用，方向会被无谓地污染。</li>
    </ul>

    <h2>法线来源与着色</h2>
    <p>
      先分清法线<strong>从哪里来</strong>。硬边物体（立方体）每个面用一个<strong>面法线</strong>，顶点拆开、各面独立，得到棱角分明的<strong>平面着色（flat）</strong>；曲面（球体、车体）则把每个顶点的法线取<strong>相邻面法线的平均</strong>，共享顶点、在光栅化时插值，得到<strong>平滑着色（smooth）</strong>。演示里可以一键切换这两套数据，直接对比同一个立方体在两种法线下的明暗差别。先讲这个，是因为法线数据本身得先正确，后面的变换才有意义。
    </p>
    <p>
      再来修「非等比缩放」。关键洞察是：法线必须始终<strong>垂直于变换后的表面</strong>。如果表面的切向量 <code>T</code> 被模型矩阵 <code>M</code> 变换，我们要求 <code>N'·(M·T) = 0</code> 依然成立。能满足这个条件的，是模型矩阵左上 3×3 的<strong>逆转置</strong>：
    </p>
    <p>
      <span class="lesson-kv">N' = transpose(inverse(mat3(model))) · N</span>
    </p>
    <p>
