    <h2>卡片外壳复用</h2>
    <p>
      你在做一个课程站：列表页、详情页、推荐位上都要放「课程卡片」，它们的外壳几乎一样——统一的圆角、内边距、标题位置、底部价格样式。不同的只有内容：这里显示课程名，那里显示套餐价，另一处底部还要多一个「立即报名」按钮。
    </p>
    <p>
      如果每个地方都手写一份卡片结构，看起来能跑，但隐患已经埋下：<strong>外壳是要统一的，内容是各不相同的</strong>。这两件事如果混在同一段模板里，想调整外壳就得满项目地找。
    </p>

    <h2>结构整体复制</h2>
    <p>
      最省事的做法：需要几张卡片就复制几份完整结构，把标题、正文、按钮直接写死在各自的模板里。
    </p>
    <p>
      这个方案做对了一件最基础的事：<strong>结构是可见的、不抽象的</strong>。每张卡片的标记都摊在眼前，改一处内容非常直接。只有当卡片很少、且完全不需要统一时，这才划算。
    </p>

    <h2>样式重复代价</h2>
    <ul>
      <li>外壳样式重复了多份，哪天要调整内边距或圆角，就得改遍每一个页面。</li>
      <li>卡片自带的行为（折叠、悬停、统一样式）没法被共用。</li>
      <li>使用方只能填写死的内容，卡片内部的数据（如这条课程对象）传不出去。</li>
      <li>内容与结构耦合在一起，卡片既不能当公共组件，也无法单独测试。</li>
    </ul>

    <h2>外壳内容分工</h2>
    <p>
      不推翻「要有统一的外壳」，而是让<strong>组件负责结构、使用方负责内容</strong>。做法是给外壳预留几个「空位」，由使用方填上——这个空位就是<strong>插槽</strong>。
    </p>
    <p>
      先从最简单的形态开始：一个<strong>默认插槽</strong>负责卡片主体。外壳组件只写 <code>&lt;slot /&gt;</code> 占位，使用方把说明文字放进去，于是同一套边框与内边距就被无数内容复用了。
    </p>
    <p>
      当卡片需要多个位置时，默认插槽就不够了——你没法把「标题」和「底部」分别塞进同一个空位。于是引出<strong>具名插槽</strong>：外壳声明 <code>header</code>、<code>default</code>、<code>footer</code> 三个命名位置，使用方用 <code>#header</code>、<code>#footer</code> 对应填充，结构照样不动。
    </p>
    <p>
      还差最后一步。底部想渲染价格，可价格来自组件内部的 <code>product</code> 数据，使用方拿不到它。于是把数据作为参数从插槽<strong>回传</strong>给父级模板，由父级决定怎么展示——这就是<strong>作用域插槽</strong>。它把「数据在哪里」和「怎么显示」拆开：子组件交出一条记录，父级决定把它画成价格还是别的样子。
    </p>
    <div class="lesson-box hint">
      <strong>默认内容：</strong>把兜底文案写在 <code>slot</code> 标签内部，使用方没有提供内容时就会显示它，卡片不会出现尴尬的空白区域。
    </div>
    <div class="lesson-box warn">
      <strong>别用过头：</strong>插槽适合内容定制，不适合承担复杂的状态通信；具名插槽越多，使用成本越高，命名要尽量直接；作用域插槽传出的数据要稳定，别把内部实现细节一股脑暴露出去。
    </div>

    <p>
      一句话概括这套分工：<strong>父级提供内容，子组件决定渲染位置</strong>。卡片只管把内容放在哪、怎么排版，至于里面具体写什么，由使用方在当场决定。
    </p>

