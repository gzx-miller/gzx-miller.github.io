    <h2>插槽分工规则</h2>
    <p>
      插槽解决的是「结构复用、内容定制」的分工：外壳由组件自己掌握，内容交给使用方填写。默认插槽管主体，具名插槽管多个命名位置，作用域插槽把组件内部数据回传给父级模板。
