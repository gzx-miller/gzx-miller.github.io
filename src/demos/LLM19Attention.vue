    <div class="llm-question"><strong>开场问题：</strong>「它太累了」——「它」指谁？让每个词自己决定该看向哪里</div>

    <h2>提出问题</h2>
    <p>读两句几乎一样的话：「小猫没有过马路，因为它太<strong>累</strong>了。」和「…因为它太<strong>堵</strong>了。」两个「它」指的东西完全不同：第一句指小猫，第二句指马路。你几乎是无意识就分辨出来了——读到「它」时，你的目光回头扫了一眼前文，只在「小猫」和「马路」之间挑了一个，其余的字几乎被忽略。这个「回头看、且看得有轻有重」的动作就是人类的注意力，问题是：<strong>怎么让神经网络也学会这个动作？</strong></p>
    <div class="llm-box warn">
      <strong>旧方案的局限</strong>：RNN / LSTM 从左到右逐词读入，把读过的一切不断压缩进一个固定大小的向量里，像滚雪球装进一只「行李箱」——句子越长，越早装进去的东西越容易被压变形。等网络读到「它」时，「小猫」已是五步前的记忆。LSTM 的阀门缓解了遗忘，却没解决根本问题：<strong>所有历史共用一条固定宽度的门缝</strong>。
    </div>

    <h2>最小方案</h2>
    <p>激进一点：根本不压缩，所有词的向量都原样留在桌面上，「它」需要谁就直接去看谁。新方案只有三步：</p>
    <ol class="llm-steps">
      <li><strong>打分</strong>：「它」想知道每个词和自己的相关度。两个向量的点积越大越相关，就让「它」的向量和每个词的向量分别做点积，得到一排分数。</li>
      <li><strong>变成权重</strong>：分数有正有负不好直接用，用 <code>softmax</code> 把这一排分数变成加起来等于 1 的比例，比如「小猫 62%、马路 9%、累 13%」。</li>
      <li><strong>按比例混合</strong>：用这些百分比对所有词的向量加权求和，得到一个主要由小猫构成、掺了一点「累」的「它」——指代问题就这样被算了出来。</li>
    </ol>

    <h2>发现不足：一个词要顾两头</h2>
    <p>直接拿词向量互相点积藏着毛病：<strong>一个词「想找什么」和「能提供什么」是两回事</strong>。「它」是代词，想找的是「前文某个具体事物」；而它能供给别的词的信息只是「这里有个代词」。一个向量身兼两职会互相打架。</p>

    <h2>迭代一：三个角色 Q、K、V</h2>
    <p>修补的办法也很小：别用原始向量直接对话，让每个词先通过三个可学习的线性变换矩阵 <code>W_Q, W_K, W_V</code>，生成三个「分身」，就像在图书馆里：</p>
    <ul>
      <li><strong>Q（查询单）</strong>「我在找：前文里一个具体事物」</li>
      <li><strong>K（书脊标签）</strong>「我这里有：一只动物、名词、主语」</li>
      <li><strong>V（书的内容）</strong>「真正被取走混合的信息本体」</li>
    </ul>
    <p>于是打分规则修正为：用「它」的 Q 去点积每个词的 K，权重算好后混合的是每个词的 V。三个矩阵都是训练学出来的——「该注意什么」这件事本身，是模型自己学会的。</p>

    <h2>迭代二：从「它」一个词到整句话</h2>
    <p>这套动作只照顾了「它」一个词，真实的句子里每个词都得回头看一遍。与其逐个循环，不如把「对所有词各做一遍」用矩阵一次写完——把每个词的 q、k、v 从上到下摞成矩阵 <code>Q、K、V</code>，整套流程就<strong>坍缩成一个式子</strong>，正是 2017 年 Google 论文《Attention Is All You Need》的核心（Scaled Dot-Product Attention）：</p>
    <div class="llm-box hint">
      <code>Attention(Q, K, V) = softmax(QKᵀ / √d_k) V</code>，四步：<code>QKᵀ</code> 打分 → <code>÷√d_k</code> 降温 → softmax 归一成权重 → 乘 V 混合。
    </div>
    <p>每一行的作用（以「它」这一行为例）：</p>
    <ol class="llm-steps">
      <li><strong>打分 <code>QKᵀ</code></strong>：一次把所有词对所有词的分数打出来，第 i 行第 j 格即「第 i 个词该看第 j 个词多少」。</li>
      <li><strong>降温 <code>÷√d_k</code></strong>：论文里 <code>d_k=64</code> 维点积数值很容易累积很大，喂进 softmax 会「饱和」，注意力变成非黑即白、梯度几乎为零。统一除以 √64=8，把分数缩回温和范围。</li>
      <li><strong>归一 softmax</strong>：对每一行做 softmax，变成加起来等于 1 的权重表。</li>
      <li><strong>混合 <code>×V</code></strong>：拿权重取各词的 V 加权相加。前三步只是算出「该看谁」的计划，<strong>这一步才把信息真的搬进词里</strong>。</li>
    </ol>
    <p>这个设计有两个「免费赠品」：所有词的回头看是<strong>同时</strong>发生的（矩阵一乘全算完，不用排队）；「小猫」距「它」5 个词还是 500 个词都是<strong>一次直达</strong>，不存在传着传着丢了的问题——行李箱被彻底扔掉了。</p>

    <h2>迭代三：代入数字手算</h2>
    <p>把向量缩到 2 维落地验算。三个分身设计成「第 1 维是动物味、第 2 维是疲惫味」：小猫 <code>q=[0.3,0.3], k=[1.2,0], v=[1.0,0]</code>，累 <code>q=[0.2,1.5], k=[0,1.0], v=[0,1.0]</code>，它 <code>q=[2.0,0.2], k=[0.1,0], v=[0.5,0.5]</code>。只算「它」这一行：</p>
    <ol class="llm-steps">
      <li>打分：它·小猫 = 2.4，它·累 = 0.2，它·它 = 0.2。「它」的查询几乎和「小猫」的 key 同向，点积远甩后面两个。</li>
      <li>降温 <code>÷√2≈1.41</code>：1.70、0.14、0.14。</li>
      <li>softmax：小猫 ≈ <strong>70.3%</strong>、累 ≈ <strong>14.8%</strong>、它 ≈ <strong>14.8%</strong>，和为 100%。</li>
      <li>混合：<code>out = 0.703×[1.0,0] + 0.148×[0,1.0] + 0.148×[0.5,0.5] = [0.78, 0.22]</code>。</li>
    </ol>
    <div class="llm-box hint">
      「它」原本是个空洞的代词（从词表查出的固定向量，与上下文无关），经过这轮注意力变成 <code>[0.78, 0.22]</code>——0.78 的动物味 + 0.22 的疲惫味，模型算出了「这个『它』≈ 一只（有点累的）小猫」。这个装好料的新向量会<strong>顶替</strong>原向量继续往上走。把 2 维换回 64 维、把「只算一行」换成「n 行一起算」，就是真实 Transformer 每层都在做的事。
    </div>

    <h2>总结</h2>
    <p>注意力机制就是让每个词带着自己的问题（Q）去查所有词的标签（K），按匹配程度分配目光，再把对应的内容（V）按比例混合成自己的新含义——理解一个词不再依赖一条会遗忘的传话链。本课要点：注意力权重（点积打分 + softmax 归一）；Q/K/V 三个可学习矩阵生成的分身；缩放因子 √d_k 防止 softmax 饱和；以及全句并行、任意距离一步直达这两个免费赠品。</p>
    <div class="llm-term"><span class="term-name">「注意力机制（Attention）」</span>是指让每个词通过查询 Q 与所有词的键 K 点积打分、softmax 归一成权重，再按权重混合各词的值 V，从而让每个词都得到「该看谁、看多少」且随上下文而变的向量表示；其缩放点积形式 <code>softmax(QKᵀ/√d_k)V</code> 是 Transformer 和大语言模型的基石。</div>
