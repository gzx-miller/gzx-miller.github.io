    <div class="llm-question"><strong>开场问题：</strong>模型眼里的「字」是什么？为什么 strawberry 数不对 r 的个数？</div>

    <h2>提出问题</h2>
    <p>前两课从头到尾摆弄的都是「词向量」——一串数字。可键盘上敲进去的「我 是 一只 小猫」是文字，不是数字，中间缺了一步：<strong>谁把文字变成向量？</strong>模型内部藏着一张<strong>有限</strong>的查找表，文字进来就查——查到哪个单元，就取出对应那一行向量。但表必须是有限的，不可能为每一种文字串都留一行，所以文字进门的第一步，必须先切成「表里查得到的单元」。这一步叫<strong>分词（tokenize）</strong>，切出来的每一块就是一个 <code>Token</code>。</p>
    <div class="llm-box warn">
      <strong>副作用</strong>：问顶尖模型「strawberry 里有几个字母 r？」，它常一本正经答「2 个」，正确答案是 3 个。不是它语文没学好——<code>strawberry</code> 常常整块就是表里的一个 token、不可分割。模型眼里它不是 10 个字母，而是一坨整体，就像你把「中国」当一个词，从不去数它有几个笔画——那 3 个 r 藏在整体内部，对模型根本不可见。
    </div>

    <h2>最小方案：两条朴素的路，各撞各的墙</h2>
    <ul>
      <li><strong>按「词」切</strong>：一个词一个 token，看着自然。但英语词形几乎无穷（单复数、时态、人名、拼写错误、新造词），词表开到上百万都兜不住；更糟的是遇到表里没有的词，模型只能吐「未知」占位符 <code>[UNK]</code>，信息全丢。中文更尴尬——根本没有空格告诉你词的边界。</li>
      <li><strong>按「字符」切</strong>：词表缩到几千甚至 256，再也不怕生词；但序列长得吓人，「understanding」=13 个 token，一篇文章 token 数翻好几倍——而注意力的复杂度是 <code>O(n²)</code>，序列翻倍、成本就翻四倍；模型还得从头学「c-a-t 合起来才是猫」。</li>
    </ul>
    <p>两堵墙逼出一个折中：<strong>子词（subword）</strong>。常见的整词当一个 token，生僻的长词拆成几个常见片段，实在没见过的退到字符/字节，保证<strong>永远不会「完全不认识」</strong>。剩下唯一的问题：这些片段从哪来、按什么规则切？</p>

    <h2>迭代：BPE——从字符出发，反复合并最常见的一对</h2>
    <p>现代大模型几乎都用 <strong>BPE（字节对编码）</strong>，它造词表的办法像玩积木——<strong>从零开始，谁老黏在一起，就把谁俩焊成一块</strong>：</p>
    <ol class="llm-steps">
      <li>先把所有词拆到最小单位（字符/字节），每个字符就是一个 token。</li>
      <li>扫一遍语料，<strong>数</strong>哪一对相邻 token 出现得最频繁。</li>
      <li>把这一对<strong>合并</strong>成一个新 token，加进词表。</li>
      <li>重复第 2、3 步，直到词表攒到目标大小（比如 5 万）。</li>
    </ol>
    <p>拿三句话当迷你语料走两轮：①我爱吃苹果，苹果很甜。②红苹果和绿苹果都是水果。③水果店卖水果。全拆成单字后，「苹 果」对出现最多（① 2 次 + ② 2 次 = 4 次），<strong>第 1 轮合并成「苹果」</strong>；重新数，「水 果」最多（② 1 次 + ③ 2 次 = 3 次），<strong>第 2 轮合并成「水果」</strong>。套回「苹果是水果」就切成了「苹果 / 是 / 水果」3 个 token。数、合并、再数、再合并几万轮之后：高频词整个变成一个 token，中频词留成几个常见片段，生僻字才碎到单字——既不爆词表，也不会完全不认识。</p>

    <h2>掀开真相：模型眼里其实是一串整数</h2>
    <p>切出 token 只是第一步，token 并不以「文字」的样子进模型。每个 token 在词表里有个固定编号（ID），模型真正吃进去的是一串<strong>整数</strong>；每个 ID 再去巨大的<strong>嵌入表</strong>里取出自己那一行数字——这就是第 15 课的词向量（大模型里叫 embedding）。一句话进模型是：文本 → 切成 token → 查编号 ID → 查嵌入表得向量 → 加位置 → 进注意力层。分词器是这条流水线的<strong>第一道工序</strong>。</p>
