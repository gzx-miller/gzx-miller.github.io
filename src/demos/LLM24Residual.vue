    <div class="llm-question"><strong>开场问题：</strong>96 层 Transformer——梯度怎么从第 96 层传回第 1 层而不消失？</div>

    <h2>提出问题</h2>
    <p>GPT-3 有 96 层 Transformer Block。训练时损失在最后一层算出，梯度要一路反向传播——从第 96 层传回第 1 层。梯度每穿一层都要乘一次那层的导数，假设每层导数平均是 0.9，经过 96 层 <code>0.9⁹⁶ ≈ 0.00006</code>——第 1 层收到的梯度只有原来的万分之零点六，几乎为零，它的参数得不到更新信号、白占内存。反过来若每层导数平均 1.1，<code>1.1⁹⁶ ≈ 12000</code>，梯度爆炸、数值溢出，训练当场崩盘。</p>
    <div class="llm-box warn">
      连乘这件事，要么把梯度碾成零、要么吹上天，极难刚好停在 1 附近。这个敌人已撞见过两回：第 13 课反向传播沿链式法则连乘；第 17 课 RNN 把同一矩阵沿「<strong>时间</strong>」连乘几十步导致记忆消退。这一次只是换了方向——沿「<strong>深度</strong>」连乘 96 层。同一道数学难题第三次找上门，解法的灵魂依旧藏在「修高速路」的思路上。
    </div>

    <h2>最小方案：残差连接——加一条直通路</h2>
    <p>残差连接的做法简单粗暴：<strong>把这一层的输入原样加到它的输出上</strong>。普通层 <code>y = f(x)</code>，残差层 <code>y = f(x) + x</code>。可把 x 加回去，输出不是被改了吗？会变，但不会变坏——关键在于 f 是<strong>训练出来的</strong>。加上捷径后，这一层要学的目标变了：原来它得亲手算完整的目标输出 H(x)，现在只需算「目标与输入的<strong>差</strong>」<code>f(x) = H(x) − x</code>，最后 <code>f(x)+x</code> 又自动拼回 H(x)。网络训练时早把「+x」算在内，会主动调整 f 去配合它——最终该输出什么还是什么，只是「这一层负责算哪部分」换了分工。「残差」（residual = 余项、差值）由此得名。</p>
    <p>更妙的是这让「按需微调」极其廉价：若某一层最该做的是「别添乱、把输入原样传下去」，普通层要逼一组权重恰好凑出恒等映射（很难），残差层只需让 <code>f(x)≈0</code>——<strong>「什么都不学」反而成了最容易达成的默认</strong>。于是深层网络可以「能不动就不动，要动只动一点」，叠到上百层也不怕被中间某层搅乱。</p>

    <h2>为什么能通：那个「+1」</h2>
    <p>关键全在求导。对 <code>y = f(x) + x</code> 求梯度：<code>∂y/∂x = ∂f/∂x + 1</code>。那个孤零零的<strong>「+1」就是命根子</strong>——哪怕 ∂f/∂x 小到 0.01，这一层的总梯度也是 1.01，稳稳压在 1 附近。于是 96 层连乘不再是 0.9⁹⁶，而是接近 1.01⁹⁶ ≈ 2.6 这种温和的数：既没碾成零也没吹爆。反向传播时梯度沿两条路回传：一条穿过 f(x)（可能很小），一条走捷径（梯度恒为 1、不衰减）——相当于给梯度铺了一条一路直通回第 1 层的高速路。</p>
    <div class="llm-box hint">
      回看第 21 课那台「最简 Transformer」，真实块里注意力和 FFN 后面各跟一个「Add & Norm」稳定器——那个「Add」就是这里的 <code>f(x)+x</code>，它一直在偷偷给梯度修高速路；并排的「Norm」是下一站的主角。
    </div>

    <h2>发现不足：高速路只进不减，量级滚雪球</h2>
    <p>那条只进不减的高速路，每过一块就往上加一截 f，一路加下去数值会不会越滚越大？确实会。但别全怪残差：「深层网络激活值尺度到处乱跑、得不时校准」本来就是个通病，残差只是让它以「单调膨胀」这种显眼的方式冒出来。</p>
    <p>要收拾的隐患是<strong>激活值量级慢慢漂</strong>：某些维度越加越大、另一些越来越小，十几层后同一条向量里可能一个分量是 10000、另一个是 0.001。以记号 <code>x_ℓ</code> 表示数据流过第 ℓ 块之后的向量（残差累加即 <code>x_{ℓ+1} = x_ℓ + f_ℓ(x_ℓ)</code>），用范数 <code>‖x‖</code>（向量的长度）量它——假设刚进网络时 ‖x‖≈1，每过一块被 +f 顶大一点，4 块就到 6.6 倍，到第 12 块近 30 倍。不拉回来会撞两堵墙：</p>
    <ol class="llm-steps">
      <li><strong>数值精度撑不住</strong>：大模型常用 16 位浮点训练，量级失控要么溢出成 inf/NaN 当场崩盘，要么大数把小数「吃掉」（10000 和 0.001 相加，0.001 被直接舍没）。</li>
      <li><strong>该敏感的地方变迟钝</strong>：Softmax 对输入大小极其敏感，数一旦过大，输出就一边倒挤成「非 0 即 1」，注意力只死盯一个词、梯度几乎归零。</li>
    </ol>

    <h2>迭代：LayerNorm 把数值拉回正常量级</h2>
    <p>正是为了堵这两堵墙，<strong>LayerNorm（层归一化）</strong>登场。它对每一个词向量单独做三步：</p>
    <ol class="llm-steps">
      <li>求这条向量的均值与标准差：<code>μ = mean(x), σ = std(x)</code></li>
      <li>归一化到均值 0、标准差 1：<code>x̂ = (x − μ) / σ</code></li>
      <li>再缩放平移（参数可学）：<code>output = γx̂ + β</code></li>
    </ol>
    <div class="llm-box hint">
      手算一条 4 维向量 <code>x = [8, 2, 2, 4]</code>：均值 μ=4；方差 = (16+4+4+0)/4 = 6，σ = √6 ≈ 2.45；归一化后 <code>x̂ ≈ [1.63, −0.82, −0.82, 0]</code>——一条量级乱七八糟的向量被拉成均值 0、标准差 1 的标准向量。第③步的 γ、β 是可学习参数：归一化是死规矩，但网络能靠 γ、β 把分布「拧」回它真正想要的范围——既享稳定又不丢灵活。
    </div>

    <h2>迭代：Norm 放前还是放后</h2>
    <p>残差 + LayerNorm 都有了，但它俩<strong>谁先谁后</strong>竟决定深层模型训不训得起来，这是 2019 年后才被业界看清的坑：</p>
    <ul>
      <li><strong>Post-LN（原始 2017）</strong>：<code>y = LN(x + f(x))</code>——Norm 压在残差主路之后，等于在高速路上设了收费站，x 被二次加工、主路受扰，深层时梯度仍不稳，得靠脆弱的学习率预热哄着训。</li>
      <li><strong>Pre-LN（现代 GPT）</strong>：<code>y = x + f(LN(x))</code>——Norm 挪到子层之前的<strong>支路</strong>上，残差主路全程畅通，那个 +x 完全没被 Norm 碰过。这才是 GPT 能稳稳堆到几十上百层的关键。</li>
    </ul>
    <p>还有个更省的变体 <strong>RMSNorm</strong>（LLaMA 等在用）：它连均值都不减，只把向量除以自己的「均方根」来定量级——少算一步、参数更少，效果却几乎一样，印证了这一卷反复出现的审美：能简则简，简到不能再简为止。</p>

    <h2>总结</h2>
    <p>残差连接 <code>y = f(x) + x</code> 的那个「+1」给梯度留一条不衰减的高速路，96 层连乘也不消失；LayerNorm 把每条向量拉回均值 0、标准差 1，挡住数值漂移；再加一个讲究——Pre-LN 让残差主路保持纯净。三者加起来，才有了今天能稳稳堆到上百层的深层模型。</p>
    <div class="llm-term"><span class="term-name">「残差连接与层归一化（Add & Norm）」</span>是指两个让超深 Transformer 能训练的分工：残差连接 <code>y = f(x) + x</code> 给梯度留一条导数恒为 1、不衰减的捷径（那个「+1」把每层梯度钉在 1 附近、彻底缓解沿深度的梯度消失/爆炸）；层归一化 LayerNorm 把每条词向量减均值、除以标准差再可学地缩放平移，拉回标准量级、拦截数值漂移；并配合 Pre-LN 让残差主路保持畅通。</div>
