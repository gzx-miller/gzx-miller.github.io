      <li>回归验证全靠人记，规则一多就点不全，漏掉的那条往往就是出问题的。</li>
      <li>业务规则写死在组件内部，和渲染、事件、DOM 缠在一起，<strong>没法脱离页面单独验证</strong>。</li>
      <li>改动缺乏信心，只能靠「我觉得应该没问题」，出了问题也只能等用户先发现。</li>
      <li>一旦重构组件结构，之前所有手动「验证过」的结论全部作废，得从零点一遍。</li>
    </ul>

    <h2>输入输出边界清晰</h2>
    <p>
      不推翻「验证结果」，而是让逻辑变得<strong>输入和输出都清晰</strong>。一个模块如果能说清「给它什么、它返回什么、它在什么条件下做什么」，它就天然容易被验证；反过来，一个模块要测，得先启动页面、模拟点击、再扒内部状态，成本高得没人愿意写。
    </p>
    <p>
