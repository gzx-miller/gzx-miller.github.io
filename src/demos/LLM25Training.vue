    <div class="llm-question"><strong>开场问题：</strong>「会接话」和「会帮忙」之间隔着一道鸿沟——ChatGPT 是怎么迈过去的？</div>

    <h2>提出问题</h2>
    <p>上一课我们拿到一台叠了上百层、在 1TB 文字上练过「预测下一个词」的 GPT。它知识渊博，可你让它「帮我写一封向房东投诉漏水的邮件」时，它会一本正经地接话——像把网文的开头往下续。原因很简单：它脑子里只有「下一个词最可能是什么」，根本没有「替用户完成一件事」的概念。<strong>预测下一个词，离会帮忙，还隔着一条鸿沟。</strong></p>

    <h2>最小方案</h2>
    <p>跨过这道鸿沟要走三步，缺一步模型都不完整：</p>
    <ol class="llm-steps">
      <li><strong>预训练</strong>：海量文本里预测下一词——学「知识/才华」。</li>
      <li><strong>SFT（监督微调）</strong>：指令-回答范例——学「问答格式/礼仪」。</li>
      <li><strong>RLHF（人类偏好强化学习）</strong>：把人类偏好炼成打分器——学「价值观」。</li>
    </ol>
    <p>第一步的目标和第十四课一模一样：给定前 <code>k</code> 个词、预测第 <code>k+1</code> 个，变的只有规模。GPT-3 用约 3000 亿 token，Llama-3 用约 15 万亿 token；一次训练耗资常达上千万美元，是三步里唯一烧钱到这个量级的。为什么这个朴素目标能学出「智能」？因为想把下一词预测准，你就<strong>被迫去理解世界</strong>：「太阳从＿升起」要填「东」就得懂地球自转。预训练就这样把语言、事实、推理、代码悄悄压进了几千亿个参数里——但它学到的是「续写」，不是「听话」。</p>

    <h2>发现不足</h2>
    <p>光有预训练，模型只是「续写机器」。SFT 想把它变成「对话助手」，可这又带来新问题：</p>
    <ul>
      <li>预训练只会续写整段对话，不知道「轮到我该怎么说」。</li>
      <li>SFT 学会了「格式」却评不了「好坏」——「好回答」本就没有唯一标准答案。</li>
      <li>没法给每种刁钻问题都写出范例，光靠模仿范例，到头了。</li>
    </ul>

    <h2>迭代</h2>
    <p><strong>SFT 用一个机关教会「该在哪儿开口」。</strong>对话被套进固定模板，且损失只算回答那一段：用户那段当「已知条件」不算损失，只训练模型生成回答。就这么点改动，模型看到 <code>&lt;|user|&gt;</code> 就知道现在轮到自己按回答格式说话，而不是把你的话往下接。</p>
    <p><strong>可「答得好」还是没解决。</strong>于是换一种问法：不让人写标准答案，只让人做选择题——同一问题给两个回答 A/B，问一句谁都答得上来的话「哪个更好」。收集几十万条这样的「A 比 B 好」比较，训练出一个奖励模型（Reward Model）：本质是另一个 Transformer，只是顶上换成「打分头」，学过让 <code>r(好回答) &gt; r(差回答)</code>，从而能给任意回答打分。「说不清的好」被悄悄量化成一个可计算的分数。</p>
    <p><strong>上下半场：用打分器反拧语言模型。</strong>拿到分数当「奖励」，让高分回答更可能被说出来（梯度上升）。但一味追高分会「奖励欺骗」——模型找到被误判为高分却车轱辘废话的策略疯狂复读。所以要栓一根缰绳：在奖励里减去一项「别离原 SFT 模型太远」的惩罚（KL 散度）：<code>奖励 = r(x,y) − β·KL(新模型 ∥ SFT模型)</code>。一边追高分、一边被缰绳拽着别走火入魔，这就是经典的 <strong>PPO</strong>。它有效但笨重，要同时伺候语言、奖励、参考好几个网络；于是 2023 年出了精简版 <strong>DPO</strong>——跳过奖励模型和整套 RL 循环，直接在偏好数据上用巧妙的损失一步拧到位，如今很多开源模型都改用了它。</p>

    <h2>总结</h2>
    <p>大模型分三步炼成：预训练（海量文本预测下一词，得才华）→ SFT（指令范例 + 只算回答的损失，学礼仪）→ RLHF（把人类两两偏好炼成奖励模型，再用它加 KL 缰绳拧语言模型，立价值观）。鸿沟、SFT 模板、奖励模型、RL+KL 缰绳、PPO→DPO，缺任何一环都无法从「会接话」走到「会帮忙」。</p>
    <div class="llm-term"><span class="term-name">「RLHF（基于人类反馈的强化学习）」</span>是指，先用人类对一对回答的偏好排序炼出一个奖励模型给任意回答打分，再把这个分数当「奖励」反向微调语言模型、并用 KL 惩罚防止它背离 SFT 版本的对齐方法。</div>
