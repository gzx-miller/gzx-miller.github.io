    <h2>组合优于堆叠</h2>
    <p>
      子图把「大图」拆成可组合的流程单元：编译后的图可以直接作为父图节点，父子图通过输入输出 schema 约定契约，检查点按命名空间隔离。它让复杂系统获得模块化的能力，代价是多一层映射与追踪。判断标准不是图有多大，而是这段流程是否值得被单独复用、测试与演进。
    </p>
