    <h2>把一段流程封装成子图</h2>
    <p>
      子图不是新概念，它就是<strong>一张编译好的普通图</strong>。把检索相关的 plan → search → synthesize 单独建成一张 <code>StateGraph</code>，<code>compile()</code> 之后得到一个可执行对象；父图用 <code>addNode('research', researchGraph)</code> 把它当成一个节点挂上去。对父图来说，子图就是一个普通节点：有输入、有输出、执行完把控制权交回。
    </p>
    <p>
      这样做的好处是<strong>边界清晰</strong>：子图可以单独测试、单独替换、单独复用；父图只关心「给它什么、拿回什么」，不必知道内部有几个步骤。子图内部还可以继续嵌套子图，形成分层结构，但层级越深，追踪与调试的成本越高。父图的状态 schema 也不必包含子图的内部字段，主流程的字段列表因此能保持精简。
    </p>

    <h2>状态 schema 的共享与映射</h2>
    <p>
      父子图各自声明状态，字段可以共享，也可以只暴露一部分。常见做法是给子图声明<strong>输入 schema</strong>与<strong>输出 schema</strong>：父图传进来的字段必须满足输入 schema，子图结束时只把输出 schema 里的字段映射回父图。中间字段——检索计划、候选列表、临时笔记——留在子图内部，不污染父图状态。
    </p>
    <ul>
      <li><strong>字段同名且类型兼容</strong>：可以直接透传，父图的 <code>topic</code> 就是子图的 <code>topic</code>。</li>
      <li><strong>字段不同名</strong>：在子图节点外包一层适配，或让子图节点声明自己的输入映射，把父图字段转成子图字段。</li>
      <li><strong>只回传结果</strong>：子图输出 <code>{ sources }</code>，父图只合并 <code>sources</code>，内部中间状态不进入父图。</li>
    </ul>
    <p>
      映射不是免费的。每加一层 schema，就多一处需要维护的契约；字段改名时，父子图要同步调整。拆之前先问：这段流程真的会被复用吗，还是只是「看起来很长」？如果确实要拆，最好让子图的输入输出只包含<strong>稳定的业务字段</strong>，不要直接把父图整份状态透传——一旦透传，子图就隐式依赖了父图的全部字段，复用性也随之消失。
    </p>

    <h2>子图有独立的检查点命名空间</h2>
    <p>
      开启 checkpointer 后，子图的检查点不会混进父图的线程里，而是挂在<strong>独立的命名空间</strong>下，形如 <code>thread_id|research:&lt;任务标识&gt;</code>。父图查询状态时，默认只看到映射后的输出字段；子图内部的每一步快照需要按命名空间单独查询。
    </p>
    <p>
      这个设计是有意的：父图不应该依赖子图的内部实现，否则子图就无法独立替换。但排障时要记住这一点——「父图状态里没有 search 的中间结果」不是 bug，而是隔离的结果。需要看内部过程时，按命名空间取子图历史，或者在开发期用可视化工具展开子图。反过来说，如果父图业务确实需要子图的中间结果，就应该把它写进子图的输出 schema，而不是绕过隔离去读内部快照。
    </p>

    <h2>什么时候该拆，什么时候不该拆</h2>
    <p>
      子图适合三种情况：<strong>流程会被多个父图复用</strong>、<strong>内部步骤需要独立测试或独立演进</strong>、<strong>团队分工以流程段为边界</strong>。反过来，只有两三个节点、没有复用需求、状态字段高度耦合的流程，拆成子图只会增加一层跳转和一套 schema 映射。
    </p>
    <p>
      还有一个隐性成本：<strong>可观测性变复杂</strong>。一次父图运行会变成父子两级时间线，日志、追踪、错误堆栈都要能关联到命名空间。拆之前先确认工具链能展开子图，否则排障时你会在两层之间来回找。错误传播也要提前约定：子图内部抛错会中止父图节点，父图是重试、降级还是把错误写入状态，应该在设计时写清楚，而不是等线上第一次失败再补。
    </p>

