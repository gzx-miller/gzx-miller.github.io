// ═══════════════════════════════════════════
// 1. 算术运算符
// ═══════════════════════════════════════════

7 % 3             // 1  —— 取余
-7 % 3            // -1 —— 结果的符号跟随被除数
2 ** 3            // 8  —— 幂运算
2 ** 3 ** 2       // 512 —— ** 右结合，等价于 2 ** (3 ** 2)

let i = 5
const pre = ++i   // pre 为 6，i 为 6 —— 前置：先加再用
const post = i++  // post 为 6，i 为 7 —— 后置：先用再加

0.1 + 0.2 === 0.3 // false —— 浮点精度问题

// ═══════════════════════════════════════════
// 2. 比较与字符串比较
// ═══════════════════════════════════════════

'2' > '10'        // true  —— 字符串逐位比较，先比首字符 '2' > '1'
'b' > 'a'         // true
[1, 2] < [1, 3]   // true  —— 转成 '1,2' 与 '1,3' 再比较
'5' < 3           // false —— 两侧先转成数字，5 < 3

// ═══════════════════════════════════════════
// 3. 逻辑运算返回的是操作数
// ═══════════════════════════════════════════

0 || 'x'          // 'x'   —— 左侧是假值，返回右侧操作数
'a' && 'b'        // 'b'   —— 左侧是真值，返回右侧操作数
'' || 'default'   // 'default' —— 空字符串被当成假值
0 ?? 'default'    // 0     —— ?? 只对 null/undefined 兜底
false || 0        // 0     —— || 会跳过 false，把 0 当兜底值

// ═══════════════════════════════════════════
// 4. 可选链与空值合并
// ═══════════════════════════════════════════

const user = { profile: { bio: '收集栗子' }, list: [] }
user?.address?.city       // undefined —— 链上缺失也不报错
user?.profile?.bio        // '收集栗子'
user?.list?.[0]           // undefined —— 可选索引
user?.save?.()            // undefined —— 函数不存在时不调用，也不报错

// ═══════════════════════════════════════════
// 5. 逻辑赋值
// ═══════════════════════════════════════════

let title
title ??= '默认标题'      // '默认标题' —— 空值才赋值
let count = 0
count ||= 5               // 5 —— 假值就赋值（0 被覆盖）
let flag = true
flag &&= false            // false —— 真值才赋值

// ═══════════════════════════════════════════
// 6. 位运算与权限标志
// ═══════════════════════════════════════════

const READ  = 0b001       // 1
const WRITE = 0b010       // 2
const ADMIN = 0b100       // 4

let perms = 0
perms |= READ             // 1  —— 按位或：授予读权限
perms |= WRITE            // 3  —— 继续授予写权限
perms & READ              // 1  —— 按位与：非 0 即拥有读权限
perms & ~WRITE            // 1  —— 与非：撤销写权限
perms ^ ADMIN             // 7  —— 异或：切换管理权限

5 & 3                     // 1  —— 101 & 011
5 | 3                     // 7  —— 101 | 011
5 ^ 3                     // 6  —— 101 ^ 011
~5                        // -6 —— 按位取反，先转为 32 位有符号整数
1 << 3                    // 8  —— 左移三位
-8 >> 1                   // -4 —— 有符号右移，保留符号位
-8 >>> 1                  // 2147483644 —— 无符号右移，高位补 0
