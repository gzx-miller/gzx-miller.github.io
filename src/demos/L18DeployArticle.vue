    <p>
      不推翻「先查后算」，而是把判断命中的那把尺子，从「比较字符串」升级成「比较语义」。
    </p>
    <p>
      第一步，<strong>让缓存按向量相似度命中</strong>。用嵌入模型把每句 prompt 转成向量，检索最相近的历史问题，相似度超过阈值就复用它的答案——这就是<strong>语义缓存</strong>。它认的是「这句话在说什么」，而不是「这句话怎么打出来的」，所以「怎么退款」和「如何退款」会落在很近的位置，命中同一个缓存。
