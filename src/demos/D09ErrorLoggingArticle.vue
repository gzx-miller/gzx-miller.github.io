      <strong>开场问题：</strong>用户请求了一个根本不存在的课程 id，接口却返回 <code>500</code>「服务器内部错误」；用户以为是自己网不好、反复重试，运维还在告警群里排查一台根本没坏的服务器——一个再普通不过的业务错误，为什么会被包装成系统级故障？
    </div>

    <h2>出错时要同时做两件事</h2>
    <p>
      服务跑起来就免不了出错，而出错之后你要<strong>同时</strong>完成两个目标：给调用方一个合适的响应，也给自己留一条能排查的线索。最省事的做法，是在请求入口统一 <code>try ... catch</code>，把异常 <code>console.log</code> 出来，一律返回 <code>500</code>。
    </p>
    <p>
      这一手至少保证了一件事：<strong>所有错误都有统一出口</strong>——响应总能正常结束，进程也不至于因一个未捕获的异常直接倒下。它的问题在于，把两类完全不同的错误压成了同一个结果。
    </p>

    <h2>一锅端的后账</h2>
    <ul>
      <li>调用方<strong>分不清</strong>「你参数传错了（重试也没用）」和「我这边炸了（稍后或许能好）」，只能盲目重试。</li>
      <li><code>console.log(err)</code> 只留下堆栈，<strong>缺请求 ID、用户 ID 与入参</strong>，几十条并发日志里根本串不出是谁、在哪一步失败的。</li>
      <li>把 <code>err.message</code> 或堆栈直接回给客户端，等于把内部结构、甚至内部路径与 SQL 暴露出去。</li>
      <li>真正该被重视的 bug 被吞掉后，<strong>进程可能带着不一致的状态继续处理后续请求</strong>，每一个都是错的。</li>
      <li>日志里混进 token、密码、手机号，排查没帮上忙，先造成了一次越权泄漏。</li>
    </ul>
    <p>
      问题落到一句话：错误该不该分类？给调用方的，和自己要留的，分别是什么？
    </p>

    <h2>先分类：操作型与程序型</h2>
    <p>
      一切处理都由一次分类开始。<strong>操作型错误</strong>是预期之内、能对应调用方一个具体动作的问题——参数缺失、权限不足、资源不存在、下游超时；<strong>程序型错误</strong>是本不该出现的 bug 或崩溃级故障。它们对应两条完全不同的出路：前者转成稳定的错误码交还给调用方，后者记录完整上下文后交给进程管理器重启。
    </p>
    <p>
      再给操作型错误建立稳定的「<strong>错误码 → HTTP 状态</strong>」映射：资源不存在用 <code>404</code>、参数不合法用 <code>400</code>、未认证用 <code>401</code>。调用方拿到错误码就能决定是提示用户改参数、还是稍后重试，而不是对着一个笼统的 500 干猜。
    </p>

    <h2>在系统边界捕获并映射</h2>
    <p>
      捕获的位置也讲究：放在<strong>系统边界</strong>——请求入口、以及调用下游服务的那条出口。这样异步错误才在它将要泄漏到系统之外的地方被接住。整个流程可以拆成几步：
    </p>
    <ol class="lesson-steps">
      <li>在边界用 <code>try ... catch</code> 捕获异常，注意异步函数里的错误要 <code>await</code> 到才会被接住。</li>
      <li>把内部错误映射成公开的错误码与合适的 HTTP 状态。</li>
      <li>用固定字段记录请求 ID 与内部原因，堆栈只进服务端日志。</li>
      <li>故意制造一次失败，核对返回的错误码与日志字段是否对得上。</li>
    </ol>
    <p>
      给程序型错误设计出口时，判断只有一条：<strong>捕获后记录完整堆栈与上下文，对外只回一个不带内部细节的笼统 500，然后把进程交给进程管理器去重启</strong>。不让它带病继续运行，比任何补救都重要。串接错误链时可以用 <code>Error</code> 的 <code>cause</code> 选项，把底层异常挂在自定义错误的背后，既不丢失根因，也不把它暴露给外部。
    </p>

    <h2>结构化日志与脱敏</h2>
    <p>
      自己这一侧要的可排查性，靠的是<strong>结构化日志</strong>：以 JSON 输出、字段固定（时间、级别、错误码、请求 ID、用户 ID、简短原因）。这样的日志既看得懂，也能被检索和聚合。把请求 ID 从入口一路带到每个日志点，同一笔请求的所有记录就串成一条线。
    </p>
    <p>
      与「记全」相反的另一头是<strong>脱敏</strong>：落盘前剔除 token、密码、身份证、手机号这类敏感字段；序列化错误对象时只取进白名单的字段，而不是把整个对象原样倒出去。可排查与不泄漏，要一起满足。
    </p>

    <h2>全局兜底别当耳旁风</h2>
    <p>
      再补两道最后防线：注册 <code>process.on('uncaughtException')</code> 与 <code>process.on('unhandledRejection')</code>，接住那些漏网的异常与未处理的 Promise 拒绝。要记住它们不是「打印一下、接着跑」，而是记录后按既定策略退出或上报——否则进程就带着一个未知的坏状态继续服务。
    </p>
    <div class="lesson-box warn">
      <strong>两件最容易被忽略的事：</strong>未处理的 Promise 拒绝如果只 <code>console.log</code> 就放过，等于把一个失控状态留着不管；任何时候都不要把 <code>err.stack</code> 或原始 <code>err.message</code> 直接返回给客户端——对外只给稳定错误码，堆栈留给服务端日志。
    </div>

