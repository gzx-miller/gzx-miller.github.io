    <div class="llm-question"><strong>开场问题：</strong>知道了往哪边走是下坡，一步该迈多大？</div>

    <h2>提出问题</h2>
    <p>上一课机器有了损失。这一课真正开始调参数——把损失降下去，用第 5 课学过的「蒙眼下山」。梯度 <code>∇L</code> 指出最陡的上坡方向，朝它反方向迈步就是下坡，更新公式为 <code>w ← w − ∇L</code>。听上去万无一失，可真迈一步就翻车。</p>

    <h2>最小方案</h2>
    <p>盯住其中一个权重 <code>w</code>，假设损失 <code>L(w) = 1.5(w − 4.5)²</code>，谷底在 <code>w = 4.5</code>。权重停在 <code>w = 0.5</code>，此刻损失 <code>L(0.5) = 24</code>；求导得 <code>∂L/∂w = 3(w−4.5)</code>，代入得 −12（负号说明往右即 w 变大是下坡）。做一个直接用梯度值更新的试验：<code>w ← 0.5 − (−12) = 12.5</code>。</p>
    <h3>发现不足：一步飞过谷底</h3>
    <p>把 12.5 代回损失：<code>L(12.5) = 96</code>。<strong>损失从 24 不降反升、飙到 96</strong>！方向其实没错（确实朝下坡迈），问题出在步子——一步迈了整整 12，直接飞过谷底 <code>w=4.5</code>、冲到对面更高的山坡。看来「方向对」不等于「走得到谷底」，还得管住<strong>步幅</strong>。</p>

    <h2>迭代</h2>
    <p>引入<strong>学习率 α</strong>，更新公式变成 <code>w ← w − α·∇L</code>，α 通常是 0.001~0.1 的小数。选多大是训练里最棘手的决定：<em>α 太大</em>，损失曲线震荡、无法收敛；<em>α 太小</em>，下降极慢。实践中用<strong>学习率调度</strong>——初期用较大的 α 快速接近最优区，后期逐渐降低（如余弦退火、线性预热）。</p>
    <h3>另一个问题：梯度算在哪些数据上</h3>
    <p>到目前为止 <code>∇L</code> 都是基于<strong>所有训练样本</strong>的平均损失。更新一次参数就要把整个训练集跑一遍——GPT-3 有 3000 亿 token；假设 10 亿条数据每条前向 1ms，算一次梯度就要 277 小时，完全没有实用价值。两个极端都不行：全量太慢，单样本太抖。</p>
    <h3>折中：Mini-batch SGD</h3>
    <p>每次随机抽取 <code>B</code> 条样本（一个 batch）算平均梯度再更新，B 通常取 32、64、128。<code>w ← w − α·(1/B)·Σ∇Lᵢ</code>，这叫 <strong>Mini-batch 随机梯度下降</strong>。「随机」指每次梯度都带一点噪声——噪声有时反而有好处：帮助跳出「小坑」（局部最小值）、找到泛化更好的区域，纯全量梯度反而更容易陷进局部最优。一个 epoch 是扫完整个训练集一遍，完整训练通常需要几十到几百个 epoch。</p>
    <h3>还不够好：峡谷地形与 Adam</h3>
    <p>Mini-batch 在「峡谷地形」（一个方向陡、一个方向平）里会沿陡峭方向来回震荡、平缓方向却走得很慢。加入<strong>动量（Momentum）</strong>给更新加惯性，用历史梯度的加权平均代替单步梯度：<code>v = βv + (1−β)∇L</code>，<code>w ← w − α·v</code>，β ≈ 0.9——震荡相互抵消、平缓方向逐步积累速度，收敛更快。现代训练几乎都用 <strong>Adam</strong>：在动量的基础上还为每个参数维护自适应学习率，默认 <code>α=0.001, β₁=0.9, β₂=0.999</code> 开箱即用，Transformer 几乎清一色用它（或变种 AdamW）。</p>

    <h2>总结</h2>
    <p>梯度告诉方向，学习率 α 控制步长；全量太慢、单样本太抖，Mini-batch 是折中；Adam 把动量和自适应学习率合二为一，是现代深度学习训练的事实标准。</p>
    <div class="llm-term"><span class="term-name">「梯度下降与优化器」</span>是指用损失对参数的梯度指导更新的方法：学习率 α 控制每次迈步大小，避免步子太大飞过最优点；用一小批样本估算梯度（Mini-batch SGD）在速度与精度间折中；再加入动量和每参数自适应学习率的 Adam 成为现代训练标配。</div>
