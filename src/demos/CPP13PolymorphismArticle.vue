    <h2>按类型分别实现</h2>
    <p>
      你要写一段"统一处理一批图形"的逻辑：不管它是圆还是矩形，都要能算面积、能把自己画出来。最省事的做法是按类型分头写：圆的循环处理圆，矩形的循环处理矩形，加一种图形就再加一段。它带来的隐藏成本有三笔：
    </p>
    <ul>
      <li>每新增一种图形，所有按类型分派的地方都得改一遍，漏一处就是线上 bug。</li>
      <li>一个容器只能装同一种类型，没法把圆和矩形混在一个列表里统一处理。</li>
      <li>分派靠的是你手写的类型标签，标签和真实类型是两个东西，容易不同步。</li>
    </ul>
    <p>
      所以要问的是：<strong>能不能让"该调用哪个函数"这件事，在运行时根据对象的真实类型自动决定，而不是靠人在代码里写死？</strong>
    </p>

    <h2>类型标签分支</h2>
    <p>
      最省事也真的能跑的做法，是在基类里放一个<strong>类型标签</strong>字段，调用处用分支分派：
    </p>
    <p>
      <code>if (s.type == CIRCLE) return areaOfCircle(s); else if (s.type == RECT) return areaOfRect(s);</code>
    </p>
    <p>
      这个方案做对了一件要紧的事：<strong>它承认了"该调用哪个实现，取决于对象的实际类型"</strong>。在没有虚函数的世界里，这正是唯一可行的办法，逻辑上没毛病。
    </p>

    <h2>分派点漏改的后果</h2>
    <ul>
      <li>新增一种图形后，每一个分派点都得进去补一个分支，任何一处漏改，这种图形在那里就会走进错误分支或默认分支。</li>
      <li>它只覆盖你事先枚举过的类型；第三方定义的新类型根本放不进来，除非回头改这段代码。</li>
      <li>类型标签是"人维护的元数据"，一旦有人忘了同步，实际类型和标签分离，分派结果就错了。</li>
      <li>如果把标签去掉、只留一个基类指针，而函数又不是虚的，那么通过指针调用时编译器只看得到"指向基类"，永远调基类版本。</li>
    </ul>

    <h2>虚函数的引入</h2>
    <p>
      不推翻"按实际类型选实现"，而是把这件事从你手写的分支交给语言：在基类的函数前加 <code>virtual</code>，在派生类的重写版本上用 <code>override</code>。于是 <code>shape-&gt;area()</code> 这一句，运行时能自己落到对的实现上。这就是<strong>动态绑定</strong>。
    </p>
    <p>
      它凭什么能自动选对？靠的是一张<strong>虚函数表</strong>（vtable）和每个对象里的一个指针（vptr）。整个过程分三步：
    </p>
    <ol class="lesson-steps">
      <li><strong>编译期</strong>：为每一个包含虚函数的类各生成一张 vtable，表里按固定槽位记录了这个类各个虚函数的地址。</li>
      <li><strong>构造对象时</strong>：对象在内存里被写入一个 vptr，指向"本类"的那张 vtable。圆对象指向圆的表，矩形对象指向矩形的表。</li>
      <li><strong>调用 <code>shape-&gt;area()</code> 时</strong>：编译器不直接调用某个写死的地址，而是取出 <code>shape</code> 的 vptr，找到它指向的 vtable，再在固定槽位里取出 <code>area</code> 的函数地址，最后间接调用。</li>
    </ol>
    <p>
      关键就在第 3 步：<code>shape</code> 指向的是圆还是矩形，它的 vptr 就指向不同的表，取出来的函数地址自然不同——<strong>同一句调用代码，落到了两份不同的实现</strong>。你看到的"自动选对"，本质是一次查表加一次间接调用。
    </p>
    <p>
      再往下补一层：如果基类某个函数根本不该有实现（比如 <code>Shape</code> 自己算不出面积），就写成<strong>纯虚函数</strong> <code>virtual double area() const = 0;</code>。含有纯虚函数的类是<strong>抽象类</strong>，不能创建对象；派生类必须重写全部纯虚函数，才能被实例化。这一步把"你必须提供这个实现"直接写进了类型系统——忘了写就编译不过，不用等到运行时才发现。
    </p>
    <p>
      别忘了虚析构函数。只要类可能有派生类、又可能通过基类指针删除，基类析构就要声明为 <code>virtual</code>，否则 <code>delete</code> 一个基类指针只会执行基类析构，派生类那部分资源没人回收。它和虚函数是同一套机制在起作用。
    </p>
    <p>
      最后是几条边界。开销方面：vtable 在编译期就生成好了，运行时只是查表和间接调用，代价是一次间接调用（可能影响分支预测），并不需要在运行期"搜索类型"。语义方面：<strong>构造函数和析构函数里调用虚函数不会触发动态绑定</strong>——构造基类时派生类部分还没建好、析构基类时派生类部分已经销毁，此时调用的只能是当前这一层的版本。限制方面：虚函数不能是 <code>static</code>（静态函数没有 <code>this</code>，拿不到 vptr），也不能是模板函数（模板在编译期实例化，虚函数在运行期决议）。C++11 的 <code>final</code> 可以阻止继续重写，也便于编译器做"去虚化"优化。
    </p>
    <div class="lesson-box warn">
      <strong>把虚函数想象成"能搜索类型"是常见误解：</strong>运行时并没有去查找对象的类型再挑选函数；一切在编译期就安排成了一张按类固定的函数地址表，运行期做的只是"顺着 vptr 查表、间接调用"。另外，把派生对象按值装进存放基类对象的容器会触发切片，多态会当场失效——容器里要放指针或智能指针。
    </div>

