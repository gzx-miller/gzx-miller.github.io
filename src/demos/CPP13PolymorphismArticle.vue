      <strong>开场问题：</strong>一个容器里同时装着圆和矩形，循环里只有一句 <code>shape-&gt;area()</code>，圆却算出圆的面积、矩形算出矩形的面积——同一个变量名、同一行代码，运行时怎么会跑到两个不同的函数里去？
