    <h2>运行期的动态分派</h2>
    <p>
      多态是把"该调用哪个函数"从编译期的手写分支，推迟到运行期由对象的真实类型决定。关键字只有 <code>virtual</code> 与 <code>override</code>，机制则是一张类级别的 vtable 加每个对象里的 vptr；再配上纯虚函数定义接口、虚析构保证清理，你就能做到"新增一种类型，而不用回头改动老代码"。
    </p>
    <div class="lesson-term">
      <span class="term-name">「动态绑定」</span>指通过基类的指针或引用调用虚函数时，实际执行哪一个函数不在编译期写死，而是在运行期依据对象的真实类型，经对象内的 vptr 查虚函数表（vtable）取出函数地址后间接调用。边界：它仅在"通过指针或引用调用虚函数"时成立；用基类对象按值接收会切片、构造函数与析构函数中调用虚函数也不触发动态绑定。
