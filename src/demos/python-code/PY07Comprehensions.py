# ═══════════════════════════════════════════
# 1. 列表推导式
# ═══════════════════════════════════════════

squares = [x * x for x in range(6)]
print(squares)             # 结果：[0, 1, 4, 9, 16, 25]

# ═══════════════════════════════════════════
# 2. 带条件过滤
# ═══════════════════════════════════════════

evens = [x for x in range(10) if x % 2 == 0]
print(evens)               # 结果：[0, 2, 4, 6, 8]

# ═══════════════════════════════════════════
# 3. 嵌套推导（笛卡尔积）
# ═══════════════════════════════════════════

pairs = [(x, y) for x in range(2) for y in range(2)]
print(pairs)               # 结果：[(0, 0), (0, 1), (1, 0), (1, 1)]

# ═══════════════════════════════════════════
# 4. 字典推导式
# ═══════════════════════════════════════════

lengths = {w: len(w) for w in ["a", "bb", "ccc"]}
print(lengths)             # 结果：{'a': 1, 'bb': 2, 'ccc': 3}

# ═══════════════════════════════════════════
# 5. 集合推导式
# ═══════════════════════════════════════════

mods = {x % 3 for x in range(6)}
print(mods)                # 结果：{0, 1, 2}，自动去重

# ═══════════════════════════════════════════
# 6. 生成器表达式与惰性求值
# ═══════════════════════════════════════════

gen = (x * x for x in range(5))
print(next(gen))           # 结果：0
print(next(gen))           # 结果：1
print(list(gen))           # 结果：[4, 9, 16]，前面的已被取走

# ═══════════════════════════════════════════
# 7. iter / next 手动迭代
# ═══════════════════════════════════════════

it = iter([10, 20])
print(next(it))            # 结果：10
print(next(it))            # 结果：20
try:
    next(it)               # 已耗尽
except StopIteration:
    print("迭代结束")       # 结果：迭代结束
