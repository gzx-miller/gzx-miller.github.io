# ═══════════════════════════════════════════
# 1. 增删改查
# ═══════════════════════════════════════════

nums = [3, 1, 4]
nums.append(1)             # 结果：[3, 1, 4, 1]
nums.insert(0, 9)          # 结果：[9, 3, 1, 4, 1]
nums.remove(1)             # 结果：[9, 3, 4, 1]，删第一个匹配项
last = nums.pop()          # 结果：last = 1，nums = [9, 3, 4]
print(last, nums)

# ═══════════════════════════════════════════
# 2. 排序：sort 就地 vs sorted 新建
# ═══════════════════════════════════════════

vals = [3, 1, 2]
print(sorted(vals))        # 结果：[1, 2, 3]，原列表不变
print(vals)                # 结果：[3, 1, 2]
vals.sort(reverse=True)    # 就地排序，返回 None
print(vals)                # 结果：[3, 2, 1]

# ═══════════════════════════════════════════
# 3. sort(key=...) 自定义排序规则
# ═══════════════════════════════════════════

words = ["bbb", "a", "cc"]
words.sort(key=len)        # 按长度排序
print(words)               # 结果：['a', 'cc', 'bbb']

# ═══════════════════════════════════════════
# 4. 切片与切片赋值
# ═══════════════════════════════════════════

seq = [0, 1, 2, 3, 4, 5]
print(seq[1:4])            # 结果：[1, 2, 3]，不含 stop
print(seq[::-1])           # 结果：[5, 4, 3, 2, 1, 0]
seq[1:3] = [9, 9]          # 切片赋值，就地替换那一段
print(seq)                 # 结果：[0, 9, 9, 3, 4, 5]

