# ═══════════════════════════════════════════
# 6. 共享引用陷阱：[[0]*3]*3
# ═══════════════════════════════════════════

grid = [[0] * 3] * 3       # 三行共享同一个内层列表
grid[0][0] = 1
print(grid)                # 结果：[[1, 0, 0], [1, 0, 0], [1, 0, 0]]
safe = [[0] * 3 for _ in range(3)]  # 推导式让每行独立
safe[0][0] = 1
print(safe)                # 结果：[[1, 0, 0], [0, 0, 0], [0, 0, 0]]

# ═══════════════════════════════════════════
# 7. 可变默认参数陷阱
# ═══════════════════════════════════════════

def collect(item, box=[]):     # 默认列表只创建一次，被所有调用共享
    box.append(item)
    return box

print(collect(1))          # 结果：[1]
print(collect(2))          # 结果：[1, 2]，默认对象被复用

def collect_safe(item, box=None):  # 正确做法：用 None 兜底
    if box is None:
        box = []
    box.append(item)
    return box

print(collect_safe(1))     # 结果：[1]
print(collect_safe(2))     # 结果：[2]
