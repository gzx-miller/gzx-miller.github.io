# ═══════════════════════════════════════════
# 1. 引号与转义
# ═══════════════════════════════════════════

print('It\'s ok')          # 结果：It's ok，转义单引号
print("line1\nline2")      # 结果：两行文本，\n 是换行
print("tab\there")         # 结果：tab 与 here 之间有制表符

# ═══════════════════════════════════════════
# 2. f-string 的对齐与精度
# ═══════════════════════════════════════════

name, score = "Ada", 3.14159
print(f"[{name:>6}]")      # 结果：[   Ada]，右对齐宽 6
print(f"[{name:<6}]")      # 结果：[Ada   ]，左对齐宽 6
print(f"{score:.2f}")      # 结果：3.14，保留两位小数
print(f"{42:04d}")         # 结果：0042，整数补零到 4 位
print(f"{name} = {score:.2f}")  # 结果：Ada = 3.14

# ═══════════════════════════════════════════
# 3. 索引与切片（负索引、正负步长）
# ═══════════════════════════════════════════

s = "abcdef"
print(s[0], s[-1])         # 结果：a f，负索引取末字符
print(s[1:4])              # 结果：bcd，不含 stop
print(s[:3], s[3:])        # 结果：abc def
print(s[::2])              # 结果：ace，步长 2
print(s[::-1])             # 结果：fedcba，负步长反转

# ═══════════════════════════════════════════
# 4. split 与 join
# ═══════════════════════════════════════════

csv = "a,b,c"
parts = csv.split(",")     # 结果：['a', 'b', 'c']
print("-".join(parts))     # 结果：a-b-c
print("a b  c".split())    # 结果：['a', 'b', 'c']，按连续空白切分

# ═══════════════════════════════════════════
# 5. strip / replace / startswith
# ═══════════════════════════════════════════

raw = "  hi  "
print(raw.strip())                     # 结果：hi，去掉首尾空白
print("aXbXc".replace("X", "-"))       # 结果：a-b-c
print("hello".startswith("he"))        # 结果：True
print("hello".find("l"))               # 结果：2，返回首次出现的位置

# ═══════════════════════════════════════════
# 6. 三引号多行
# ═══════════════════════════════════════════

text = """第一行
第二行"""
print(text.count("\n") + 1)  # 结果：2，跨两行

# ═══════════════════════════════════════════
# 7. str 与 bytes（encode / decode）
# ═══════════════════════════════════════════

data = "栗子".encode("utf-8")
print(type(data))            # 结果：<class 'bytes'>
print(data)                  # 结果：b'\xe6\xa0\x97\xe5\xad\x90'
print(data.decode("utf-8"))  # 结果：栗子，还原回文本
