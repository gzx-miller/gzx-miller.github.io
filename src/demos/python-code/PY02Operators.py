# ═══════════════════════════════════════════
# 1. 算术与整除
# ═══════════════════════════════════════════

print(7 + 2)        # 结果：9
print(7 / 2)        # 结果：3.5，/ 恒为 float
print(7 // 2)       # 结果：3，向下取整的整除
print(7.0 // 2)     # 结果：3.0，带 float 则结果为 float
print(divmod(7, 2))  # 结果：(3, 1)，一次拿到商与余数

# ═══════════════════════════════════════════
# 2. 取余的符号跟随除数
# ═══════════════════════════════════════════

print(7 % 3)        # 结果：1
print(-7 % 3)       # 结果：2，余数符号跟随除数
print(7 % -3)       # 结果：-2
print(-7 // 2, -7 % 2)  # 结果：-4 1，满足 (-4) * 2 + 1 == -7

# ═══════════════════════════════════════════
# 3. 幂运算（右结合）
# ═══════════════════════════════════════════

print(2 ** 10)      # 结果：1024
print(2 ** -1)      # 结果：0.5，负指数返回 float
print(2 ** 3 ** 2)  # 结果：512，等价于 2 ** (3 ** 2)

# ═══════════════════════════════════════════
# 4. 链式比较
# ═══════════════════════════════════════════

x = 5
print(0 < x < 10)   # 结果：True
print(0 < x < 3)    # 结果：False
print(1 <= x <= 5)  # 结果：True，x 只求值一次

# ═══════════════════════════════════════════
# 5. and / or 的短路求值
# ═══════════════════════════════════════════

def noisy():
    print("副作用被执行了")
    return True

print(False and noisy())   # 结果：False，右侧不会执行
print(True or noisy())     # 结果：True，右侧不会执行
print(0 or "默认值")        # 结果：默认值，返回参与运算的对象本身
print("" and "不回执行")    # 结果：，空串为假直接返回

# ═══════════════════════════════════════════
# 6. == 比较值，is 比较身份
# ═══════════════════════════════════════════

a = [1, 2, 3]
b = [1, 2, 3]
print(a == b)       # 结果：True，值相等
print(a is b)       # 结果：False，不是同一个对象
print(a is not None)  # 结果：True，判断 None 用 is

# ═══════════════════════════════════════════
# 7. 增强赋值
# ═══════════════════════════════════════════

count = 1
count += 4          # 等价于 count = count + 4
count *= 3          # 等价于 count = count * 3
print(count)        # 结果：15

nums = [1, 2]
alias = nums
alias += [3]        # 列表的 += 走 extend，就地修改
print(nums)         # 结果：[1, 2, 3]，原列表同样被改
