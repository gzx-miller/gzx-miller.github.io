    <div class="llm-question"><strong>开场问题：</strong>「错得有多离谱」怎么变成一个可以比较的数？</div>

    <h2>提出问题</h2>
    <p>用「猜数字」游戏找感觉：我心想一个 1~100 的整数，你每报一次我只回「大了 / 小了」。就靠这一句反馈，你就把瞎猜变成了有方向的逼近。但神经网络的局面难得多：一次要调成千上万个参数、输出是一组<strong>概率</strong>而不是一个数，它怎么知道自己「大了还是小了」、每个参数该往哪个方向挪？</p>
    <p>这一课要造的，是给网络配一个<strong>损失（loss）</strong>：先把「这一次猜得有多差」压成<strong>一个数</strong>。有了它，梯度下降就能求出它对每个参数的导数，从而同时知道「方向」和「该使多大劲」。</p>

    <h2>最小方案</h2>
    <p>先用猜数字更简单的场景——预测<strong>数值</strong>。房价真实 300 万，网络给两个预测：A 是 299 万（差 1 万）、B 是 100 万（差 200 万）。我们不仅要「哪个更离谱」，还要知道离谱多少，因为梯度下降要靠<strong>可求导的数</strong>来更新权重。直接「预测值减真实值」会带正负号、难比较，于是取平方再来逐样本平均——这就是<strong>均方误差（MSE）</strong>：<code>MSE = (1/n)·Σ(ŷᵢ − yᵢ)²</code>。差 200 万会被平方放大成差 1 万的 4 万倍，大错惩罚更重。</p>
    <h3>真正推动训练的是导数，不是损失值</h3>
    <p>对单个样本把损失看成 <code>L(ŷ) = (ŷ − y)²</code>，对 <code>ŷ</code> 求导得 <code>dL/dŷ = 2(ŷ − y)</code>。念一遍就懂：导数 = 2 ×（预测 − 真实）。预测大了导数为正（往小收），预测小了为负（往大调），离得越远推得越狠。既处处可微、形式又简单，拿来就能用。MSE 适合回归。</p>

    <h2>发现不足</h2>
    <ul>
      <li>把 MSE 用在分类上：输出是 0~1 的概率（Sigmoid）。预测「有 90% 把握是苹果」的损失只有 0.01，而「只有 1% 把握」的损失是 0.98——可真正推动训练的是导数，照样 <code>2(p−1)</code>。</li>
      <li>网络从「1% 把握」掉到「0.1% 把握」明明错得更离谱，导数的绝对值却几乎不动（约 −1.98 → −1.998）——<strong>不管错得多狠，MSE 给的推力都差不多大</strong>！越离谱的错误得不到更强的纠正信号，训练会拖泥带水。</li>
    </ul>

    <h2>迭代</h2>
    <p>我们想要一个「<strong>越错，导数越大、推得越狠</strong>」的损失：正确类别的概率 <code>p</code> 在 <code>p = 1</code> 时损失为 0、<code>p → 0</code> 时趋向无穷大。答案就是——<strong>交叉熵（二分类时是 −log(p)）</strong>。有意思的是，第 6 课从信息论推过同一个公式；现在仅凭损失函数「该有的脾气」，竟然又把它找了回来——两条不同的路殊途同归。</p>
    <p>对正确类别的预测概率取负对数：<code>CE = −log p̂_c</code>。它的导数 <code>−1/p</code>：<code>p = 0.01</code> 时导数为 −100、<code>p = 0.001</code> 时是 −1000——错得越狠、推力越大还成倍放大，正好补上 MSE「最该用力时却封顶（最多到 −2）」的短板。当有 K 个类别时是 <code>CE = −Σ yₖ·log p̂ₖ</code>，只有正确那一项不为 0，本质上就是「对正确类别的 −log」。交叉熵配合下一课的 Softmax 输出，几乎是所有分类任务的默认损失。</p>

    <h2>总结</h2>
    <p>损失函数是梯度下降的「方向标」——它把「猜得有多差」变成一个可微的数，网络才知道每一步该往哪调。一句话：<strong>回归用 MSE（平方差）、分类用交叉熵（−log 概率）</strong>。MSE 对误差线性敏感；交叉熵对「极度自信的错误」指数级惩罚，梯度信号更强、分类收敛更快。</p>
    <div class="llm-term"><span class="term-name">「损失函数」</span>是指把一次预测的误差压成一个可比较、可求导的数的函数：回归用均方误差 MSE（平方差再平均），分类用交叉熵 ∝ −log(正确类别的概率)，后者让越离谱的错误得到越大的梯度推力，加速收敛。</div>
