    <div class="lesson-question">
      <strong>开场问题：</strong>一个逻辑简单的小接口压到几百并发就抛出 <code>too many connections</code> 拒连，可真正同时在跑的请求并没有那么多——那些「多出来」的连接，究竟是谁在替它们占着？
    </div>

    <h2>连接这件事，本来就很贵</h2>
    <p>
      你要写一个查课程列表的接口。可选的做法很多：直接拼一条 SQL 交给数据库，或者用对象的方式去读写，但无论哪一条路，都绕不开一个更底层的前提——<strong>你的代码得先和数据库「接上头」</strong>，而这件事远不是「调个函数」那么轻。
    </p>
    <p>
      建立一条数据库连接是有成本的：要完成 TCP 握手、身份认证、参数协商，数据库端还得为这条连接分配内存与服务端资源。最直接的做法是<strong>现用现连</strong>：在处理函数里 <code>await createConnection(...)</code>，执行完 SQL 就 <code>close()</code>，下个请求再从头来一遍。
    </p>
    <p>
      这个写法做对了一件事：<strong>连接管理最简单、最不容易出错</strong>——用一条开一条、用完就释放，不会被长期占住。请求量不大、接口不密集时，它完全跑得动。
    </p>

    <h2>并发有多少，连接就有多少</h2>
    <ul>
      <li>连接数直接等于并发数：几百个并发就是几百条连接，轻易越过数据库的 <code>max_connections</code>，于是报错拒连。</li>
      <li>每个请求都要重走握手与认证，这部分开销纯粹是重复劳动，白白拖慢每一次响应。</li>
      <li>连接建立失败或异常退出时忘了 <code>close</code>，连接就会泄漏；泄漏攒到上限，新的连接再也建不出来。</li>
      <li>短连接反复开开关关，对数据库自身也是一种额外的抖动压力。</li>
    </ul>
    <p>
      问题集中到一点：<strong>连接这么贵，怎么让大量请求共享有限条连接，而不是各自去开一条？</strong>
    </p>

    <h2>连接池：借出、使用、归还</h2>
    <p>
      不推翻「用连接」，而是把「开连接」从每个请求里挪出来，交给一个<strong>连接池</strong>统一管理。思路很朴素：<strong>预先建好一批连接放着，请求来了借一条用、用完还回去，而不是每次重新建</strong>。连接被反复复用，握手和认证只付一次，总数也被压在池子大小之内，不再随并发无限膨胀。
    </p>
    <ol class="lesson-steps">
      <li>进程启动时，连接池按配置建立若干条到数据库的连接，放进「空闲」集合。</li>
      <li>请求要访问数据库，先从池里取一条空闲连接；没有空闲的就在队列里等，直到有人归还或触发获取超时。</li>
      <li>执行完 SQL，连接<strong>归还</strong>给池子而不是真的关闭，留给下一个请求复用。</li>
      <li>池子负责剔除与重建坏连接，保证借出去的连接是可用的。</li>
    </ol>
    <p>
      那池子该开多大？这里有一条最容易记反的结论：<strong>并不是越大越好</strong>。数据库能承受的总连接数是有限的，而你的服务往往有多个实例、每个实例又各开一个池子，所以要核算的是「<strong>实例数乘每池连接数，不超过数据库可承受的上限</strong>」，而不是拍脑袋把 <code>max</code> 调大。池子过大，反而让数据库同时处理过多活跃连接、彼此争抢资源，吞吐不升反降。池大小要结合压测确定，并给「获取连接」设一个<strong>超时</strong>，免得池子耗尽时请求无限干等。
    </p>

    <h2>三个访问层次：原生 SQL、查询构建器、ORM</h2>
    <p>
      「怎么连」解决之后，还剩「怎么选访问方式」。数据库访问大致分三个层次：<strong>原生 SQL</strong> 最贴近数据库、最灵活，但要你自己防注入；<strong>查询构建器</strong>用代码链式拼 SQL，兼顾灵活与安全；<strong>ORM</strong> 提供对象映射、开发效率高，却会把执行细节和性能成本藏起来。取舍很实在：复杂查询偏原生 SQL 或查询构建器，以增删改查为主、追开发速度就上 ORM。
    </p>
    <div class="lesson-box warn">
      <strong>两个最容易出事的坑：</strong>其一，没有参数化的 SQL 就是注入的入口，<strong>无论用哪一层，变量都要走占位符</strong>，别用字符串拼接；其二，ORM 看着省心，却容易冒出 <strong>N+1 查询</strong>与隐式全表加载——循环里每访问一次关联字段就发一条查询，或把整张表的字段都拉回来。复杂、高频的查询应当<strong>回退到原生 SQL 并显式指定需要的字段</strong>。
    </div>

    <h2>迁移脚本与慢查询巡检</h2>
    <p>
      最后，表结构本身也需要版本管理。用<strong>迁移脚本</strong>描述每一次 Schema 变更，按时间戳或版本号顺序执行：<code>up</code> 应用变更、<code>down</code> 回滚变更，各环境的表结构才能保持一致、也随时可退。迁移脚本必须做到<strong>可重复执行、双向可用</strong>，并<strong>纳入部署流程自动执行</strong>；上线前在临时库上把「迁移到回滚」演练一遍，确认两个方向都没问题。
    </p>
    <p>
      再配上<strong>慢查询日志巡检</strong>：定期把耗时超阈值的语句捞出来看，缺索引、写法不合理的查询会在那里先露头，你就能赶在它变成线上报警之前先发现它。
    </p>

