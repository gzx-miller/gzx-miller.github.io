    <h2>地基式的连接复用</h2>
    <p>
      数据库访问的地基是连接复用：连接很贵，所以要用连接池把「借出、使用、归还」循环起来，把连接总数压在池子大小之内，池子大小再按「实例数乘以每池连接数」去核对数据库上限。在此之上按场景挑数据访问层——复杂查询用原生 SQL 或查询构建器、CRUD 用 ORM，表结构变更交给可回滚的迁移脚本。
    </p>
    <div class="lesson-term">
      <span class="term-name">「连接池」</span>数据库连接的建立成本高（握手、认证、分配资源），连接池预先维持一组连接供请求<strong>借用与归还</strong>，而非每次新建，从而复用开销并把并发连接数限制在池大小内。池大小应满足「<strong>实例数乘以每池连接数，不超过数据库连接上限</strong>」，并非越大越好，还需为获取连接设置超时。注意：参数化查询在任何一层都要用；ORM 易引发 N+1 查询，复杂查询宜回退原生 SQL 并显式指定字段；表结构变更由可双向执行的迁移脚本管理。
