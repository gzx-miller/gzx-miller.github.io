    <h2>昂贵的连接资源</h2>
    <p>
      你要给用户查课程列表。有两种写法可选：直接拼一条 SQL 交给数据库执行，或者用 ORM 以对象的方式去读写。但无论选哪一种，都绕不开一个更底层的前提——<strong>你的代码得先跟数据库「接上头」</strong>，而这件事远不是「调个函数」那么简单。
    </p>
    <p>
      建立一条数据库连接是有成本的：要完成 TCP 握手、认证、协商参数，数据库还要为这条连接分配内存和服务端资源。如果你对每个请求都<strong>新建一条连接、用完就关</strong>，那么高峰期连接数会随并发一起飙升，很快撞上数据库的连接上限，触发开场那句报错。麻烦还不止于此：建立连接本身耗时，会让每个请求的响应都慢上一截。所以这里有一个必须回答的问题：<strong>连接这么贵，怎么让大量请求共享有限的连接，而不是各自去开一条？</strong>
    </p>

    <h2>按请求即时建连</h2>
    <p>
      最直接的做法：在处理函数里现用现连——<code>const conn = await createConnection(...)</code>，执行完 SQL 就 <code>conn.close()</code>，下个请求再从头连一次。
    </p>
    <p>
      这个方案做对了一件事：<strong>它的连接管理最简单、最不容易出错</strong>——用一条开一条、用完就释放，不会出现连接被长期占住的情况。请求量小、接口不密集时，这样写完全能跑。
    </p>

    <h2>并发与连接数等量</h2>
    <ul>
      <li>连接数等于并发数：几百个并发就是几百条连接，轻易超过数据库的 <code>max_connections</code>，直接报错拒连。</li>
      <li>每个请求都要重走一遍握手与认证，这部分开销纯粹是重复劳动，白白拖慢响应。</li>
      <li>连接建立失败或异常退出时，忘记 <code>close</code> 就会泄漏，泄漏积累到上限后，新的连接再也建不出来。</li>
      <li>短连接频繁地开开关关，对数据库本身也是一种额外的抖动压力。</li>
    </ul>

    <h2>连接池的复用</h2>
    <p>
      不推翻「用连接」，而是把「开连接」这件事从每个请求里挪出来，交给一个<strong>连接池</strong>统一管理。池子的思路很朴素：<strong>预先建一批连接放着，请求来了就借一条来用、用完还回去，而不是每次重新建</strong>。连接被反复复用，握手和认证的开销只付一次，连接总数也被固定在池子大小之内，不再随并发无限膨胀。
    </p>
    <ol class="lesson-steps">
      <li>进程启动时，连接池按配置建立若干条到数据库的连接，放进「空闲连接」集合。</li>
      <li>请求需要访问数据库，先从池里取一条空闲连接；没有空闲的就在队列里等，直到有人归还或触发获取超时。</li>
      <li>执行完 SQL，连接<strong>归还</strong>给池子（而不是真的关闭），供下一个请求复用。</li>
      <li>池子负责坏连接的剔除与重建，保证借出去的连接是可用的。</li>
    </ol>
    <p>
      那池子该开多大？这里有一条最容易记反的结论：<strong>连接池不是越大越好</strong>。数据库能承受的总连接数是有限的，而你的服务往往有多个实例，每个实例又会开一个池子。核算时要看的是「实例数乘以每池连接数，不超过数据库可承受的连接上限」，而不是拍脑袋把池子调大。池子设得过大，反而会让数据库同时处理过多活跃连接、彼此争抢资源，吞吐不升反降。池大小要结合实际压测确定，并为「获取连接」设一个超时，避免请求在池子耗尽时无限等待。
    </p>
    <p>
      到这一步，「怎么连」解决了，还剩「怎么选访问方式」。数据库访问其实分三个层次：<strong>原生 SQL</strong> 最贴近数据库、灵活，但需要你自己防注入；<strong>查询构建器</strong>用代码链式拼 SQL，兼顾灵活与安全；<strong>ORM</strong> 提供对象映射、开发效率高，却会隐藏执行细节和性能成本。选择原则很实在：复杂查询偏原生 SQL 或查询构建器，以增删改查为主、追求开发速度就上 ORM。
    </p>
    <div class="lesson-box warn">
      <strong>两个最容易出事的坑：</strong>其一，没有参数化的 SQL 就是注入的入口，无论用哪一层，变量都要走占位符；其二，ORM 看似省心，却容易产生 <strong>N+1 查询</strong>与隐式全表加载——循环里每访问一次关联字段就发一条查询，复杂或高频的查询应当回退到原生 SQL 并<strong>显式指定需要的字段</strong>。
    </div>
    <p>
      最后，表结构本身也需要版本管理。用<strong>迁移脚本</strong>描述每一次 Schema 变更，按时间戳或版本号顺序执行：<code>up</code> 应用变更、<code>down</code> 回滚变更，这样各环境的表结构才能保持一致、且随时可退。迁移脚本要做到可重复执行、双向可用，并纳入部署流程自动执行；上线前在临时库上演练一次「迁移到回滚」，确认两个方向都没问题。再配合慢查询日志定期巡检，你就能在问题变成线上报警之前先发现它。
    </p>

