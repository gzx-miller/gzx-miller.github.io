      <strong>开场问题：</strong>你跟客服机器人说「我叫小明，帮我查下订单」，它答得头头是道。又聊了几轮，你随口问「我叫什么名字」，它却回「抱歉，我不知道你的名字」——明明上一轮它还叫过你的名字，怎么转眼就忘了？
    </div>

    <h2>提出问题</h2>
    <p>
      原因不在模型记性差，而在于<strong>每一次调用都是无状态的</strong>：你发什么，它就只看什么，之前聊过什么它完全不知道。它每次都是从零开始，你上一句说的「小明」，在它这次看到的内容里根本不存在。
    </p>
    <p>
      坚持「不管历史、每轮独立」，三笔成本都得分摊给用户和你。
    </p>
    <ol class="lesson-steps">
      <li><strong>用户被迫重复背景</strong>：每轮都得再说一遍「我是谁、我前面问了什么」，体验极差。</li>
      <li><strong>历史得手工拼</strong>：想让它记住，就得自己在前端把过往对话拼成一段文本塞进提示词，格式各家各样，全是维护负担。</li>
      <li><strong>迟早撑爆上下文</strong>：历史越攒越长，总有一天超过模型的 token 上限，而「该丢哪一段」全凭手感，没有规则。</li>
    </ol>
    <p>
      要回答的是：<strong>怎么让模型「看得见」之前的对话，同时又不让它被越攒越长的历史压垮？</strong>
    </p>

    <h2>最小方案</h2>
    <p>
      最朴素的做法：把之前所有对话原样拼成一大段文本，塞在本次提问的前面，一起发给模型。
    </p>
    <p>
      这个方案做对了一件事：<strong>它让模型这一次「看得见」历史</strong>。历史不再是模型之外的东西，而是变成了输入的一部分——只要它在你发过去的文本里，模型就真的能读到。
    </p>

    <h2>发现不足</h2>
    <ul>
      <li>轮数一多，拼出来的文本越来越长，很快就会顶到 token 上限，成本跟着一路飙升。</li>
      <li>全拼成一段纯文本，模型分不清哪句是人说的、哪句是它自己说的，「你」「我」的指代整个乱套。</li>
      <li>越早说的话，越容易被后面的大段内容淹没；模型其实「读过」，但用不上。</li>
      <li>拼接的格式全靠手工维护，换个分隔符、漏个换行，行为就悄悄变了，还很难查。</li>
    </ul>

    <h2>迭代</h2>
    <p>
      不推翻「把历史喂给模型」，而是换一种喂法。第一步补<strong>结构化</strong>：把历史从「一段字符串」升级成「一串带角色的消息」。用 <code>ChatMessageHistory</code> 把每条消息连同角色（human / ai / system）一起存下来；再在提示词模板里用一个占位符 <code>MessagesPlaceholder</code> 预留「历史该插在哪」的位置，运行时把消息数组填进去。先补它，是因为它治好了「分不清谁在说话」的毛病——角色是结构，不是靠文字去猜的。
    </p>
    <p>
      第二步补<strong>滑动窗口</strong>：历史太长时，只取最近 k 轮（k 轮就是 2k 条消息）参与本次请求，更早的直接丢掉。它牺牲的是久远的记忆，换来的是「永远不超上下文、成本可预期」。
    </p>
    <p>
      第三步补<strong>摘要</strong>：如果早期信息也重要、不能一丢了之，就额外调一次模型，把旧历史压缩成一段摘要，用这段摘要替掉原始的多轮消息。它用「细节」换「空间」，让很久远的信息以浓缩的形式继续留在上下文里——这是窗口丢掉的东西的一种补偿。
    </p>
    <p>
      最后补<strong>按会话自动管理</strong>：用 <code>RunnableWithMessageHistory</code> 把链包住，传入一个按 <code>sessionId</code> 取历史的函数；之后每次调用只要在 <code>configurable</code> 里带上 <code>sessionId</code>，它就会自动注入该会话的历史，并在结束后把新一轮问答写回。生产环境里，把这层存储从内存换成 Redis 或数据库，会话才能跨重启保住。
    </p>
    <div class="lesson-box warn">
      <strong>三种策略不是三选一，而是同一条时间轴上的搭配：</strong>窗口负责「最近说了什么」，摘要负责「更早大概聊过什么」，完整历史只在对话很短时才用得起。另外，摘要记忆不是免费的——每生成一次摘要都要多调一次模型，多出来的延迟和成本必须算进预算。
    </div>

