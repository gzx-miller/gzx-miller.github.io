    <div class="llm-question"><strong>开场问题：</strong>同样是 Transformer，BERT 为什么不能生成文章，GPT 为什么是主流？</div>

    <h2>提出问题</h2>
    <p>上几课搭出了一块通用积木——Transformer Block。可真正拿它干活时，语言任务大致只有两大类、工作方式差别很大：</p>
    <ul>
      <li><strong>理解</strong>：给模型一句话让它读懂再给判断，比如「这部电影真的让我很失望」→ 负面。像阅读理解的题，<strong>整句读完了才能下结论</strong>。</li>
      <li><strong>生成</strong>：给个开头让它接着写，比如「从前有一只小猫，它每天最喜欢做的事就是」→ 一个词一个词续写。像接龙，<strong>只能根据已经写出来的决定下一个词</strong>。</li>
    </ul>
    <div class="llm-box warn">
      <strong>关键参照物</strong>：说「前后左右」，参照物不是整句话，而是<strong>当前正在处理的那个位置</strong>。在「猫 / 追 / 球」里，若当前处理中间「追」这个位置：「前后都看」是它既能看左边「猫」也能看右边「球」；「只能往左看」是它只能看左边已出现内容、不能看右边未来内容。所以<b>编码器和解码器的差别，不是整句层面不同，而是「当前位置能看见哪些位置」不同</b>。
    </div>

    <h2>两个名字其实很好懂</h2>
    <p>模型做<strong>理解</strong>时，把一句自然语言读进去变成内部一排表示（如「这部电影很无聊」揉进了「谁修饰谁」「情绪偏负面」）——像把原始文字<strong>编码</strong>成机器内部更好用的形式，所以叫<strong>编码器（Encoder）</strong>。做<strong>生成</strong>时方向反过来，把内部表示一步步<strong>还原成文字</strong>、一个词一个词往外吐——像把表示解回自然语言，所以叫<strong>解码器（Decoder）</strong>。一句话记法：<strong>编码器像「先把一句话读懂」，解码器像「根据已有内容继续往下写」</strong>。</p>

    <h2>编码器：整句一起看，任务是「读懂」</h2>
    <p>编码器最重要的特点只有一句话：<strong>对句子里的每个位置，都允许它看见整句所有位置</strong>——没有遮挡，左边右边都能看。很适合理解类任务：判断情感时，某个位置常常同时需要参考左边和右边（前面「本来我很期待」、后面「结果非常失望」，整句语义就翻了）。它的输出不是「下一个词」，而是<strong>每个位置一个已融入上下文的向量</strong>——可以理解成每个位置都做了一份「读后笔记」。</p>
    <p>代表模型是 <strong>BERT</strong>，训练方式也符合这个定位：不是续写，而是<strong>完形填空</strong>——把「巴黎是法国的 [MASK]」挖掉一个词，让它同时利用左右两边猜回来。所以 BERT 擅长「读懂一句话后做判断」，但不擅长一个词一个词写文章，因为它压根不是按那个方向训练出来的。</p>

    <h2>解码器：蒙住未来，任务是「往下写」</h2>
    <p>解码器和编码器的 block 长得差不多，差别在注意力的规矩上：<strong>当前这个位置不能看右边未来的位置</strong>（掩码）。为什么必须这样？解码器是拿来生成的，假设要续写「它最爱晒太阳」：处理第 1 个位置只能根据输入猜「它」，处理第 2 个位置只能看见左边「它」再猜「最」，第 3 个位置只能看见「它 最」再猜「爱」……否则训练时它会直接偷看标准答案。</p>
    <p>这个「当前位置只能根据左边内容预测下一个词」的训练目标，正是 <strong>GPT</strong> 这类模型的核心。它还有个漂亮的工程点：训练时虽然逻辑上是「一个个往后猜」，但整句都喂进去了，模型能在<strong>一次前向计算里同时算出每个位置的预测题</strong>——既遵守单向规则、又能并行训练。所以 GPT 擅长写作、对话、代码续写，因为它从出生起训练目标就是「继续往下写」。</p>

    <h2>现在看三种结构，就不会乱了</h2>
    <ul>
      <li><strong>只有编码器</strong>：适合「先读懂，再判断」，代表 BERT。</li>
      <li><strong>只有解码器</strong>：适合「给个开头，继续往下写」，代表 GPT。</li>
      <li><strong>编码器 + 解码器</strong>：适合「先把输入读懂，再根据它生成输出」，代表原始 Transformer、T5。最通俗的理解是<strong>编码器先负责读题，解码器再负责答题</strong>——翻译时编码器把中文整句读懂，解码器再据此一个词一个词写英文（用交叉注意力回头查编码器已读懂的输入）。</li>
    </ul>

    <h2>为什么今天的大模型几乎都偏爱解码器</h2>
    <p>核心原因很简单：<strong>「生成」非常统一，很多任务都能改写成续写问题</strong>。情感分析可改写为「答：负面」；翻译改写为「把…翻成英文：#」；问答改写为「法国的首都是：巴黎」；写代码本身就是续写。很多看似不同的任务，最后都能塞进「给你一段上下文，你把后面补出来」这个统一框架——用一套纯解码器架构、一个训练目标，就能覆盖大部分任务。</p>
    <p>顺带还带来一个强能力：把「根据前文继续往下写」练到极致后，模型会顺便学会——<strong>你只要在提示里先给它几个例子，它就能照例子格式继续做下去</strong>，这就是<strong>上下文学习</strong>。今天我们写 prompt、给 few-shot 示例，本质都在利用它。所以不是编码器没用，而是<strong>纯解码器太通用了</strong>——足够统一、足够简单、又足够适合大规模预训练。</p>

    <h2>总结</h2>
    <p>编码器「先把整句读懂」、双向、适合理解；解码器「根据已有内容往下写」、遮住未来、适合生成。只用编码器是 BERT，只用解码器是 GPT，两者合起来是「先理解再生成」的编码器-解码器结构。根本差别全落在「当前位置能看见哪些位置」。今天多用解码器，是因为很多任务都能统一改写为「续写」。</p>
    <div class="llm-term"><span class="term-name">「编码器与解码器」</span>是指在 Transformer 里按「当前位置能否看右边」区分的两种形态：双向（左右都能看）的编码器负责把整句读懂成读后笔记，适合理解任务（BERT）；单向（遮住未来、自回归猜下一个词）的解码器负责一个词一个词续写，适合生成任务（GPT、Claude）；纯解码器因能统一改写各类任务而成为主流。</div>
