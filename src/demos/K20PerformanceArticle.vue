    <h2>性能优化本质</h2>
    <p>
      性能优化的本质，是把「不必要的计算、不必要的渲染、不必要的节点」一层层减掉：<code>computed</code> 管住计算，<code>v-memo</code> 管住渲染，分页与虚拟滚动管住节点数量。而这一切的前提是先测量——先确认瓶颈，再选手段，效率和复杂度才都不会失控。
    </p>
    <div class="lesson-term">
      <span class="term-name">「按需计算与按需渲染」</span>是 Vue 里两条互补的优化主线：<code>computed</code> 基于依赖缓存派生结果，依赖不变就不重算；<code>v-memo</code> 在依赖数组未变化时跳过子树重渲染。数据量真正变大时，还要靠分页、虚拟滚动或后端过滤减少 DOM 节点本身。所有手段都应建立在测量之上，并以生产构建的表现为准。
