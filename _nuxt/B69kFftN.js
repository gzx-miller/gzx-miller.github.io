const n=`import numpy as np

# 矩阵就是“多组权重”排成的一张表；Wx 即每行与 x 做点积
W = np.array([[0.2, 0.8],     # 第 1 个输出神经元：0.2*[0] + 0.8*[1]
              [0.9, 0.1],     # 第 2 个输出神经元
              [0.5, 0.5]])    # 第 3 个输出神经元
x = np.array([3, 1])          # 输入向量

out = W @ x
print(out)        # [1.4 2.8 2.0]
# 维度规则：矩阵列数 = 输入维，矩阵行数 = 输出维，内层匹配外层定`;export{n as default};
